//! GraphQL target（M10）：Program → schema.graphql + 可运行的 graphql-yoga resolver 网关。
//!
//! 定位：以 DSL 为唯一事实来源，导出**规范 GraphQL 契约**（schema.graphql / typeDefs），
//! resolver 层委托到 REST 后端（`REST_BASE` 环境变量），因此**与任意后端 target 解耦**
//! （Rust/axum、NestJS、Hono、FastAPI 皆可前置）。
//!
//! v1 范围：
//! - 枚举 / 实体类型 / Create·Update Input / Query / Mutation；
//! - 正向对象关系（`owner: User`，resolver 按 `{rel}_id` 拉取——GraphQL 惯用形态）；
//! - **逆向关系（v2，`User.items`）**：按源实体 REST list 单批拉取 + DataLoader
//!   按 `{rel}_id` 分组（一次请求服务整批父对象，避免 N+1）。
//! - 安全语义（auth/access/tenant）由 REST 后端权威执行；网关透传 token。

use crate::dsl::{is_relation, pluralize, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

pub fn emit_graphql(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() || program.apis.is_empty() {
        return Ok(vec![]);
    }
    let mut files: Vec<GeneratedFile> = Vec::new();
    let sdl = schema_graphql(program);
    files.push(file(out_dir, "schema.graphql", sdl.clone()));
    files.push(file(out_dir, "src/schema.ts", schema_ts(&sdl)));
    files.push(file(out_dir, "src/rest.ts", rest_ts(program)));
    files.push(file(out_dir, "src/resolvers.ts", resolvers_ts(program)));
    files.push(file(out_dir, "src/loaders.ts", loaders_ts(program)));
    files.push(file(out_dir, "src/server.ts", server_ts()));
    files.push(file(
        out_dir,
        "src/types.ts",
        crate::emit::web_react::types_ts(program),
    ));
    files.push(file(out_dir, "package.json", package_json(app_name)));
    files.push(file(out_dir, "tsconfig.json", tsconfig()));
    files.push(file(
        out_dir,
        "README.md",
        format!(
            "{}{}",
            crate::emit::generated_md_header("gen-graphql"),
            readme(app_name)
        ),
    ));

    for f in &files {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(files)
}

fn file(out: &str, rel: &str, content: String) -> GeneratedFile {
    GeneratedFile {
        path: format!("{out}/{rel}"),
        content,
        generator: "gen-graphql".into(),
    }
}

/// DSL 标量类型 → GraphQL 类型名（枚举/实体名由调用方直接用 type_name）。
fn gql_scalar_type(type_name: &str) -> Option<&'static str> {
    match type_name {
        "Uuid" => Some("ID"),
        "String" | "Text" | "Email" => Some("String"),
        "Int" => Some("Int"),
        "Float" => Some("Float"),
        // 后端把 Decimal 序列化为字符串（spec:types）——GraphQL 侧同形，
        // 精度要求场景由客户端用 Decimal 库解析。
        "Decimal" => Some("String"),
        "Bool" => Some("Boolean"),
        "Timestamp" | "Date" => Some("String"),
        "Json" => Some("JSON"),
        _ => None,
    }
}

/// 字段类型：标量 → 映射名；枚举/关系 → 类型名本身。
fn gql_field_type(_program: &Program, type_name: &str) -> String {
    if let Some(g) = gql_scalar_type(type_name) {
        return g.to_string();
    }
    type_name.to_string()
}

/// 逆向关系：`Source.target` → `Target.<plural_sources>`（A-4 / v2）。
#[derive(Debug, Clone)]
struct ReverseRel {
    /// 承载逆向字段的实体（关系目标）
    target: String,
    /// GraphQL 字段名（源实体复数 snake_case）
    field: String,
    /// 源实体
    source: String,
    /// REST 响应中的外键列名（`{rel}_id`）
    fk_col: String,
    /// loaders 对象键
    loader_key: String,
}

fn reverse_rels(program: &Program) -> Vec<ReverseRel> {
    use std::collections::BTreeSet;
    let mut out = Vec::new();
    let mut used: BTreeSet<(String, String)> = BTreeSet::new();
    for src in &program.entities {
        for f in src
            .fields
            .iter()
            .filter(|f| is_relation(program, &f.type_name))
        {
            let target = f.type_name.clone();
            if !program.entities.iter().any(|e| e.name == target) {
                continue;
            }
            let mut field = to_snake_case(&pluralize(&src.name));
            // 同名冲突（多个源实体指向同一目标且复数同名）→ 拼上源实体名消歧
            if used.contains(&(target.clone(), field.clone())) {
                field = format!("{}_{}", to_snake_case(&src.name), field);
            }
            used.insert((target.clone(), field.clone()));
            out.push(ReverseRel {
                loader_key: format!("{}_{}", to_snake_case(&target), field),
                target,
                field,
                source: src.name.clone(),
                fk_col: format!("{}_id", to_snake_case(&f.name)),
            });
        }
    }
    out
}

/// SDL 主体（schema.graphql 与 src/schema.ts 共用同一份文本）。
fn schema_graphql(program: &Program) -> String {
    let mut s = String::new();
    let rev = reverse_rels(program);
    s.push_str("# @generated by Forma (gen-graphql) — do not edit manually.\n");
    s.push_str("# Decimal 以 String 传输（后端序列化契约）；JSON 为自定义标量。\n\n");
    if program
        .entities
        .iter()
        .any(|e| e.fields.iter().any(|f| f.type_name == "Json"))
    {
        s.push_str("scalar JSON\n\n");
    }
    // 枚举
    for e in &program.enums {
        s.push_str("enum ");
        s.push_str(&e.name);
        s.push_str(" {\n");
        for v in &e.variants {
            s.push_str("  ");
            s.push_str(&v.name);
            s.push('\n');
        }
        s.push_str("}\n\n");
    }
    // 实体类型（正向对象关系 + 标量）
    for entity in &program.entities {
        s.push_str("type ");
        s.push_str(&entity.name);
        s.push_str(" {\n");
        for f in &entity.fields {
            let nullable = f.optional;
            let snake = to_snake_case(&f.name);
            if is_relation(program, &f.type_name) {
                // 关系列：{rel}_id 标量 + 对象字段（resolver 拉取）
                s.push_str("  ");
                s.push_str(&format!("{snake}Id: ID"));
                if !nullable {
                    s.push('!');
                }
                s.push('\n');
                s.push_str("  ");
                s.push_str(&snake);
                s.push_str(": ");
                s.push_str(&f.type_name);
                if !nullable {
                    s.push('!');
                }
                s.push('\n');
            } else {
                let gql = gql_field_type(program, &f.type_name);
                s.push_str("  ");
                s.push_str(&snake);
                s.push_str(": ");
                s.push_str(&gql);
                if !nullable {
                    s.push('!');
                }
                s.push('\n');
            }
        }
        // 逆向关系（A-4）：非空列表，无匹配行返回 []
        for r in rev.iter().filter(|r| r.target == entity.name) {
            s.push_str("  ");
            s.push_str(&r.field);
            s.push_str("(page: Int, pageSize: Int): [");
            s.push_str(&r.source);
            s.push_str("!]!\n");
        }
        s.push_str("}\n\n");
    }
    // Input 类型
    for entity in &program.entities {
        s.push_str("input Create");
        s.push_str(&entity.name);
        s.push_str("Input {\n");
        for f in &entity.fields {
            if is_relation(program, &f.type_name) {
                let snake = to_snake_case(&f.name);
                let required = !f.optional && crate::dsl::has_attr(f, "required");
                s.push_str("  ");
                s.push_str(&format!("{snake}Id: ID"));
                if required {
                    s.push('!');
                }
                s.push('\n');
                continue;
            }
            if crate::dsl::has_attr(f, "readonly") || crate::dsl::has_attr(f, "id") {
                continue;
            }
            let gql = gql_field_type(program, &f.type_name);
            let required = !f.optional && crate::dsl::has_attr(f, "required");
            s.push_str("  ");
            s.push_str(&to_snake_case(&f.name));
            s.push_str(": ");
            s.push_str(&gql);
            if required {
                s.push('!');
            }
            s.push('\n');
        }
        s.push_str("}\n\n");
        s.push_str("input Update");
        s.push_str(&entity.name);
        s.push_str("Input {\n");
        for f in &entity.fields {
            if is_relation(program, &f.type_name) {
                let snake = to_snake_case(&f.name);
                s.push_str("  ");
                s.push_str(&format!("{snake}Id: ID"));
                s.push('\n');
                continue;
            }
            if crate::dsl::has_attr(f, "readonly") || crate::dsl::has_attr(f, "id") {
                continue;
            }
            let gql = gql_field_type(program, &f.type_name);
            s.push_str("  ");
            s.push_str(&to_snake_case(&f.name));
            s.push_str(": ");
            s.push_str(&gql);
            s.push('\n');
        }
        s.push_str("}\n\n");
    }
    // Query / Mutation（按 api 声明生成）
    let has_query = program
        .apis
        .iter()
        .any(|a| a.operations.iter().any(|o| o == "list" || o == "get"));
    let has_mutation = program.apis.iter().any(|a| {
        a.operations
            .iter()
            .any(|o| o == "create" || o == "update" || o == "delete")
    });
    if has_query {
        s.push_str("type Query {\n");
        for api in &program.apis {
            let Some(entity) = program.entities.iter().find(|e| e.name == api.entity) else {
                continue;
            };
            let plural_snake = to_snake_case(&pluralize(&entity.name));
            let single_snake = to_snake_case(&entity.name);
            for op in &api.operations {
                match op.as_str() {
                    "list" => {
                        s.push_str("  ");
                        s.push_str(&plural_snake);
                        s.push_str("(page: Int, pageSize: Int, q: String): [");
                        s.push_str(&entity.name);
                        s.push_str("!]!\n");
                    }
                    "get" => {
                        s.push_str("  ");
                        s.push_str(&single_snake);
                        s.push_str("(id: ID!): ");
                        s.push_str(&entity.name);
                        s.push('\n');
                    }
                    _ => {}
                }
            }
        }
        s.push_str("}\n\n");
    }
    if has_mutation {
        s.push_str("type Mutation {\n");
        for api in &program.apis {
            let Some(entity) = program.entities.iter().find(|e| e.name == api.entity) else {
                continue;
            };
            for op in &api.operations {
                match op.as_str() {
                    "create" => {
                        s.push_str("  create");
                        s.push_str(&entity.name);
                        s.push_str("(input: Create");
                        s.push_str(&entity.name);
                        s.push_str("Input!): ");
                        s.push_str(&entity.name);
                        s.push_str("!\n");
                    }
                    "update" => {
                        s.push_str("  update");
                        s.push_str(&entity.name);
                        s.push_str("(id: ID!, input: Update");
                        s.push_str(&entity.name);
                        s.push_str("Input!): ");
                        s.push_str(&entity.name);
                        s.push_str("!\n");
                    }
                    "delete" => {
                        s.push_str("  delete");
                        s.push_str(&entity.name);
                        s.push_str("(id: ID!): Boolean!\n");
                    }
                    _ => {}
                }
            }
        }
        s.push_str("}\n");
    }
    s
}

/// 把 SDL 作为 typeDefs 常量（避免 .graphql 导入需要额外 loader）。
fn schema_ts(sdl: &str) -> String {
    let mut s = String::from("// @generated by Forma (gen-graphql) — do not edit manually.\n");
    s.push_str(
        "// SDL 与 schema.graphql 同源（构建期生成两份：文档用 .graphql，运行时用本文件）。\n",
    );
    s.push_str("export const typeDefs = /* GraphQL */ `\n");
    s.push_str(sdl);
    s.push_str("`;\n");
    s
}

/// 服务端 REST 客户端：resolvers 的数据来源。REST_BASE 环境变量可覆盖。
fn rest_ts(program: &Program) -> String {
    let mut s = String::new();
    s.push_str("// @generated by Forma (gen-graphql) — do not edit manually.\n");
    s.push_str("// resolver 层的数据来源：REST 后端（任意 Forma 后端 target 均可）。\n");
    s.push_str("// REST_BASE 环境变量指定后端地址（默认 http://localhost:8080）；GRAPHQL_TOKEN 透传 bearer。\n\n");
    let mut type_imports: Vec<String> = Vec::new();
    for entity in &program.entities {
        type_imports.push(entity.name.clone());
    }
    s.push_str("import { ");
    s.push_str(&type_imports.join(", "));
    s.push_str(" } from \"./types\";\n\n");
    s.push_str("const base = process.env.REST_BASE ?? \"http://localhost:8080\";\n\n");
    s.push_str("let token: string | null = process.env.GRAPHQL_TOKEN ?? null;\n\n");
    s.push_str("export function setRestToken(t: string | null) {\n  token = t;\n}\n\n");
    s.push_str("async function req<T>(path: string, init?: RequestInit): Promise<T> {\n");
    s.push_str("  const headers: Record<string, string> = { \"Content-Type\": \"application/json\", ...(init?.headers as Record<string, string> | undefined) };\n");
    s.push_str("  if (token) headers[\"Authorization\"] = `Bearer ${token}`;\n");
    s.push_str("  const res = await fetch(`${base}${path}`, { ...init, headers });\n");
    s.push_str("  if (!res.ok) {\n    const body = await res.json().catch(() => ({}) as any);\n    const err = new Error(body.error ?? res.statusText) as any;\n    err.status = res.status;\n    err.code = body.code;\n    err.extensions = { code: body.code, status: res.status };\n    throw err;\n  }\n");
    s.push_str("  if (res.status === 204) return undefined as T;\n  return res.json() as Promise<T>;\n}\n\n");
    s.push_str("function qs(params: Record<string, unknown>): string {\n");
    s.push_str("  const usp = new URLSearchParams();\n");
    s.push_str("  for (const [k, v] of Object.entries(params)) {\n    if (v === null || v === undefined || v === \"\") continue;\n    usp.set(k, String(v));\n  }\n  const str = usp.toString();\n  return str ? `?${str}` : \"\";\n}\n\n");
    for entity in &program.entities {
        let name = &entity.name;
        let plural = to_snake_case(&pluralize(name));
        s.push_str("export const ");
        s.push_str(name);
        s.push_str("Api = {\n");
        s.push_str("  list: (p: Record<string, unknown> = {}) =>\n    req<");
        s.push_str(name);
        s.push_str("[]>(`/api/");
        s.push_str(&plural);
        s.push_str("${qs(p)}`),\n");
        s.push_str("  get: (id: string) => req<");
        s.push_str(name);
        s.push_str(">(`/api/");
        s.push_str(&plural);
        s.push_str("/${id}`),\n");
        s.push_str("  create: (input: unknown) => req<");
        s.push_str(name);
        s.push_str(">(`/api/");
        s.push_str(&plural);
        s.push_str("`, { method: \"POST\", body: JSON.stringify(input) }),\n");
        s.push_str("  update: (id: string, input: unknown) => req<");
        s.push_str(name);
        s.push_str(">(`/api/");
        s.push_str(&plural);
        s.push_str("/${id}`, { method: \"PUT\", body: JSON.stringify(input) }),\n");
        s.push_str("  remove: (id: string) => req<{ ok: boolean }>(`/api/");
        s.push_str(&plural);
        s.push_str("/${id}`, { method: \"DELETE\" }),\n};\n\n");
    }
    s
}

/// DataLoader：逆向关系按 `{rel}_id` 分组，一批父对象只发一次 REST list 请求（A-4）。
fn loaders_ts(program: &Program) -> String {
    let rev = reverse_rels(program);
    let mut s = String::new();
    s.push_str("// @generated by Forma (gen-graphql) — do not edit manually.\n");
    s.push_str("// 逆向关系批加载：整批父 id → 单次 REST list → 内存按外键分组（避免 N+1）。\n");
    s.push_str(
        "// 边界：单次最多取 FORMA_GRAPHQL_REVERSE_BATCH 行（缺省 1000），超出需人工分页。\n\n",
    );
    if rev.is_empty() {
        s.push_str("// 本工程无逆向关系。\nexport function createLoaders() {\n  return {};\n}\n");
        return s;
    }
    s.push_str("import DataLoader from \"dataloader\";\n");
    let apis: Vec<String> = rev
        .iter()
        .map(|r| format!("{}Api", r.source))
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect();
    s.push_str(&format!(
        "import {{ {} }} from \"./rest\";\n\n",
        apis.join(", ")
    ));
    s.push_str("const batchSize = Number(process.env.FORMA_GRAPHQL_REVERSE_BATCH ?? 1000);\n\n");
    s.push_str("function unwrap(v: unknown): any[] {\n");
    s.push_str("  if (Array.isArray(v)) return v as any[];\n");
    s.push_str("  if (v && typeof v === \"object\" && Array.isArray((v as any).items)) return (v as any).items;\n");
    s.push_str("  return [];\n}\n\n");
    s.push_str("export function createLoaders() {\n  return {\n");
    for r in &rev {
        s.push_str(&format!(
            "    {}: new DataLoader<string, any[]>(async (ids) => {{\n",
            r.loader_key
        ));
        s.push_str(&format!(
            "      const rows = unwrap(await {}Api.list({{ pageSize: batchSize }}));\n",
            r.source
        ));
        s.push_str("      const grouped = new Map<string, any[]>();\n");
        s.push_str("      for (const key of ids) grouped.set(String(key), []);\n");
        s.push_str("      for (const row of rows) {\n");
        s.push_str(&format!(
            "        const fk = String((row as any)[\"{}\"] ?? \"\");\n",
            r.fk_col
        ));
        s.push_str("        const bucket = grouped.get(fk);\n");
        s.push_str("        if (bucket) bucket.push(row);\n");
        s.push_str("      }\n");
        s.push_str("      return ids.map((id) => grouped.get(String(id)) ?? []);\n");
        s.push_str("    }),\n");
    }
    s.push_str("  };\n}\n");
    s
}

/// Resolvers：Query/Mutation 委托 REST；正向对象关系按 {rel}_id 拉取；
/// 逆向关系走每请求 DataLoader（ctx.loaders）。
fn resolvers_ts(program: &Program) -> String {
    let mut s = String::new();
    s.push_str("// @generated by Forma (gen-graphql) — do not edit manually.\n");
    s.push_str("// 安全语义（auth/access/tenant）由 REST 后端权威执行；网关只透传 token。\n\n");
    // imports：每实体一个 {Entity}Api
    let mut import_parts: Vec<String> = Vec::new();
    for entity in &program.entities {
        import_parts.push(format!("{}Api", entity.name));
    }
    s.push_str("import { ");
    s.push_str(&import_parts.join(", "));
    s.push_str(" } from \"./rest\";\n\n");
    // Query / Mutation
    s.push_str("export const resolvers = {\n");
    s.push_str("  Query: {\n");
    for api in &program.apis {
        let Some(entity) = program.entities.iter().find(|e| e.name == api.entity) else {
            continue;
        };
        let plural_snake = to_snake_case(&pluralize(&entity.name));
        let single_snake = to_snake_case(&entity.name);
        for op in &api.operations {
            match op.as_str() {
                "list" => {
                    s.push_str("    ");
                    s.push_str(&plural_snake);
                    s.push_str(": (_p: unknown, args: Record<string, unknown>) => ");
                    s.push_str(&entity.name);
                    s.push_str("Api.list(args),\n");
                }
                "get" => {
                    s.push_str("    ");
                    s.push_str(&single_snake);
                    s.push_str(": (_p: unknown, args: { id: string }) => ");
                    s.push_str(&entity.name);
                    s.push_str("Api.get(args.id),\n");
                }
                _ => {}
            }
        }
    }
    s.push_str("  },\n");
    s.push_str("  Mutation: {\n");
    for api in &program.apis {
        let Some(entity) = program.entities.iter().find(|e| e.name == api.entity) else {
            continue;
        };
        for op in &api.operations {
            match op.as_str() {
                "create" => {
                    s.push_str("    create");
                    s.push_str(&entity.name);
                    s.push_str(": (_p: unknown, args: { input: unknown }) => ");
                    s.push_str(&entity.name);
                    s.push_str("Api.create(args.input),\n");
                }
                "update" => {
                    s.push_str("    update");
                    s.push_str(&entity.name);
                    s.push_str(": (_p: unknown, args: { id: string; input: unknown }) => ");
                    s.push_str(&entity.name);
                    s.push_str("Api.update(args.id, args.input),\n");
                }
                "delete" => {
                    s.push_str("    delete");
                    s.push_str(&entity.name);
                    s.push_str(": async (_p: unknown, args: { id: string }) => {\n      await ");
                    s.push_str(&entity.name);
                    s.push_str("Api.remove(args.id);\n      return true;\n    },\n");
                }
                _ => {}
            }
        }
    }
    s.push_str("  },\n");
    // 对象关系 resolvers：正向（按 {rel}_id）+ 逆向（DataLoader）合并到同一实体
    let rev = reverse_rels(program);
    for entity in &program.entities {
        let rels: Vec<&crate::dsl::FieldDecl> = entity
            .fields
            .iter()
            .filter(|f| is_relation(program, &f.type_name))
            .collect();
        let reverse: Vec<&ReverseRel> = rev.iter().filter(|r| r.target == entity.name).collect();
        if rels.is_empty() && reverse.is_empty() {
            continue;
        }
        s.push_str("  ");
        s.push_str(&entity.name);
        s.push_str(": {\n");
        for f in rels {
            let snake = to_snake_case(&f.name);
            s.push_str("    ");
            s.push_str(&snake);
            s.push_str(": (parent: any) => (parent.");
            s.push_str(&format!("{snake}Id"));
            s.push_str(" ? ");
            s.push_str(&f.type_name);
            s.push_str("Api.get(parent.");
            s.push_str(&format!("{snake}Id"));
            s.push_str(") : null),\n");
        }
        for r in reverse {
            s.push_str("    ");
            s.push_str(&r.field);
            s.push_str(": (parent: any, _args: unknown, ctx: any) => ctx.loaders.");
            s.push_str(&r.loader_key);
            s.push_str(".load(String(parent.id)),\n");
        }
        s.push_str("  },\n");
    }
    s.push_str("};\n");
    s
}

