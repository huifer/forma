//! gRPC/Protobuf 导出（轨道 B 重新排期）：Program → `.proto`（proto3）。
//!
//! - 实体 → message（字段类型映射：Uuid/String/Email/Text → string、Int → int64、
//!   Float → double、Decimal → string、Bool → bool、Timestamp → string、Json → string、
//!   枚举 → 对应 enum、关系 → string（`{rel}_id` 外键））；
//! - 枚举 → enum（proto3 首个成员必须为 0 → 生成保留序号的变体）；
//! - 每个实体生成列表请求/响应消息（分页 + q + 过滤）；
//! - 每个 api 块 → service（操作按 operations 裁剪）；
//! - `link`/`graph` 等非 API 语义不进入 proto。

use crate::dsl::{is_enum, is_relation, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

fn proto_type(program: &Program, field: &crate::dsl::FieldDecl) -> String {
    match field.type_name.as_str() {
        "Int" => "int64".to_string(),
        "Float" => "double".to_string(),
        "Bool" => "bool".to_string(),
        other if is_enum(program, other) => other.to_string(), // enum 名作为 proto 类型（同包引用）
        _ => "string".to_string(),
    }
}

fn pascal(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(['_', '-', '.']) {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            out.extend(c.to_uppercase());
            out.extend(cs);
        }
    }
    out
}

fn message_name(entity: &str) -> String {
    pascal(entity)
}

pub fn emit_grpc(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.apis.is_empty() || program.entities.is_empty() {
        return Ok(vec![]);
    }
    let app = program
        .app
        .as_ref()
        .map(|a| a.name.clone())
        .unwrap_or_else(|| "forma-app".into());
    let package = to_snake_case(&app);
    let mut out = String::from(
        "// @generated by Forma (gen-grpc) — do not edit manually.\nsyntax = \"proto3\";\n\n",
    );
    out.push_str(&format!("package {package};\n\n"));

    // 枚举（proto3 首成员必须为 0）
    for e in &program.enums {
        if e.variants.is_empty() {
            continue;
        }
        out.push_str(&format!("enum {} {{\n", pascal(&e.name)));
        for (i, v) in e.variants.iter().enumerate() {
            out.push_str(&format!("    {} = {};\n", v.name.to_uppercase(), i));
        }
        out.push_str("}\n\n");
    }

    // 实体 → message + 列表消息
    for entity in &program.entities {
        let name = message_name(&entity.name);
        let snake_e = to_snake_case(&entity.name);
        out.push_str(&format!("message {name} {{\n"));
        for (i, f) in entity.fields.iter().enumerate() {
            let fname = to_snake_case(&f.name);
            if is_relation(program, &f.type_name) {
                // 关系字段 → 外键（{rel}_id）
                out.push_str(&format!("    string {}_id = {};\n", fname, i + 1));
            } else {
                let optional_marker = "";
                out.push_str(&format!(
                    "    {} {}{} = {};\n",
                    proto_type(program, f),
                    optional_marker,
                    fname,
                    i + 1
                ));
            }
        }
        out.push_str("}\n\n");

        // 列表请求 / 响应
        out.push_str(&format!(
            "message {name}ListRequest {{\n    int64 page = 1;\n    int64 page_size = 2;\n    string q = 3;\n}}\n\n"
        ));
        out.push_str(&format!(
            "message {name}ListResponse {{\n    repeated {name} items = 1;\n    int64 total = 2;\n}}\n\n"
        ));
        out.push_str(&format!(
            "message {name}IdRequest {{\n    string id = 1;\n}}\n\n"
        ));
        let _ = snake_e;
    }

    // Create/Update 输入消息（字段为实体可写字段，全可选，proto3 语义）
    for entity in &program.entities {
        let writable: Vec<&crate::dsl::FieldDecl> = entity
            .fields
            .iter()
            .filter(|f| {
                !crate::dsl::has_attr(f, "id")
                    && !crate::dsl::has_attr(f, "readonly")
                    && f.type_name != "Timestamp"
            })
            .collect();
        for (kind, prefix) in [("Create", "create_"), ("Update", "update_")] {
            let name = format!("{kind}{}Request", message_name(&entity.name));
            out.push_str(&format!("message {name} {{\n"));
            for (i, f) in writable.iter().enumerate() {
                let fname = to_snake_case(&f.name);
                if is_relation(program, &f.type_name) {
                    out.push_str(&format!("    string {}_id = {};\n", fname, i + 1));
                } else {
                    out.push_str(&format!("    {} {} = {};\n", proto_type(program, f), fname, i + 1));
                }
                let _ = prefix;
            }
            out.push_str("}\n\n");
        }
    }

    // api 块 → service
    for api in &program.apis {
        let service = format!("{}Service", pascal(&api.name));
        out.push_str(&format!("service {service} {{\n"));
        for op in &api.operations {
            let entity = message_name(&api.entity);
            let snake_e = to_snake_case(&api.entity);
            match op.as_str() {
                "list" => out.push_str(&format!(
                    "    rpc List{entity} ({entity}ListRequest) returns ({entity}ListResponse);\n"
                )),
                "get" => out.push_str(&format!(
                    "    rpc Get{entity} ({entity}IdRequest) returns ({entity});\n"
                )),
                "create" => out.push_str(&format!(
                    "    rpc Create{entity} (Create{entity}Request) returns ({entity});\n"
                )),
                "update" => out.push_str(&format!(
                    "    rpc Update{entity} (Update{entity}Request) returns ({entity});\n"
                )),
                "delete" => out.push_str(&format!(
                    "    rpc Delete{entity} ({entity}IdRequest) returns ({});\n",
                    pascal("ok")
                )),
                _ => {}
            }
            let _ = snake_e;
        }
        out.push_str("}\n\n");
    }

    // Ok 哨兵消息（delete 用）
    out.push_str("message Ok {\n    bool ok = 1;\n}\n");

    let file = GeneratedFile {
        path: format!("{out_dir}/{package}.proto"),
        content: out,
        generator: "gen-grpc".into(),
    };
    crate::util::write_text(&project_dir.join(&file.path), &file.content)?;
    Ok(vec![file])
}
