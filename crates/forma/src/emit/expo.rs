//! 移动端 Expo（React Native）适配层（gen-expo）：Program → 可运行的 Expo + React Native 工程。
//!
//! 与 web-react 同构地复用同一份 TypeScript「共享层」（与后端 serde / DSL 规则同源）：
//! - `src/types.ts` ← web_react::types_ts
//! - `src/validators.ts` ← web_react::validators_ts
//! - `src/api.ts` ← web_react::api_ts（fetch + token + CRUD + 命令 + auth，RN 可用）
//! - `src/format.ts` ← web_react::format_ts
//! - `src/access.ts` ← web_react::access_ts（react-query 在 RN 可用）
//!
//! React Native 侧用 View/Text/FlatList/TextInput 渲染，替代 Web DOM 原语；导航用轻量
//! 手写栈（无 react-navigation 额外依赖）。列表页内嵌编辑视图（editing 状态），避免跨页传参。

use crate::dsl::Program;
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

pub fn emit_expo(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    // 宪法 6.2：spec 已声明但未实现的构造必须写盘前显式报错（不静默降级）。
    // 看板（dashboard）页暂仅 Web 支持（移动端图表/看板投影 V0.6+）。
    if program
        .pages
        .iter()
        .any(|p| matches!(p.body, crate::dsl::PageBody::Dashboard(_)))
    {
        anyhow::bail!(
            "Expo target does not support dashboard pages yet (web-only; mobile dashboard projection is V0.6+)"
        );
    }
    let pkg = to_snake_case(app_name).replace('_', "-");
    let title = program
        .app
        .as_ref()
        .map(|a| a.name.clone())
        .unwrap_or_else(|| app_name.to_string());

    let mut files: Vec<GeneratedFile> = vec![file(out_dir, "package.json", package_json(&pkg))];
    files.push(file(out_dir, "app.json", app_json(&title, &pkg)));
    files.push(file(out_dir, "tsconfig.json", tsconfig()));
    files.push(file(out_dir, "main.tsx", main_tsx()));
    files.push(file(out_dir, "App.tsx", app_tsx(program)));
    files.push(file(
        out_dir,
        "src/types.ts",
        crate::emit::web_react::types_ts(program),
    ));
    files.push(file(
        out_dir,
        "src/validators.ts",
        crate::emit::web_react::validators_ts(program),
    ));
    files.push(file(
        out_dir,
        "src/api.ts",
        crate::emit::web_react::api_ts(program),
    ));
    files.push(file(
        out_dir,
        "src/format.ts",
        crate::emit::web_react::format_ts(program),
    ));
    if !crate::emit::web_react::frontend_access_rules(program).is_empty()
        || !crate::dsl::field_policy_roles(program).is_empty()
    {
        files.push(file(
            out_dir,
            "src/access.ts",
            crate::emit::web_react::access_ts(program),
        ));
    }
    if program.auth.is_some() {
        files.push(file(out_dir, "src/pages/Login.tsx", login_page_rn(program)));
    }
    for page in &program.pages {
        let snake = to_snake_case(&page.name);
        files.push(file(
            out_dir,
            &format!("src/pages/{snake}.tsx"),
            page_rn(program, page),
        ));
    }
    files.push(file(
        out_dir,
        "README.md",
        format!(
            "# {title} mobile (Expo, generated by Forma)\n\n```bash\nnpx expo install --yes\nnpx tsc --noEmit\nnpx expo start\n```\n"
        ),
    ));

    for f in &files {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(files)
}

fn file(out: &str, rel: &str, content: String) -> GeneratedFile {
    GeneratedFile {
        path: format!("{out}/{rel}"),
        content,
        generator: "gen-expo".into(),
    }
}

fn pascal_case(s: &str) -> String {
    let mut out = String::new();
    for part in s.split('_') {
        let cap = part
            .chars()
            .next()
            .map(|c| c.to_uppercase().to_string())
            .unwrap_or_default();
        out.push_str(&cap);
        out.push_str(&part[1..]);
    }
    out
}

fn package_json(pkg: &str) -> String {
    format!("{{ \"name\": \"{pkg}-mobile\", \"version\": \"1.0.0\", \"main\": \"main.tsx\", \"scripts\": {{ \"start\": \"expo start\", \"android\": \"expo start --android\", \"ios\": \"expo start --ios\", \"web\": \"expo start --web\", \"tsc\": \"tsc --noEmit\" }}, \"dependencies\": {{ \"expo\": \"~50.0.0\", \"react\": \"18.2.0\", \"react-native\": \"0.74.0\", \"react-native-safe-area-context\": \"~4.10.0\", \"react-native-screens\": \"~3.31.0\", \"@tanstack/react-query\": \"^5.59.0\" }}, \"devDependencies\": {{ \"@types/react\": \"~18.2.0\", \"typescript\": \"^5.3.3\" }}, \"private\": true }}")
}

fn app_json(title: &str, pkg: &str) -> String {
    format!("{{ \"expo\": {{ \"name\": \"{title}\", \"slug\": \"{pkg}\", \"version\": \"1.0.0\", \"orientation\": \"portrait\", \"userInterfaceStyle\": \"automatic\", \"ios\": {{ \"supportsTablet\": true }}, \"android\": true, \"web\": {{ \"bundler\": \"metro\" }}, \"plugins\": [] }} }}")
}

fn tsconfig() -> String {
    "{\n  \"extends\": \"expo/tsconfig.base\",\n  \"compilerOptions\": {\n    \"strict\": true,\n    \"jsx\": \"react-native\",\n    \"moduleResolution\": \"bundler\",\n    \"noEmit\": true\n  },\n  \"include\": [\"**/*.ts\", \"**/*.tsx\"]\n}\n".into()
}

fn main_tsx() -> String {
    "import React from \"react\";\nimport { registerRootComponent } from \"expo\";\nimport App from \"./App\";\n\nregisterRootComponent(App);\n".into()
}

fn app_tsx(program: &Program) -> String {
    let mut s = String::new();
    s.push_str("// @generated by Forma (gen-expo) — do not edit manually.\n");
    s.push_str("import React, { useState } from \"react\";\n");
    s.push_str(
        "import { SafeAreaView, View, Text, Pressable, StyleSheet } from \"react-native\";\n",
    );
    s.push_str("import { QueryClient, QueryClientProvider } from \"@tanstack/react-query\";\n");
    s.push_str("import { setAuthToken } from \"./src/api\";\n");
    for p in &program.pages {
        let snake = to_snake_case(&p.name);
        s.push_str(&format!(
            "import {} from \"./src/pages/{snake}\";\n",
            pascal_case(&snake)
        ));
    }
    s.push_str("\nconst QUERY_CLIENT = new QueryClient();\n\n");
    s.push_str("export type ScreenProps = { go: (name: string, props?: Record<string, unknown>) => void; back: () => void };\n");
    s.push_str("type NavScreen = { name: string; props: Record<string, unknown> };\n");
    s.push_str("type PageComp = React.ComponentType<ScreenProps & Record<string, unknown>>;\n\n");
    // TITLES
    s.push_str("const TITLES: Record<string, string> = {\n");
    for p in &program.pages {
        let snake = to_snake_case(&p.name);
        let msg = super::pick_message(&p.title, &p.name);
        s.push_str("  ");
        s.push_str(&snake);
        s.push_str(": \"");
        s.push_str(&msg);
        s.push_str("\",\n");
    }
    s.push_str("};\n\n");
    // ROUTES
    s.push_str("const ROUTES: Record<string, PageComp> = {\n");
    for p in &program.pages {
        let snake = to_snake_case(&p.name);
        s.push_str(&format!(
            "  {snake}: {pascal},\n",
            pascal = pascal_case(&snake)
        ));
    }
    s.push_str("};\n\n");
    // NavHeader
    s.push_str("function NavHeader({ title, onBack }: { title: string; onBack: () => void }) {\n");
    s.push_str("  return (\n    <View style={styles.header}>\n");
    s.push_str(
        "      <Pressable onPress={onBack}><Text style={styles.back}>←</Text></Pressable>\n",
    );
    s.push_str("      <Text style={styles.headerText}>{title}</Text>\n    </View>\n  );\n}\n\n");
    // Root (nav stack)
    s.push_str("function Root({ initial }: { initial: string }) {\n");
    s.push_str("  const [stack, setStack] = useState<NavScreen[]>([]);\n");
    s.push_str("  if (stack.length === 0) setStack([{ name: initial, props: {} }]);\n");
    s.push_str("  const cur = stack[stack.length - 1];\n");
    s.push_str("  const Comp = ROUTES[cur.name];\n");
    s.push_str("  const go = (name: string, props?: Record<string, unknown>) => setStack((s) => [...s, { name, props: props ?? {} }]);\n");
    s.push_str("  const back = () => setStack((s) => (s.length > 1 ? s.slice(0, -1) : s));\n");
    s.push_str("  return (\n    <SafeAreaView style={styles.screen}>\n");
    s.push_str("      <NavHeader title={TITLES[cur.name] ?? cur.name} onBack={back} />\n");
    s.push_str(
        "      <Comp go={go} back={back} {...cur.props} />\n    </SafeAreaView>\n  );\n}\n\n",
    );
    // App
    let first = program
        .pages
        .first()
        .map(|p| to_snake_case(&p.name))
        .unwrap_or_default();
    s.push_str("export default function App() {\n");
    if program.auth.is_some() {
        s.push_str("  const [token, setToken] = useState<string | null>(null);\n");
        s.push_str("  if (token === null) return <Login onLogin={(t) => { setAuthToken(t); setToken(t); }} />;\n");
        s.push_str(&format!(
            "  return <Root initial=\"{first}\" />;\n",
            first = first
        ));
    } else {
        s.push_str(&format!(
            "  return <Root initial=\"{first}\" />;\n",
            first = first
        ));
    }
    s.push_str("}\n\n");
    // styles
    s.push_str("const styles = StyleSheet.create({\n");
    s.push_str("  screen: { flex: 1, backgroundColor: \"#fff\" },\n");
    s.push_str("  header: { flexDirection: \"row\", alignItems: \"center\", padding: 16, borderBottomWidth: 1, borderBottomColor: \"#eee\" },\n");
    s.push_str("  headerText: { fontSize: 18, fontWeight: \"600\" },\n");
    s.push_str("  back: { fontSize: 20 },\n});\n");
    s
}

fn page_rn(program: &Program, page: &crate::dsl::PageDecl) -> String {
    match &page.body {
        crate::dsl::PageBody::Table(cfg) => list_page_rn(program, page, cfg),
        crate::dsl::PageBody::Form(cfg) => edit_page_rn(program, page, cfg),
        crate::dsl::PageBody::Detail(cfg) => detail_page_rn(program, page, cfg),
        crate::dsl::PageBody::Chart(cfg) => chart_page_rn(program, page, cfg),
        // 不可达：emit_expo 已在生成前拒绝 dashboard（见函数头）
        crate::dsl::PageBody::Dashboard(_) => String::new(),
    }
}

fn list_page_rn(
    program: &Program,
    page: &crate::dsl::PageDecl,
    cfg: &crate::dsl::TableCfg,
) -> String {
    let Some(api) = program.apis.iter().find(|a| a.name == cfg.query_api) else {
        return "// unknown api".into();
    };
    let Some(entity) = super::find_entity(program, &api.entity) else {
        return "// unknown entity".into();
    };
    let entity_name = entity.name.clone();
    let snake = to_snake_case(&page.name);
    let api_name = format!("{}Api", entity_name);
    let display = crate::emit::web_react::display_field_of(program, &entity_name);

    let cols: Vec<String> = cfg.columns.iter().map(|c| to_snake_case(&c.path)).collect();

    let mut s = String::new();
    s.push_str("// @generated by Forma (gen-expo) — do not edit manually.\n");
    s.push_str("import React, { useState } from \"react\";\n");
    s.push_str("import { View, Text, TextInput, Pressable, FlatList, StyleSheet, ActivityIndicator } from \"react-native\";\n");
    s.push_str("import type { ScreenProps } from \"../../App\";\n");
    s.push_str(
        "import { useQuery, useMutation, useQueryClient } from \"@tanstack/react-query\";\n",
    );
    s.push_str("import { ");
    s.push_str(&api_name);
    s.push_str(" } from \"../api\";\n\n");
    s.push_str("export default function ");
    s.push_str(&pascal_case(&snake));
    s.push_str("({ go, back }: ScreenProps) {\n");
    s.push_str("  const qc = useQueryClient();\n");
    s.push_str("  const [q, setQ] = useState(\"\");\n");
    s.push_str("  const [editing, setEditing] = useState<any>(null);\n");
    s.push_str("  const list = useQuery({\n");
    s.push_str("    queryKey: [\"");
    s.push_str(&entity_name);
    s.push_str("\", q],\n");
    s.push_str("    queryFn: () => ");
    s.push_str(&api_name);
    s.push_str(".list({ q: q || null }),\n  });\n");
    s.push_str("  const remove = useMutation({ mutationFn: (id: string) => ");
    s.push_str(&api_name);
    s.push_str(".remove(id), onSuccess: () => qc.invalidateQueries({ queryKey: [\"");
    s.push_str(&entity_name);
    s.push_str("\"] }) });\n\n");
    s.push_str("  if (editing) {\n");
    s.push_str("    const isEdit = !!editing.id;\n");
    s.push_str("    const [row, setRow] = [editing, (v: Record<string, any>) => setEditing({ ...editing, ...v })];\n");
    s.push_str("    const save = async () => {\n");
    s.push_str("      if (isEdit) await ");
    s.push_str(&entity_name);
    s.push_str("Api.update(editing.id, row);\n");
    s.push_str("      else await ");
    s.push_str(&entity_name);
    s.push_str("Api.create(row);\n");
    s.push_str("      qc.invalidateQueries({ queryKey: [\"");
    s.push_str(&entity_name);
    s.push_str("\"] });\n      setEditing(null);\n    };\n");
    s.push_str("    return (\n      <View style={styles.screen}>\n");
    for c in &cols {
        s.push_str("        <View style={styles.field} key=\"");
        s.push_str(c);
        s.push_str("\">\n          <Text style={styles.label}>");
        s.push_str(c);
        let qk = format!("\"{c}\"", c = c);
        s.push_str("</Text>\n          <TextInput style={styles.input} value={String(row[");
        s.push_str(&qk);
        s.push_str("] ?? \"\")} onChangeText={(v: string) => setRow({ ");
        s.push_str(&qk);
        s.push_str(": v })} />\n        </View>\n");
    }
    s.push_str("        <Pressable style={styles.add} onPress={save}>\n          <Text style={styles.addText}>保存</Text>\n        </Pressable>\n      </View>\n    );\n  }\n\n");
    s.push_str("  return (\n    <View style={styles.screen}>\n");
    s.push_str("      <TextInput style={styles.search} placeholder=\"搜索\" value={q} onChangeText={setQ} />\n");
    s.push_str("      {!list.isLoading ? (\n        <FlatList\n          data={list.data ?? []}\n          keyExtractor={(r) => r.id}\n          renderItem={({ item }) => (\n            <View style={styles.row}>\n              <Pressable onPress={() => setEditing(item)}>\n                <Text style={styles.title}>{item.");
    s.push_str(&display);
    s.push_str("}</Text>\n              </Pressable>\n              <Pressable onPress={() => remove.mutate(item.id)}><Text style={styles.del}>删除</Text></Pressable>\n            </View>\n          )}\n        />\n      ) : (\n        <ActivityIndicator />\n      )}\n");
    s.push_str("      <Pressable style={styles.add} onPress={() => setEditing({})}>\n        <Text style={styles.addText}>+ 新建</Text>\n      </Pressable>\n    </View>\n  );\n}\n\n");
    s.push_str("const styles = StyleSheet.create({\n");
    s.push_str("  screen: { flex: 1, backgroundColor: \"#fff\" },\n");
    s.push_str("  search: { padding: 12, borderBottomWidth: 1, borderBottomColor: \"#eee\" },\n");
    s.push_str("  row: { flexDirection: \"row\", justifyContent: \"space-between\", alignItems: \"center\", padding: 12, borderBottomWidth: 1, borderBottomColor: \"#eee\" },\n");
    s.push_str("  title: { fontSize: 16 },\n");
    s.push_str("  del: { color: \"#e00\" },\n");
    s.push_str("  add: { margin: 16, padding: 12, backgroundColor: \"#0a7\", borderRadius: 8, alignItems: \"center\" },\n");
    s.push_str("  addText: { color: \"#fff\", fontWeight: \"600\" },\n");
    s.push_str("  field: { padding: 8 },\n");
    s.push_str("  label: { fontSize: 12, color: \"#666\" },\n");
    s.push_str(
        "  input: { borderWidth: 1, borderColor: \"#ccc\", borderRadius: 6, padding: 8 },\n});\n",
    );
    s
}

