//! 数据库升级：IR 快照对比 → 增量 ALTER 迁移（表/字段/索引/外键的增删改）。

use super::mysql::{plan_tables, TablePlan};
use super::Program;
use crate::util::write_text;
use anyhow::Result;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

const SNAPSHOT_VERSION: u32 = 1;

#[derive(Debug, Serialize, Deserialize)]
pub struct IrSnapshot {
    pub version: u32,
    pub tables: Vec<TablePlan>,
}

fn snapshot_path(project_dir: &Path) -> PathBuf {
    project_dir.join(".forma").join("ir-snapshot.json")
}

fn read_snapshot(project_dir: &Path) -> Option<IrSnapshot> {
    let p = snapshot_path(project_dir);
    let text = crate::util::read_text(&p).ok()?;
    let snap: IrSnapshot = serde_json::from_str(&text).ok()?;
    if snap.version == SNAPSHOT_VERSION {
        Some(snap)
    } else {
        None
    }
}

fn save_snapshot(project_dir: &Path, tables: &[TablePlan]) -> Result<()> {
    let snap = IrSnapshot {
        version: SNAPSHOT_VERSION,
        tables: tables.to_vec(),
    };
    write_text(
        &snapshot_path(project_dir),
        &serde_json::to_string_pretty(&snap)?,
    )?;
    Ok(())
}

fn count_migrations(migrations_dir: &Path) -> usize {
    std::fs::read_dir(migrations_dir)
        .map(|entries| {
            entries
                .flatten()
                .filter(|e| e.path().extension().map(|x| x == "sql").unwrap_or(false))
                .count()
        })
        .unwrap_or(0)
}

/// 与上次构建的 IR 快照对比；有变化则生成 `000N_upgrade.sql` 并更新快照。
/// 首次构建（无快照）只保存快照——基线由 gen-mysql 负责。
pub fn emit_migration(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> Result<Option<crate::generators::GeneratedFile>> {
    let new_plans = plan_tables(program);
    let migrations_dir = project_dir.join(out_dir).join("migrations");
    let previous = read_snapshot(project_dir);

    let Some(old_snapshot) = previous else {
        // 首次：记录基线快照（迁移文件由 gen-mysql 的 0001_init.sql 承载）
        save_snapshot(project_dir, &new_plans)?;
        return Ok(None);
    };

    let sql = diff_sql(&old_snapshot.tables, &new_plans);
    if sql.trim().is_empty() {
        return Ok(None);
    }

    let index = count_migrations(&migrations_dir) + 1;
    let rel = format!("{out_dir}/migrations/{index:04}_upgrade.sql");
    let content = format!(
        "-- @generated by Forma (gen-migrate) — do not edit manually.\n-- Schema upgrade #{index}\n\n{sql}"
    );
    write_text(&project_dir.join(&rel), &content)?;
    save_snapshot(project_dir, &new_plans)?;

    Ok(Some(crate::generators::GeneratedFile {
        path: rel,
        content,
        generator: "gen-migrate".into(),
    }))
}

/// 表结构差异 → SQL 语句序列。
pub fn diff_sql(old: &[TablePlan], new: &[TablePlan]) -> String {
    let mut stmts: Vec<String> = Vec::new();
    let old_by_table: std::collections::HashMap<&str, &TablePlan> =
        old.iter().map(|t| (t.table.as_str(), t)).collect();
    let new_by_table: std::collections::HashMap<&str, &TablePlan> =
        new.iter().map(|t| (t.table.as_str(), t)).collect();

    // 1. 新增表
    for t in new {
        if !old_by_table.contains_key(t.table.as_str()) {
            stmts.push(super::mysql::render_create_table(t));
        }
    }
    // 2. 删除表
    for t in old.iter().rev() {
        if !new_by_table.contains_key(t.table.as_str()) {
            stmts.push(format!("DROP TABLE IF EXISTS {};", t.table));
        }
    }
    // 3. 共有表的列/索引/外键差异
    for t in new {
        let Some(old_t) = old_by_table.get(t.table.as_str()) else {
            continue;
        };
        stmts.extend(column_diff(t, old_t));
        stmts.extend(index_diff(t, old_t));
        stmts.extend(fk_diff(t, old_t));
    }
    if stmts.is_empty() {
        return String::new();
    }
    let mut out = String::new();
    for s in stmts {
        out.push_str(&s);
        out.push('\n');
    }
    out
}

fn column_diff(new: &TablePlan, old: &TablePlan) -> Vec<String> {
    let mut out = Vec::new();
    let t = &new.table;
    let old_by_name: std::collections::HashMap<&str, &super::mysql::ColumnPlan> =
        old.columns.iter().map(|c| (c.name.as_str(), c)).collect();

    // 新增列（存量表回填安全：以 NULL 落地）
    for col in &new.columns {
        if !old_by_name.contains_key(col.name.as_str()) {
            let null_sql = if col.nullable {
                "NULL"
            } else {
                "NULL /* 回填后可收紧为 NOT NULL */"
            };
            out.push(format!(
                "ALTER TABLE {} ADD COLUMN {} {} {};",
                t, col.name, col.sql_type, null_sql
            ));
        }
    }
    // 删除列
    for col in &old.columns {
        if !new.columns.iter().any(|c| c.name == col.name) {
            out.push(format!("ALTER TABLE {} DROP COLUMN {};", t, col.name));
        }
    }
    // 类型/可空修改
    for col in &new.columns {
        let Some(old_col) = old_by_name.get(col.name.as_str()) else {
            continue;
        };
        if old_col.sql_type != col.sql_type || old_col.nullable != col.nullable {
            let null_sql = if col.nullable { "NULL" } else { "NOT NULL" };
            out.push(format!(
                "ALTER TABLE {} MODIFY COLUMN {} {} {};",
                t, col.name, col.sql_type, null_sql
            ));
        }
    }
    out
}

fn index_diff(new: &TablePlan, old: &TablePlan) -> Vec<String> {
    let mut out = Vec::new();
    let t = &new.table;
    // 唯一约束（块级 unique [..]）
    for (i, cols) in new.uniques.iter().enumerate() {
        if !old.uniques.contains(cols) {
            out.push(format!(
                "ALTER TABLE {} ADD UNIQUE KEY uq_{}_{} ({});",
                t,
                t,
                i,
                cols.join(", ")
            ));
        }
    }
    for (i, cols) in old.uniques.iter().enumerate() {
        if !new.uniques.contains(cols) {
            out.push(format!("ALTER TABLE {} DROP INDEX uq_{}_{};", t, t, i));
        }
    }
    // 普通索引
    for (i, cols) in new.indexes.iter().enumerate() {
        if !old.indexes.contains(cols) {
            out.push(format!(
                "ALTER TABLE {} ADD INDEX idx_{}_{} ({});",
                t,
                t,
                i,
                cols.join(", ")
            ));
        }
    }
    for (i, cols) in old.indexes.iter().enumerate() {
        if !new.indexes.contains(cols) {
            out.push(format!("ALTER TABLE {} DROP INDEX idx_{}_{};", t, t, i));
        }
    }
    // 列级 @unique 变化
    let old_by_name: std::collections::HashMap<&str, &super::mysql::ColumnPlan> =
        old.columns.iter().map(|c| (c.name.as_str(), c)).collect();
    for col in &new.columns {
        let Some(old_col) = old_by_name.get(col.name.as_str()) else {
            continue;
        };
        if col.unique && !old_col.unique {
            out.push(format!(
                "ALTER TABLE {} ADD UNIQUE KEY uq_{}_{} ({});",
                t, t, col.name, col.name
            ));
        } else if !col.unique && old_col.unique {
            out.push(format!(
                "ALTER TABLE {} DROP INDEX uq_{}_{};",
                t, t, col.name
            ));
        }
    }
    out
}

fn fk_diff(new: &TablePlan, old: &TablePlan) -> Vec<String> {
    let mut out = Vec::new();
    let t = &new.table;
    for fk in &new.fks {
        if !old.fks.contains(fk) {
            out.push(format!(
                "ALTER TABLE {} ADD CONSTRAINT fk_{}_{} FOREIGN KEY ({}) REFERENCES {} (id);",
                t, t, fk.column, fk.column, fk.ref_table
            ));
        }
    }
    for fk in &old.fks {
        if !new.fks.contains(fk) {
            out.push(format!(
                "ALTER TABLE {} DROP FOREIGN KEY fk_{}_{};",
                t, t, fk.column
            ));
        }
    }
    out
}
