//! seed-data 适配层（gen-seed）：Program → 确定性案例数据（SQL 种子 + JSON fixtures）。
//!
//! 设计不变量：**案例数据不是 AI 数据**。全部取值由 DSL（类型/约束/枚举/关系）
//! 经纯函数推导，不经过任何模型；同一 Program 两次生成结果 byte 级一致，
//! 可做 hash 校验与跨机器重放。
//!
//! - SQL：`{out}/seed_{version}.sql` —— `INSERT IGNORE` + 确定性主键 ⇒ 幂等可重放；
//!   表顺序复用 `plan_tables` 拓扑序（父表先于子表，FK 永远可满足）。
//! - JSON：`{out}/fixtures/{table}.json`（实体形态）与 `{table}_list.json`
//!   （列表形态，含 `{rel}_name`），键名与 Rust 后端 serde 序列化一致（snake_case）。
//! - 行值必须通过同一套 DSL rules（min/max/枚举/必填），否则会被自己生成的
//!   validator 拒绝——这是 seed 与 rules 同源一致性的自检。

use super::{find_entity, has_attr, is_enum, is_relation, EntityDecl, FieldDecl, Program};
use crate::emit::mysql::plan_tables;
use crate::identity::to_snake_case;
use anyhow::bail;
use serde_json::{Map, Value};
use sha2::{Digest, Sha256};
use std::path::Path;

/// 每实体生成的行数（确定性小样本：前 2 行填满可空字段，后 3 行可空字段为 NULL）。
pub const SEED_ROWS: usize = 5;

/// 时间锚点：2025-01-06T08:00:00Z（固定常量，保证跨机器跨时间确定性）。
const ANCHOR_EPOCH_SECS: i64 = 1_736_150_400;
/// 锚点日期（距 1970-01-01 的天数）。
const ANCHOR_EPOCH_DAY: i64 = 20_094; // 2025-01-06

/// 一个版本的种子内容（纯推导，不写盘）——emit 与 verify 共用。
pub struct SeedBundle {
    /// 相对路径（不含 out_dir 前缀）
    pub sql_rel: String,
    pub sql: String,
    /// (相对路径, 内容)
    pub fixtures: Vec<(String, String)>,
    pub version: String,
}

/// 从 DSL 纯函数推导全部种子内容（SQL + JSON fixtures）。
pub fn render_seed_bundle(program: &Program) -> anyhow::Result<SeedBundle> {
    if program.entities.is_empty() {
        bail!("no entities to seed");
    }
    let app = program
        .app
        .as_ref()
        .map(|a| (a.name.clone(), a.version.clone()))
        .unwrap_or_else(|| ("app".into(), "0.0.0".into()));
    let namespace = format!("forma-seed:{}", app.0);
    let plans = plan_tables(program);

    // ── SQL 种子 ──────────────────────────────────────────
    let version_tag = app.1.replace('.', "_");
    let sql_rel = format!("seed_{version_tag}.sql");
    let sql = render_seed_sql(program, &plans, &namespace, &app.0, &app.1);

    // ── JSON fixtures（实体形态 + 列表形态） ──────────────
    let mut fixtures: Vec<(String, String)> = Vec::new();
    for plan in &plans {
        let Some(entity) = find_entity(program, &plan.entity) else {
            continue;
        };
        let table = &plan.table;

        let mut rows = Vec::new();
        let mut list_rows = Vec::new();
        for i in 0..SEED_ROWS {
            let mut obj = Map::new();
            let mut list_obj = Map::new();
            for f in &entity.fields {
                let val = cell(program, &app.0, &namespace, entity, f, i);
                let key = if is_relation(program, &f.type_name) {
                    format!("{}_id", to_snake_case(&f.name))
                } else {
                    to_snake_case(&f.name)
                };
                obj.insert(key.clone(), val.clone().into_json());
                list_obj.insert(key, val.into_json());
                if is_relation(program, &f.type_name) {
                    let name = relation_display(program, &app.0, &namespace, &f.type_name, i);
                    list_obj.insert(
                        format!("{}_name", to_snake_case(&f.name)),
                        Value::String(name),
                    );
                }
            }
            rows.push(Value::Object(obj));
            list_rows.push(Value::Object(list_obj));
        }

        fixtures.push((
            format!("fixtures/{table}.json"),
            format!(
                "// @generated by Forma (gen-seed) — do not edit manually.\n{}\n",
                Value::Array(rows)
            ),
        ));
        fixtures.push((
            format!("fixtures/{table}_list.json"),
            format!(
                "// @generated by Forma (gen-seed) — do not edit manually.\n{}\n",
                Value::Array(list_rows)
            ),
        ));
    }

    Ok(SeedBundle {
        sql_rel,
        sql,
        fixtures,
        version: app.1,
    })
}

pub fn emit_seed(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<crate::generators::GeneratedFile>> {
    let bundle = render_seed_bundle(program)?;

    let mut files = Vec::new();
    let rel_sql = format!("{out_dir}/{}", bundle.sql_rel);
    crate::util::write_text(&project_dir.join(&rel_sql), &bundle.sql)?;
    files.push(crate::generators::GeneratedFile {
        path: rel_sql,
        content: bundle.sql,
        generator: "gen-seed".into(),
    });
    for (rel, content) in &bundle.fixtures {
        let path = format!("{out_dir}/{rel}");
        crate::util::write_text(&project_dir.join(&path), content)?;
        files.push(crate::generators::GeneratedFile {
            path,
            content: content.clone(),
            generator: "gen-seed".into(),
        });
    }
    Ok(files)
}

/// 种子校验报告：重新推导与磁盘逐字节比对。
pub struct SeedVerifyReport {
    pub version: String,
    pub ok: bool,
    pub sql_hash: String,
    pub issues: Vec<String>,
}

/// `forma seed --verify`：确定性校验——磁盘上的种子必须与当前 DSL 的纯函数推导
/// byte 级一致（SHA-256）。任何手工改动或 DSL 演进后未重建都会被抓住。
pub fn verify_seed(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<SeedVerifyReport> {
    let bundle = render_seed_bundle(program)?;
    let mut issues: Vec<String> = Vec::new();

    let sql_path = project_dir.join(format!("{out_dir}/{}", bundle.sql_rel));
    if let Ok(disk) = crate::util::read_text(&sql_path) {
        if disk != bundle.sql {
            issues.push(format!(
                "{} 与当前 DSL 推导不一致（DSL 已演进或文件被手工改动）",
                bundle.sql_rel
            ));
        }
    } else {
        issues.push(format!("{} 缺失（先运行 forma seed）", bundle.sql_rel));
    }
    for (rel, content) in &bundle.fixtures {
        let path = project_dir.join(format!("{out_dir}/{rel}"));
        match crate::util::read_text(&path) {
            Ok(disk) => {
                if &disk != content {
                    issues.push(format!("{rel} 与推导不一致"));
                }
            }
            Err(_) => issues.push(format!("{rel} 缺失")),
        }
    }

    let mut hasher = Sha256::new();
    hasher.update(bundle.sql.as_bytes());
    let sql_hash: String = hasher
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();

    Ok(SeedVerifyReport {
        version: bundle.version,
        ok: issues.is_empty(),
        sql_hash,
        issues,
    })
}

// ── SQL 渲染 ────────────────────────────────────────────

fn render_seed_sql(
    program: &Program,
    plans: &[crate::emit::mysql::TablePlan],
    namespace: &str,
    app: &str,
    version: &str,
) -> String {
    let mut out = String::new();
    out.push_str("-- @generated by Forma (gen-seed) — do not edit manually.\n");
    out.push_str(&format!(
        "-- 确定性种子数据：{app} v{version}。同一 DSL 生成结果 byte 级一致（SHA-256 派生主键）。\n"
    ));
    out.push_str("-- 幂等：INSERT IGNORE + 确定性主键；表按拓扑序先父后子，FK 永远可满足。\n");
    out.push_str("-- 值满足 DSL rules（min/max/枚举/必填），可被同一套生成的 validator 接受。\n\n");
    out.push_str("SET NAMES utf8mb4;\n");

    for plan in plans {
        let Some(entity) = find_entity(program, &plan.entity) else {
            continue;
        };
        out.push_str(&format!("\n-- ── {}（{} 行） ──\n", plan.table, SEED_ROWS));
        let cols: Vec<String> = entity
            .fields
            .iter()
            .map(|f| {
                if is_relation(program, &f.type_name) {
                    format!("{}_id", to_snake_case(&f.name))
                } else {
                    to_snake_case(&f.name)
                }
            })
            .collect();
        out.push_str(&format!(
            "INSERT IGNORE INTO {} ({}) VALUES\n",
            plan.table,
            cols.join(", ")
        ));
        let mut row_sqls = Vec::new();
        for i in 0..SEED_ROWS {
            let vals: Vec<String> = entity
                .fields
                .iter()
                .map(|f| cell(program, app, namespace, entity, f, i).into_sql())
                .collect();
            row_sqls.push(format!("({})", vals.join(", ")));
        }
        out.push_str(&row_sqls.join(",\n"));
        out.push_str(";\n");
    }
    out
}

// ── 取值内核（SQL 与 JSON 共用） ─────────────────────────

#[derive(Debug, Clone, PartialEq)]
enum Val {
    Null,
    Str(String),
    Int(i64),
    Float(f64),
    Bool(bool),
    /// DATETIME(3)：锚点秒 + 行偏移（毫秒恒为 0）
    Ts(i64),
    /// DATE：距 epoch 天数
    Day(i64),
}

impl Val {
    fn into_sql(self) -> String {
        match self {
            Val::Null => "NULL".into(),
            Val::Str(s) => sql_quote(&s),
            Val::Int(v) => v.to_string(),
            Val::Float(v) => format!("{v:.2}"),
            Val::Bool(b) => if b { 1 } else { 0 }.to_string(),
            Val::Ts(secs) => {
                let (y, mo, d) = civil_from_days(secs.div_euclid(86_400));
                let sod = secs.rem_euclid(86_400);
                format!(
                    "'{y:04}-{mo:02}-{d:02} {:02}:{:02}:{:02}.000'",
                    sod / 3600,
                    (sod % 3600) / 60,
                    sod % 60
                )
            }
            Val::Day(days) => {
                let (y, m, d) = civil_from_days(days);
                format!("'{y:04}-{m:02}-{d:02}'")
            }
        }
    }

    fn into_json(self) -> Value {
        match self {
            Val::Null => Value::Null,
            Val::Str(s) => Value::String(s),
            Val::Int(v) => Value::Number(v.into()),
            Val::Float(v) => serde_json::Number::from_f64(v)
                .map(Value::Number)
                .unwrap_or(Value::Null),
            Val::Bool(b) => Value::Bool(b),
            // 与 chrono serde（DateTime<Utc>）一致：RFC3339，毫秒为 0 时省略亚秒
            Val::Ts(secs) => {
                let (y, mo, d) = civil_from_days(secs.div_euclid(86_400));
                let sod = secs.rem_euclid(86_400);
                Value::String(format!(
                    "{y:04}-{mo:02}-{d:02}T{:02}:{:02}:{:02}Z",
                    sod / 3600,
                    (sod % 3600) / 60,
                    sod % 60
                ))
            }
            // 与 chrono serde（NaiveDate）一致：YYYY-MM-DD
            Val::Day(days) => {
                let (y, m, d) = civil_from_days(days);
                Value::String(format!("{y:04}-{m:02}-{d:02}"))
            }
        }
    }
}

fn sql_quote(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "''"))
}

/// 单元格取值：纯函数，仅由 (Program, 实体, 字段, 行号) 决定。
fn cell(
    program: &Program,
    app: &str,
    namespace: &str,
    entity: &EntityDecl,
    field: &FieldDecl,
    i: usize,
) -> Val {
    // 主键：确定性 UUID（SHA-256 派生，RFC4122 v5-shape 位）
    if has_attr(field, "id") {
        return Val::Str(det_uuid(
            namespace,
            &format!("{app}.{}.row{i}", entity.name),
        ));
    }
    // 关系 → 父表同行号的主键
    if is_relation(program, &field.type_name) {
        if field.optional && i >= 2 {
            return Val::Null;
        }
        return Val::Str(det_uuid(
            namespace,
            &format!("{app}.{}.row{i}", field.type_name),
        ));
    }
    // 可空字段：前 2 行填满，后 3 行 NULL（让列表/表单覆盖空值渲染路径）
    if field.optional && i >= 2 {
        return Val::Null;
    }

    match field.type_name.as_str() {
        "Uuid" => Val::Str(det_uuid(
            namespace,
            &format!("{app}.{}.{}.row{i}", entity.name, field.name),
        )),
        "Email" => Val::Str(format!("{}{i}@example.test", to_snake_case(&entity.name))),
        "String" => {
            if field.name.to_lowercase().contains("phone") {
                return Val::Str(format!("138{i:08}"));
            }
            let n = field
                .type_args
                .first()
                .and_then(|a| a.parse::<usize>().ok())
                .unwrap_or(255);
            Val::Str(pool_value(&entity.name, &field.name, i, n))
        }
        "Text" => Val::Str(pool_value(&entity.name, &field.name, i, 500)),
        "Int" => Val::Int(int_value(program, entity, field, i)),
        "Float" => Val::Float(float_value(program, entity, field, i)),
        "Decimal" => {
            let s = field
                .type_args
                .get(1)
                .and_then(|a| a.parse::<usize>().ok())
                .unwrap_or(2);
            Val::Str(decimal_value(program, entity, field, i, s))
        }
        "Bool" => Val::Bool(i.is_multiple_of(2)),
        "Timestamp" => Val::Ts(anchor_secs(field, i)),
        "Date" => Val::Day(ANCHOR_EPOCH_DAY + (i as i64) * 3),
        "Json" => Val::Str("{}".into()),
        other => {
            if is_enum(program, other) {
                let Some(e) = program.enums.iter().find(|e| e.name == other) else {
                    return Val::Null;
                };
                let v = &e.variants[i % e.variants.len()];
                Val::Str(v.name.clone())
            } else {
                Val::Str(pool_value(&entity.name, &field.name, i, 100))
            }
        }
    }
}

fn anchor_secs(field: &FieldDecl, i: usize) -> i64 {
    let name = field.name.to_lowercase();
    let base = ANCHOR_EPOCH_SECS + (i as i64) * 86_400;
    if name.contains("start") {
        base + 9 * 3600 // startsAt 当日 09:00，晚于 createdAt
    } else if name.contains("end") {
        base + 7 * 86_400 + 9 * 3600 // endsAt 一周后，保证 end > start
    } else if name.contains("enroll") {
        base + 2 * 3600 // enrolledAt ≥ createdAt（check 规则）
    } else {
        base
    }
}

fn int_value(program: &Program, entity: &EntityDecl, field: &FieldDecl, i: usize) -> i64 {
    let (min, max) = num_bounds(program, entity, field);
    let i = i as i64;
    match (min, max) {
        (Some(lo), Some(hi)) if hi >= lo => lo as i64 + (i * 7 + 3) % (hi as i64 - lo as i64 + 1),
        (Some(lo), None) => lo as i64 + i * 3 + 1,
        (None, Some(hi)) => hi as i64 - i * 3 - 1,
        _ => 10 + i * 5,
    }
}

fn float_value(program: &Program, entity: &EntityDecl, field: &FieldDecl, i: usize) -> f64 {
    let (min, max) = num_bounds(program, entity, field);
    let i = i as f64;
    match (min, max) {
        (Some(lo), Some(hi)) if hi > lo => lo + (i + 0.5) * (hi - lo) / (SEED_ROWS as f64 + 1.0),
        (Some(lo), None) => lo + i * 0.25 + 0.5,
        (None, Some(hi)) => hi - i * 0.25 - 0.5,
        _ => 1.5 + i * 0.25,
    }
}

fn decimal_value(
    program: &Program,
    entity: &EntityDecl,
    field: &FieldDecl,
    i: usize,
    scale: usize,
) -> String {
    let (min, max) = num_bounds(program, entity, field);
    let i = i as f64;
    let v = match (min, max) {
        (Some(lo), Some(hi)) if hi > lo => lo + (i + 1.0) * (hi - lo) / (SEED_ROWS as f64 + 1.0),
        (Some(lo), None) => lo * (i + 1.0),
        (None, Some(hi)) => hi / (i + 1.0),
        _ => (i + 1.0) * 12.34,
    };
    format!("{v:.scale$}")
}

/// 数值边界：字段 @min/@max 属性 + rules 中 Min/Max 约束（与 validator 同源）。
fn num_bounds(
    program: &Program,
    entity: &EntityDecl,
    field: &FieldDecl,
) -> (Option<f64>, Option<f64>) {
    let mut min = None;
    let mut max = None;
    for attr in &field.attrs {
        if matches!(attr.name.as_str(), "min" | "max") {
            if let Some(v) = attr.args.first().and_then(|a| a.parse::<f64>().ok()) {
                if attr.name == "min" {
                    min = Some(v);
                } else {
                    max = Some(v);
                }
            }
        }
    }
    for rules in &program.rules {
        for fr in &rules.field_rules {
            if fr.entity != entity.name || fr.field != field.name {
                continue;
            }
            for c in &fr.constraints {
                if let crate::dsl::FieldConstraint::Min(v, _) = c {
                    min = min.map_or(Some(*v), |m| Some(m.max(*v)));
                }
                if let crate::dsl::FieldConstraint::Max(v, _) = c {
                    max = max.map_or(Some(*v), |m| Some(m.min(*v)));
                }
            }
        }
    }
    (min, max)
}

