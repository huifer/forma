/// 关系显示名：父表展示列（第一个 required 的 String/Email 字段）取同行号的值。
fn relation_display(
    program: &Program,
    app: &str,
    namespace: &str,
    parent: &str,
    i: usize,
) -> String {
    let Some(parent_entity) = find_entity(program, parent) else {
        return det_uuid(namespace, &format!("{app}.{parent}.row{i}"));
    };
    let field = parent_entity
        .fields
        .iter()
        .find(|f| matches!(f.type_name.as_str(), "String" | "Email") && has_attr(f, "required"))
        .or_else(|| {
            parent_entity
                .fields
                .iter()
                .find(|f| f.type_name == "String")
        });
    match field {
        Some(f) => match cell(program, app, namespace, parent_entity, f, i) {
            Val::Str(s) => s,
            _ => parent.to_string(),
        },
        None => parent.to_string(),
    }
}

/// 确定性 UUID：SHA-256(namespace, 0x00, name) 前 16 字节，
/// 置 RFC4122 版本位 5 / 变体位 10。仓库零新增依赖（复用 sha2），
/// 与标准 UUIDv5（SHA-1）仅散列算法不同；此处只要求「合法格式 + 确定性」。
pub fn det_uuid(namespace: &str, name: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(namespace.as_bytes());
    hasher.update([0x00]);
    hasher.update(name.as_bytes());
    let h = hasher.finalize();
    let mut b = [0u8; 16];
    b.copy_from_slice(&h[..16]);
    b[6] = (b[6] & 0x0f) | 0x50; // version 5
    b[8] = (b[8] & 0x3f) | 0x80; // variant 10xx
    let hex: String = b.iter().map(|x| format!("{x:02x}")).collect();
    format!(
        "{}-{}-{}-{}-{}",
        &hex[..8],
        &hex[8..12],
        &hex[12..16],
        &hex[16..20],
        &hex[20..]
    )
}

/// Howard Hinnant civil_from_days：epoch 天数 → (年, 月, 日)。
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = (z - era * 146_097) as u64; // [0, 146096]
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365; // [0, 399]
    let y = yoe as i64 + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100); // [0, 365]
    let mp = (5 * doy + 2) / 153; // [0, 11]
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32; // [1, 31]
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32; // [1, 12]
    (if m <= 2 { y + 1 } else { y }, m, d)
}

