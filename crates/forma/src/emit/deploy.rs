struct Ctx {
    app: String,
    ns: String,
    db: String,
    replicas: String,
    image: String,
    image_repo: String,
    image_tag: String,
    host: String,
    version: String,
    jwt_line: String,
    jwt_secret: String,
    rule_head: String,
}

fn render(template: &str, ctx: &Ctx) -> String {
    template
        .replace("__APP__", &ctx.app)
        .replace("__NS__", &ctx.ns)
        .replace("__DB__", &ctx.db)
        .replace("__REPLICAS__", &ctx.replicas)
        .replace("__IMAGE_REPO__", &ctx.image_repo)
        .replace("__IMAGE_TAG__", &ctx.image_tag)
        .replace("__IMAGE__", &ctx.image)
        .replace("__HOST__", &ctx.host)
        .replace("__VERSION__", &ctx.version)
        .replace("__JWT_LINE__", &ctx.jwt_line)
        .replace("__JWT_SECRET__", &ctx.jwt_secret)
        .replace("__RULE_HEAD__", &ctx.rule_head)
}

/// 生成部署产物（按 provider 分派；`all` = 三套全生成）。
pub fn emit_deploy(
    project_dir: &Path,
    program: &Program,
    cfg: &DeploymentConfig,
    app_name: &str,
    project_version: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(Vec::new());
    }
    let app = crate::identity::to_snake_case(app_name).replace('_', "-");
    let db = crate::identity::to_snake_case(app_name);
    let ns = cfg.namespace.clone().unwrap_or_else(|| "default".into());
    let image = cfg
        .image
        .clone()
        .unwrap_or_else(|| format!("{app}-backend:latest"));
    let (image_repo, image_tag) = match image.rsplit_once(':') {
        Some((r, t)) => (r.to_string(), t.to_string()),
        None => (image.clone(), "latest".to_string()),
    };
    let host = cfg.host.clone().unwrap_or_default();
    let has_auth = program.auth.is_some();
    let ctx = Ctx {
        app: app.clone(),
        ns,
        db,
        replicas: cfg.replicas.max(1).to_string(),
        image,
        image_repo,
        image_tag,
        version: project_version.to_string(),
        jwt_line: if has_auth {
            "  JWT_SECRET: \"CHANGE_ME_JWT_SECRET\"\n".to_string()
        } else {
            String::new()
        },
        jwt_secret: if has_auth {
            "CHANGE_ME_JWT_SECRET".into()
        } else {
            String::new()
        },
        rule_head: if host.is_empty() {
            "  - http:\n".to_string()
        } else {
            format!("  - host: {}\n    http:\n", host)
        },
        host,
    };

    let want = |p: &str| cfg.provider == "all" || cfg.provider == p;
    let mut files: Vec<GeneratedFile> = Vec::new();
    let mut add = |path: String, template: &str| {
        files.push(GeneratedFile {
            path,
            content: render(template, &ctx),
            generator: "gen-deploy".into(),
        });
    };

    if want("kubernetes") {
        add("k8s/namespace.yaml".into(), K8S_NAMESPACE);
        add("k8s/configmap.yaml".into(), K8S_CONFIGMAP);
        add("k8s/secret.yaml".into(), K8S_SECRET);
        add("k8s/deployment.yaml".into(), K8S_DEPLOYMENT);
        add("k8s/service.yaml".into(), K8S_SERVICE);
        add("k8s/ingress.yaml".into(), K8S_INGRESS);
    }
    if want("helm") {
        let base = format!("helm/{app}");
        add(format!("{base}/Chart.yaml"), HELM_CHART);
        add(format!("{base}/values.yaml"), HELM_VALUES);
        add(format!("{base}/templates/_helpers.tpl"), HELM_HELPERS);
        add(format!("{base}/templates/deployment.yaml"), HELM_DEPLOYMENT);
        add(format!("{base}/templates/service.yaml"), HELM_SERVICE);
        add(format!("{base}/templates/ingress.yaml"), HELM_INGRESS);
        add(format!("{base}/templates/NOTES.txt"), HELM_NOTES);
    }
    if want("terraform") {
        add("terraform/versions.tf".into(), TF_VERSIONS);
        add("terraform/variables.tf".into(), TF_VARIABLES);
        add("terraform/main.tf".into(), TF_MAIN);
        add("terraform/outputs.tf".into(), TF_OUTPUTS);
    }

    for f in &files {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(files)
}
