//! 部署产物生成（M11 / P1）：`deployment:` manifest 段 opt-in。
//!
//! 三套**同源**部署表达（同一 app / 镜像 / 端口 / 命名空间 / 副本数）：
//! - `k8s/*.yaml`：原生 Kubernetes manifests（Deployment / Service / Ingress /
//!   ConfigMap / Secret 占位 / Namespace）；
//! - `helm/<app>/`：Helm v3 Chart（Chart.yaml / values.yaml / templates）；
//! - `terraform/*.tf`：Kubernetes provider 的 IaC（namespace / deployment / service）。
//!
//! 契约：
//! - 默认零产物（未声明 `deployment:` 不生成任何文件）；
//! - `provider: kubernetes | helm | terraform | all`（未知值在 build.rs 显式报错）；
//! - 探活用 TCP socket 8080（不假设后端存在 /health 端点）；
//! - Secret 只放占位符（不落真凭据，生产换 SealedSecret / External Secrets）；
//! - 模板用占位符替换而非 format!（避免与 YAML `{}` / Go `{{ }}` / HCL `{}` 冲突）。

