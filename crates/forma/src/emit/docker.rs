//! Docker / docker-compose 产物生成（roadmap M9 / P1）。
//!
//! 为生成的 Rust 后端产出**可直接部署**的容器化配置：
//! - `Dockerfile`（多阶段构建：cargo build → debian-slim 运行时）
//! - `docker-compose.yml`（MySQL 8 + backend 服务 + healthcheck + 数据卷）
//! - `.dockerignore`
//! - `entrypoint.sh`（等库就绪 → 按序执行迁移 → 启动服务）
//!
//! 语义约定：
//! - `DATABASE_URL` 从环境变量注入（docker-compose 里指向 `db` 服务）；
//! - 迁移按文件名序执行 `*_upgrade.sql`（幂等靠 `INSERT IGNORE` + CREATE TABLE IF NOT EXISTS 语义）；
//! - `PORT` 可覆盖（默认 8080，与 Web proxy / Flutter 默认 API_BASE 对齐）。

use crate::dsl::Program;
use std::path::Path;

/// 生成 Docker 部署文件（backend 存在时才调用）。
pub fn emit_docker(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> anyhow::Result<Vec<crate::generators::GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    let mut files = Vec::new();
    let db_name = crate::identity::to_snake_case(app_name).replace('_', "-");
    let has_auth = program.auth.is_some();
    let has_seed = program
        .apis
        .iter()
        .any(|a| a.operations.iter().any(|o| o == "list"));

    // ── Dockerfile ──
    let binary_name = format!(
        "{}-backend",
        crate::identity::to_snake_case(app_name).replace('_', "-")
    );
    let dockerfile = format!(
        r#"# @generated by Forma (gen-rust) — do not edit manually.
# 多阶段构建：cargo build → debian-slim 运行时（最终镜像不含 Rust 工具链）。

# ── build ──
# 用滚动稳定版：依赖（如 sqlx → idna_adapter）会要求 edition2024（Cargo 1.85+），
# 固定 1.83 会在干净环境构建失败（实测 docker build 报错）。
FROM rust:1-slim AS build
WORKDIR /app
# compose 的 build context 是项目根目录；后端源码位于 generated/backend。
# emitter 不产出 Cargo.lock（generated/ 是生成物），因此先复制 Cargo.toml
# 并 `cargo fetch` 生成锁文件 + 预取依赖，利用 Docker 层缓存（依赖不变时不重编译）。
COPY generated/backend/Cargo.toml ./
RUN mkdir -p src && echo "fn main() {{}}" > src/main.rs
RUN cargo fetch && cargo build --release && rm -rf src target/release/deps/*_backend*
COPY generated/backend/src ./src
RUN cargo build --release && cp target/release/{binary_name} /app/server

# ── runtime ──
FROM debian:bookworm-slim
RUN apt-get update && apt-get install -y ca-certificates default-mysql-client && rm -rf /var/lib/apt/lists/*
COPY --from=build /app/server /usr/local/bin/server
COPY db/migrations /app/migrations
COPY generated/backend/entrypoint.sh /app/entrypoint.sh
RUN chmod +x /app/entrypoint.sh \
 && useradd --system --uid 10001 --create-home --home-dir /app forma \
 && mkdir -p /app/uploads && chown -R forma:forma /app

ENV PORT=8080
# 不提供默认凭据：DATABASE_URL / DB_* / JWT_SECRET 必须由部署方显式注入
# （缺失时后端 fail-closed 退出，绝不使用内置开发密钥/默认口令）。

EXPOSE ${{PORT}}
# 以非 root 用户运行（最小权限）
USER forma
ENTRYPOINT ["/app/entrypoint.sh"]
CMD ["server"]
"#,
        binary_name = binary_name,
    );
    files.push(crate::generators::GeneratedFile {
        path: format!("{out_dir}/generated/backend/Dockerfile"),
        content: dockerfile,
        generator: "gen-docker".into(),
    });

    // ── entrypoint.sh ──
    let entrypoint = r#"#!/bin/bash
# @generated by Forma (gen-docker) — do not edit manually.
set -e

# ── 凭据 fail-closed：没有口令就不启动（绝不使用内置默认口令）──
if [ -z "${DB_PASS:-}" ]; then
  echo "[entrypoint] DB_PASS is required (no built-in default password)" >&2
  exit 1
fi
DB_HOST="${DB_HOST:-db}"
DB_USER="${DB_USER:-root}"
DB_NAME="${DB_NAME:-app}"

# ── 等待数据库就绪（compose healthcheck + depends_on 之外再兜底一层，60s 超时）──
echo "[entrypoint] waiting for database..."
for i in $(seq 1 60); do
  if mysql -h "$DB_HOST" -u "$DB_USER" -p"$DB_PASS" -e "SELECT 1" >/dev/null 2>&1; then
    break
  fi
  if [ "$i" = "60" ]; then
    echo "[entrypoint] database not reachable after 60s" >&2
    exit 1
  fi
  sleep 1
done
echo "[entrypoint] database is ready"

# ── 建库（如果不存在）──
mysql -h "$DB_HOST" -u "$DB_USER" -p"$DB_PASS" \
  -e "CREATE DATABASE IF NOT EXISTS ${DB_NAME} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"

# ── 数据库内迁移台账（与 `forma migrate up --execute` 共享）──
# 基线 CREATE TABLE 非幂等：容器重启或 CLI 已执行过时必须跳过，否则 ERROR 1050。
MIGRATION_DDL="CREATE TABLE IF NOT EXISTS forma_migrations (
  name VARCHAR(191) NOT NULL PRIMARY KEY,
  applied_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
mysql -h "$DB_HOST" -u "$DB_USER" -p"$DB_PASS" "$DB_NAME" -e "$MIGRATION_DDL"

# ── 按序执行尚未应用的迁移 ──
# 任一失败必须让容器启动失败（吞错会让 schema 不完整却照常启动）。
echo "[entrypoint] running migrations..."
for f in /app/migrations/*_init.sql /app/migrations/*_upgrade.sql; do
  [ -f "$f" ] || continue
  name=$(basename "$f")
  done_count=$(mysql -N -B -h "$DB_HOST" -u "$DB_USER" -p"$DB_PASS" "$DB_NAME" \
    -e "SELECT COUNT(*) FROM forma_migrations WHERE name = '$name'" 2>/dev/null)
  if [ "$done_count" != "0" ]; then
    echo "  → $name (already applied, skip)"
    continue
  fi
  echo "  → $name"
  if ! mysql -h "$DB_HOST" -u "$DB_USER" -p"$DB_PASS" "$DB_NAME" < "$f"; then
    echo "[entrypoint] migration failed: $f" >&2
    exit 1
  fi
  mysql -h "$DB_HOST" -u "$DB_USER" -p"$DB_PASS" "$DB_NAME" \
    -e "INSERT IGNORE INTO forma_migrations (name) VALUES ('$name')"
done

# ── 种子数据（可选；INSERT IGNORE 幂等，失败只告警不阻断）──
if [ -d /app/migrations/../seed ]; then
  for f in /app/migrations/../seed/*.sql; do
    [ -f "$f" ] || continue
    echo "  → seed: $(basename "$f")"
    mysql -h "$DB_HOST" -u "$DB_USER" -p"$DB_PASS" "$DB_NAME" < "$f" \
      || echo "[entrypoint] warning: seed failed: $f" >&2
  done
fi

echo "[entrypoint] starting server on port ${PORT:-8080}"
exec "$@"
"#;
    files.push(crate::generators::GeneratedFile {
        path: format!("{out_dir}/generated/backend/entrypoint.sh"),
        content: entrypoint.to_string(),
        generator: "gen-docker".into(),
    });

    // ── .dockerignore ──
    // Docker 从 build context 根目录读取 .dockerignore；compose 的 context 是项目根，
    // 所以这里必须落在项目根（放在 generated/backend/ 会被 Docker 忽略，踩过）。
    // 不能排除 generated/ 与 db/——Dockerfile 要 COPY 它们。
    let dockerignore = r#"# @generated by Forma (gen-docker) — do not edit manually.
target/
node_modules/
.git/
.dart_tool/
.env
*.md
"#;
    files.push(crate::generators::GeneratedFile {
        path: format!("{out_dir}/.dockerignore"),
        content: dockerignore.to_string(),
        generator: "gen-docker".into(),
    });

    // ── docker-compose.yml ──
    let compose = generate_compose(project_dir, program, app_name, &db_name, has_auth, has_seed);
    files.push(crate::generators::GeneratedFile {
        path: format!("{out_dir}/docker-compose.yml"),
        content: compose,
        generator: "gen-docker".into(),
    });

    // Docker emitter follows the existing emitter contract: return files for the build report
    // **and** write them to disk (the build pipeline itself only aggregates files).
    for f in &files {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(files)
}

/// docker-compose.yml：MySQL 8 + backend（+ 可选 web dev server）。
fn generate_compose(
    _project_dir: &Path,
    program: &Program,
    _app_name: &str,
    db_name: &str,
    _has_auth: bool,
    _has_seed: bool,
) -> String {
    let mut services = String::new();

    services.push_str("  db:\n    image: mysql:8\n    environment:\n      MYSQL_ROOT_PASSWORD: ${MYSQL_ROOT_PASSWORD:?set MYSQL_ROOT_PASSWORD (compose 不内嵌默认口令)}\n      MYSQL_DATABASE: ");
    services.push_str(db_name);
    services.push_str("\n    command: --character-set-server=utf8mb4 --collation-server=utf8mb4_unicode_ci\n    ports:\n      - \"3306:3306\"\n    volumes:\n      - db_data:/var/lib/mysql\n    healthcheck:\n      test: [\"CMD\", \"mysqladmin\", \"ping\", \"-h\", \"localhost\"]\n      interval: 5s\n      timeout: 3s\n      retries: 10\n");

    services.push_str(&format!("\n  backend:\n    build:
      context: .
      dockerfile: generated/backend/Dockerfile\n    ports:\n      - \"8080:8080\"\n    environment:\n      DATABASE_URL: mysql://root:${{MYSQL_ROOT_PASSWORD:?set MYSQL_ROOT_PASSWORD}}@db:3306/{db_name}\n      DB_HOST: db\n      DB_USER: root\n      DB_PASS: ${{MYSQL_ROOT_PASSWORD:?set MYSQL_ROOT_PASSWORD}}\n      DB_NAME: {db_name}\n    depends_on:\n      db:\n        condition: service_healthy\n", db_name = db_name));

    let has_web = !program.pages.is_empty();
    if has_web {
        services.push_str("\n  web:\n    image: node:20-slim\n    working_dir: /app\n    command: sh -c \"npm install && npm run dev -- --host 0.0.0.0\"\n    ports:\n      - \"5173:5173\"\n    volumes:\n      - ./generated/web:/app\n    environment:\n      VITE_API_BASE: http://backend:8080/api\n    depends_on:\n      - backend\n");
    }

    let has_web_note = if has_web { " + Web dev server" } else { "" };
    let mut out = String::from("# @generated by Forma (gen-docker) — do not edit manually.\n");
    out.push_str(&format!(
        "# docker-compose up --build → 启动 MySQL + backend{}\n\n",
        has_web_note
    ));
    out.push_str("services:\n");
    out.push_str(&services);
    out.push_str("\nvolumes:\n  db_data:\n");
    out
}
