//! SQLite target（M10）：Program → SQLite 3 DDL。
//!
//! 与 MySQL/PostgreSQL 共享 DSL 表拓扑与约束语义，但独立渲染 SQLite 方言：
//! UUID/DateTime/Decimal/JSON 采用 TEXT/NUMERIC 亲和性；Bool 采用 INTEGER CHECK；
//! 不输出 PostgreSQL/MySQL 专有语法。

use super::mysql::{plan_tables, ColumnPlan, TablePlan};
use crate::dsl::{is_enum, is_relation, FieldDecl, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

pub fn sqlite_type(program: &Program, field: &FieldDecl) -> String {
    match field.type_name.as_str() {
        // SQLite 无原生 UUID / 时间 / JSON 类型；TEXT 保留序列化契约。
        "Uuid" => "TEXT".into(),
        "String" | "Email" | "Text" => "TEXT".into(),
        "Int" => "INTEGER".into(),
        "Float" => "REAL".into(),
        "Decimal" => "NUMERIC".into(),
        "Bool" => "INTEGER".into(),
        "Timestamp" | "Date" => "TEXT".into(),
        "Json" => "TEXT".into(),
        other if is_enum(program, other) => "TEXT".into(),
        _ if is_relation(program, &field.type_name) => "TEXT".into(),
        _ => "TEXT".into(),
    }
}

fn column_sql(program: &Program, entity: &crate::dsl::EntityDecl, col: &ColumnPlan) -> String {
    let field_name = col.name.strip_suffix("_id").unwrap_or(&col.name);
    let ty = entity
        .fields
        .iter()
        .find(|f| to_snake_case(&f.name) == field_name)
        .map(|f| sqlite_type(program, f))
        .unwrap_or_else(|| col.sql_type.clone());
    let mut out = format!("{} {}", col.name, ty);
    if col.name == table_pk(entity) {
        out.push_str(" PRIMARY KEY");
    }
    if !col.nullable {
        out.push_str(" NOT NULL");
    }
    out
}

fn table_pk(entity: &crate::dsl::EntityDecl) -> String {
    entity
        .fields
        .iter()
        .find(|f| crate::dsl::has_attr(f, "id"))
        .map(|f| to_snake_case(&f.name))
        .unwrap_or_else(|| "id".into())
}

fn render_table(program: &Program, entity: &crate::dsl::EntityDecl, table: &TablePlan) -> String {
    let mut out = format!("CREATE TABLE IF NOT EXISTS {} (\n", table.table);
    let mut defs: Vec<String> = table
        .columns
        .iter()
        .map(|c| format!("    {}", column_sql(program, entity, c)))
        .collect();
    // SQLite 的列级 PRIMARY KEY 已在 column_sql 中处理；复合/非标准主键仍补表级约束。
    if table.primary_key.contains(',') {
        defs.push(format!("    PRIMARY KEY ({})", table.primary_key));
    }
    for unique in &table.uniques {
        defs.push(format!("    UNIQUE ({})", unique.join(", ")));
    }
    for fk in &table.fks {
        defs.push(format!(
            "    FOREIGN KEY ({}) REFERENCES {} (id)",
            fk.column, fk.ref_table
        ));
    }
    out.push_str(&defs.join(",\n"));
    out.push_str("\n);\n\n");
    for idx in &table.indexes {
        out.push_str(&format!(
            "CREATE INDEX IF NOT EXISTS idx_{}_{} ON {} ({});\n",
            table.table,
            idx.join("_"),
            table.table,
            idx.join(", ")
        ));
    }
    out
}

pub fn emit_sqlite(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    let plans = plan_tables(program);
    let mut sql = String::from(
        "-- @generated by Forma (gen-sqlite) — do not edit manually.\n-- SQLite 3\n\nPRAGMA foreign_keys = ON;\n\n",
    );
    for table in &plans {
        let entity = program
            .entities
            .iter()
            .find(|e| e.name == table.entity)
            .ok_or_else(|| {
                anyhow::anyhow!("table plan references unknown entity {}", table.entity)
            })?;
        sql.push_str(&render_table(program, entity, table));
    }
    let file = GeneratedFile {
        path: format!("{out_dir}/0001_init.sql"),
        content: sql,
        generator: "gen-sqlite".into(),
    };
    crate::util::write_text(&project_dir.join(&file.path), &file.content)?;
    Ok(vec![file])
}

pub fn emit_sqlite_migration(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    let plans = plan_tables(program);
    let mut sql = String::from(
        "-- @generated by Forma (gen-sqlite) — upgrade migration\n\nPRAGMA foreign_keys = ON;\n\n",
    );
    for table in &plans {
        let entity = program
            .entities
            .iter()
            .find(|e| e.name == table.entity)
            .ok_or_else(|| anyhow::anyhow!("unknown entity {}", table.entity))?;
        sql.push_str(&render_table(program, entity, table));
    }
    let file = GeneratedFile {
        path: format!("{out_dir}/migrations/0001_upgrade.sql"),
        content: sql,
        generator: "gen-sqlite".into(),
    };
    crate::util::write_text(&project_dir.join(&file.path), &file.content)?;
    Ok(vec![file])
}
