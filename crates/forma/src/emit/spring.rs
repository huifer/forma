fn reject_unsupported(program: &Program) -> anyhow::Result<()> {
    let mut bad = Vec::new();
    if program.auth.is_some() {
        bad.push("auth module");
    }
    if !program.commands.is_empty() {
        bad.push("command operations");
    }
    if program
        .rules
        .iter()
        .any(|r| !r.access.is_empty() || !r.guards.is_empty() || !r.checks.is_empty())
    {
        bad.push("access/field rules");
    }
    if crate::dsl::tenant_enabled(program) {
        bad.push("@tenant");
    }
    if bad.is_empty() {
        Ok(())
    } else {
        anyhow::bail!(
            "Spring Boot target does not support: {} (use backend.language: rust for full semantics)",
            bad.join(", ")
        )
    }
}

fn java_type(program: &Program, f: &FieldDecl) -> &'static str {
    match f.type_name.as_str() {
        "Uuid" | "String" | "Email" | "Text" | "Json" => "String",
        "Int" => "Long",
        "Float" => "Double",
        "Decimal" => "BigDecimal",
        "Bool" => "Boolean",
        "Timestamp" | "Date" => "Instant",
        other if is_enum(program, other) => "String",
        _ if is_relation(program, &f.type_name) => "String",
        _ => "String",
    }
}

fn column_name(program: &Program, f: &FieldDecl) -> String {
    let n = to_snake_case(&f.name);
    if is_relation(program, &f.type_name) {
        format!("{n}_id")
    } else {
        n
    }
}

fn imports_for(program: &Program, entity: &crate::dsl::EntityDecl) -> String {
    let mut imports = vec![
        "import jakarta.persistence.*;".to_string(),
        "import java.math.BigDecimal;".to_string(),
        "import java.time.Instant;".to_string(),
    ];
    let _ = (program, entity, &mut imports);
    imports.join("\n")
}

fn entity_source(program: &Program, entity: &crate::dsl::EntityDecl, pkg: &str) -> String {
    let table = to_snake_case(&crate::dsl::pluralize(&entity.name));
    let mut s = format!(
        "// @generated by Forma (gen-spring) — do not edit manually.\npackage {pkg}.{e};\n\n{imports}\n\n@Entity\n@Table(name = \"{table}\")\npublic class {cls} {{\n",
        pkg = pkg,
        e = to_snake_case(&entity.name),
        imports = imports_for(program, entity),
        table = table,
        cls = entity.name,
    );
    for f in &entity.fields {
        let col = column_name(program, f);
        if has_attr(f, "id") {
            s.push_str("    @Id\n");
        }
        s.push_str(&format!("    @Column(name = \"{}\")\n", col));
        s.push_str(&format!(
            "    private {} {};\n\n",
            java_type(program, f),
            to_snake_case(&f.name)
        ));
    }
    // getters/setters
    for f in &entity.fields {
        let n = to_snake_case(&f.name);
        let t = java_type(program, f);
        s.push_str(&format!(
            "    public {t} get{Cap}() {{ return {n}; }}\n    public void set{Cap}({t} v) {{ this.{n} = v; }}\n\n",
            t = t,
            Cap = capitalize(&n),
            n = n,
        ));
    }
    s.push_str("}\n");
    s
}

fn capitalize(s: &str) -> String {
    let mut cs = s.chars();
    match cs.next() {
        Some(c) => c.to_uppercase().collect::<String>() + cs.as_str(),
        None => String::new(),
    }
}

fn dto_source(program: &Program, entity: &crate::dsl::EntityDecl, pkg: &str) -> String {
    let mut s = format!(
        "// @generated by Forma (gen-spring) — do not edit manually.\npackage {pkg}.{e};\n\nimport java.math.BigDecimal;\nimport java.time.Instant;\n\npublic class {cls}Dto {{\n",
        pkg = pkg,
        e = to_snake_case(&entity.name),
        cls = entity.name
    );
    for f in &entity.fields {
        if has_attr(f, "id") || has_attr(f, "readonly") {
            continue;
        }
        let n = to_snake_case(&f.name);
        s.push_str(&format!("    private {} {};\n", java_type(program, f), n));
    }
    s.push('\n');
    for f in &entity.fields {
        if has_attr(f, "id") || has_attr(f, "readonly") {
            continue;
        }
        let n = to_snake_case(&f.name);
        let t = java_type(program, f);
        s.push_str(&format!(
            "    public {t} get{Cap}() {{ return {n}; }}\n    public void set{Cap}({t} v) {{ this.{n} = v; }}\n",
            t = t, Cap = capitalize(&n), n = n
        ));
    }
    s.push_str("}\n");
    s
}

fn repository_source(entity: &crate::dsl::EntityDecl, pkg: &str) -> String {
    format!(
        "// @generated by Forma (gen-spring) — do not edit manually.\npackage {pkg}.{e};\n\nimport org.springframework.data.jpa.repository.JpaRepository;\nimport org.springframework.stereotype.Repository;\n\n@Repository\npublic interface {cls}Repository extends JpaRepository<{cls}, String> {{\n}}\n",
        pkg = pkg,
        e = to_snake_case(&entity.name),
        cls = entity.name
    )
}

fn controller_source(program: &Program, entity: &crate::dsl::EntityDecl, pkg: &str) -> String {
    let e = to_snake_case(&entity.name);
    let cls = &entity.name;
    let plural = to_snake_case(&crate::dsl::pluralize(&entity.name));
    let mut s = format!(
        r#"// @generated by Forma (gen-spring) — do not edit manually.
package {pkg}.{e};

import org.springframework.web.bind.annotation.*;
import org.springframework.data.domain.*;
import java.util.List;

@RestController
@RequestMapping("/api/{plural}")
public class {cls}Controller {{
    private final {cls}Repository repo;
    public {cls}Controller({cls}Repository repo) {{ this.repo = repo; }}

    @GetMapping
    public List<{cls}> list(
        @RequestParam(defaultValue = "1") int page,
        @RequestParam(defaultValue = "20") int pageSize
    ) {{
        return repo.findAll(PageRequest.of(Math.max(0, page - 1), pageSize)).getContent();
    }}

    @GetMapping("/{{id}}")
    public {cls} get(@PathVariable String id) {{ return repo.findById(id).orElseThrow(); }}

    @PostMapping
    public {cls} create(@RequestBody {cls}Dto dto) {{
        {cls} row = new {cls}();
__CREATE_BINDS__        row.setId(java.util.UUID.randomUUID().toString());
        row.setCreatedAt(Instant.now());
        return repo.save(row);
    }}

    @PutMapping("/{{id}}")
    public {cls} update(@PathVariable String id, @RequestBody {cls}Dto dto) {{
        {cls} row = repo.findById(id).orElseThrow();
__UPDATE_BINDS__        return repo.save(row);
    }}

    @DeleteMapping("/{{id}}")
    public void delete(@PathVariable String id) {{ repo.deleteById(id); }}
}}
"#,
        pkg = pkg,
        e = e,
        cls = cls,
        plural = plural,
    );
    let mut binds = String::new();
    let mut upd = String::new();
    for f in &entity.fields {
        if has_attr(f, "id") || has_attr(f, "readonly") {
            continue;
        }
        let n = to_snake_case(&f.name);
        let cap = capitalize(&n);
        binds.push_str(&format!("        row.set{cap}(dto.get{cap}());\n"));
        upd.push_str(&format!("        row.set{cap}(dto.get{cap}());\n"));
        let _ = program;
    }
    s = s
        .replace("__CREATE_BINDS__", &binds)
        .replace("__UPDATE_BINDS__", &upd);
    s
}

