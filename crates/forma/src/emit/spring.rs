//! Spring Boot target（轨道 B 重新排期）：Program → Spring Boot 3 + JPA CRUD 后端。
//!
//! 与 NestJS/Hono/FastAPI 同属「有限但真实」子集：标量字段、枚举、关系外键、
//! CRUD、offset 列表、字段 required 校验；显式拒绝 auth/access/tenant/commands/
//! 跨字段 rules（不能静默降级安全语义，见 reject_unsupported）。
//!
//! 产物：Maven 工程（pom.xml）+ Application + 每实体 Entity/DTO/Repository/Controller，
//! 数据库物理契约沿用 `{rel}_id` / 文本 UUID（与 MySQL DDL 一致）。

use crate::dsl::{has_attr, is_enum, is_relation, FieldDecl, Program};
