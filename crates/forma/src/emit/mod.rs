/// RFC-0007 §16 / P3·G-6：Markdown 产物的 `@generated` 头。
///
/// JSON 等不支持注释的格式（如 `package.json`）按 [spec:serialization] 决议豁免——
/// 所有权与完整性由 artifacts manifest 的内容哈希保障，不在产物内伪造注释。
pub fn generated_md_header(generator: &str) -> String {
    format!(
        "<!-- @generated by Forma ({generator}) — do not edit manually. Regenerate with: forma build -->\n\n"
    )
}
