//! PostgreSQL target（M10）：Program → PostgreSQL 15+ DDL。
//!
//! 与 MySQL 共享 DSL `TablePlan` 的拓扑与约束语义，但独立渲染 PostgreSQL 方言：
//! UUID / JSONB / BOOLEAN / TIMESTAMPTZ / NUMERIC；不复用 MySQL 反引号、TINYINT、DOUBLE。

use super::mysql::{plan_tables, ColumnPlan, TablePlan};
use crate::dsl::{is_enum, is_relation, FieldDecl, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

pub fn postgres_type(program: &Program, field: &FieldDecl) -> String {
    match field.type_name.as_str() {
        "Uuid" => "UUID".into(),
        "String" => {
            let n = field
                .type_args
                .first()
                .and_then(|v| v.parse::<usize>().ok())
                .unwrap_or(255);
            format!("VARCHAR({n})")
        }
        "Email" => "VARCHAR(320)".into(),
        "Text" => "TEXT".into(),
        "Int" => "BIGINT".into(),
        "Float" => "DOUBLE PRECISION".into(),
        "Decimal" => {
            let p = field
                .type_args
                .first()
                .and_then(|v| v.parse::<usize>().ok())
                .unwrap_or(12);
            let s = field
                .type_args
                .get(1)
                .and_then(|v| v.parse::<usize>().ok())
                .unwrap_or(2);
            format!("NUMERIC({p},{s})")
        }
        "Bool" => "BOOLEAN".into(),
        "Timestamp" => "TIMESTAMPTZ".into(),
        "Date" => "DATE".into(),
        "Json" => "JSONB".into(),
        other if is_enum(program, other) => "VARCHAR(64)".into(),
        _ if is_relation(program, &field.type_name) => "UUID".into(),
        _ => "TEXT".into(),
    }
}

fn column_sql(program: &Program, entity: &crate::dsl::EntityDecl, col: &ColumnPlan) -> String {
    let field_name = col.name.strip_suffix("_id").unwrap_or(&col.name);
    let ty = entity
        .fields
        .iter()
        .find(|f| to_snake_case(&f.name) == field_name)
        .map(|f| postgres_type(program, f))
        .unwrap_or_else(|| col.sql_type.clone());
    format!(
        "{} {}{}",
        col.name,
        ty,
        if col.nullable { "" } else { " NOT NULL" }
    )
}

fn render_table(program: &Program, entity: &crate::dsl::EntityDecl, table: &TablePlan) -> String {
    let mut out = format!("CREATE TABLE IF NOT EXISTS {} (\n", table.table);
    let mut defs: Vec<String> = table
        .columns
        .iter()
        .map(|c| format!("    {}", column_sql(program, entity, c)))
        .collect();
    defs.push(format!("    PRIMARY KEY ({})", table.primary_key));
    for unique in &table.uniques {
        defs.push(format!("    UNIQUE ({})", unique.join(", ")));
    }
    for fk in &table.fks {
        defs.push(format!(
            "    FOREIGN KEY ({}) REFERENCES {} (id)",
            fk.column, fk.ref_table
        ));
    }
    out.push_str(&defs.join(",\n"));
    out.push_str("\n);\n\n");
    for idx in &table.indexes {
        out.push_str(&format!(
            "CREATE INDEX IF NOT EXISTS idx_{}_{} ON {} ({});\n",
            table.table,
            idx.join("_"),
            table.table,
            idx.join(", ")
        ));
    }
    out
}

pub fn emit_postgres(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    let plans = plan_tables(program);
    let mut sql = String::from(
        "-- @generated by Forma (gen-postgres) — do not edit manually.\n-- PostgreSQL 15+\n\n",
    );
    for table in &plans {
        let entity = program
            .entities
            .iter()
            .find(|e| e.name == table.entity)
            .ok_or_else(|| {
                anyhow::anyhow!("table plan references unknown entity {}", table.entity)
            })?;
        sql.push_str(&render_table(program, entity, table));
    }
    let file = GeneratedFile {
        path: format!("{out_dir}/0001_init.sql"),
        content: sql,
        generator: "gen-postgres".into(),
    };
    crate::util::write_text(&project_dir.join(&file.path), &file.content)?;
    Ok(vec![file])
}

/// PostgreSQL 迁移增量（简化：全量 schema diff → CREATE TABLE IF NOT EXISTS 幂等）。
pub fn emit_postgres_migration(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    let plans = plan_tables(program);
    let mut sql = String::from("-- @generated by Forma (gen-postgres) — upgrade migration\n\n");
    for table in &plans {
        let entity = program
            .entities
            .iter()
            .find(|e| e.name == table.entity)
            .ok_or_else(|| anyhow::anyhow!("unknown entity {}", table.entity))?;
        sql.push_str(&render_table(program, entity, table));
    }
    let file = GeneratedFile {
        path: format!("{out_dir}/migrations/0001_upgrade.sql"),
        content: sql,
        generator: "gen-postgres".into(),
    };
    crate::util::write_text(&project_dir.join(&file.path), &file.content)?;
    Ok(vec![file])
}
