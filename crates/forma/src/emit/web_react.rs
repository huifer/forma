//! web-react 适配层：Program → 可运行的 React + TanStack Router/Query + shadcn 风格前端工程。

use super::Program;
use crate::util::{sha256_hex, write_text};
use anyhow::Result;
use std::path::Path;

pub fn emit_web_react(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> Result<Vec<crate::generators::GeneratedFile>> {
    if program.entities.is_empty() || program.pages.is_empty() {
        return Ok(vec![]);
    }
    let mut files: Vec<crate::generators::GeneratedFile> = Vec::new();
    let title = program
        .app
        .as_ref()
        .map(|a| a.name.clone())
        .unwrap_or_else(|| app_name.to_string());

    files.push(file(
        out_dir,
        "package.json",
        package_json(app_name, !program.charts.is_empty()),
        "gen-web",
    ));
    files.push(file(out_dir, "vite.config.ts", vite_config(), "gen-web"));
    files.push(file(out_dir, "tsconfig.json", tsconfig(), "gen-web"));
    files.push(file(out_dir, "index.html", index_html(&title), "gen-web"));
    files.push(file(out_dir, "src/main.tsx", main_tsx(), "gen-web"));
    files.push(file(out_dir, "src/types.ts", types_ts(program), "gen-web"));
    files.push(file(
        out_dir,
        "src/validators.ts",
        validators_ts(program),
        "gen-web",
    ));
    files.push(file(out_dir, "src/api.ts", api_ts(program), "gen-web"));
    files.push(file(out_dir, "src/ui.tsx", ui_tsx(), "gen-web"));
    files.push(file(out_dir, "src/ui.css", ui_css(), "gen-web"));
    files.push(file(
        out_dir,
        "src/format.ts",
        format_ts(program),
        "gen-web",
    ));

    for page in &program.pages {
        let content = match &page.body {
            crate::dsl::PageBody::Table(t) => list_page(program, page, t),
            crate::dsl::PageBody::Form(f) => edit_page(program, page, f),
            crate::dsl::PageBody::Detail(d) => detail_page(program, page, d),
            crate::dsl::PageBody::Chart(c) => chart_page(program, page, c),
        };
        files.push(file(
            out_dir,
            &format!("src/pages/{}.tsx", page.name),
            content,
            "gen-web",
        ));
    }

    files.push(file(
        out_dir,
        "src/layout.tsx",
        layout_tsx(program),
        "gen-web",
    ));
    files.push(file(
        out_dir,
        "src/router.tsx",
        router_tsx(program),
        "gen-web",
    ));
    files.push(file(
        out_dir,
        "README.md",
        format!(
            "# {title} web (generated by Forma)\n\n```bash\nnpm install\nnpm run dev\n```\n需同时运行后端（Vite 已代理 /api → http://localhost:8080）。\n"
        ),
        "gen-web",
    ));

    let mut written = Vec::new();
    for f in files {
        let abs = project_dir.join(&f.path);
        let hash = sha256_hex(&f.content);
        let unchanged = abs.is_file()
            && crate::util::read_text(&abs)
                .map(|c| sha256_hex(&c) == hash)
                .unwrap_or(false);
        if !unchanged {
            write_text(&abs, &f.content)?;
        }
        written.push(f);
    }
    Ok(written)
}

fn file(
    out_dir: &str,
    rel: &str,
    content: String,
    generator: &str,
) -> crate::generators::GeneratedFile {
    crate::generators::GeneratedFile {
        path: format!("{out_dir}/{rel}"),
        content,
        generator: generator.into(),
    }
}

