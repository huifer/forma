pub fn emit_web_react(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
    uses_rhf: bool,
    uses_zustand: bool,
) -> Result<Vec<crate::generators::GeneratedFile>> {
    if program.entities.is_empty() || program.pages.is_empty() {
        return Ok(vec![]);
    }
    let mut files: Vec<crate::generators::GeneratedFile> = Vec::new();
    let title = program
        .app
        .as_ref()
        .map(|a| a.name.clone())
        .unwrap_or_else(|| app_name.to_string());

    files.push(file(
        out_dir,
        "package.json",
        package_json(app_name, needs_echarts(program), uses_rhf, uses_zustand),
        "gen-web",
    ));
    files.push(file(out_dir, "vite.config.ts", vite_config(), "gen-web"));
    files.push(file(out_dir, "tsconfig.json", tsconfig(), "gen-web"));
    // M9/P1：zustand store（列表过滤/搜索状态，从页面数据依赖派生）
    if uses_zustand {
        if let Some(store) = store_ts(program) {
            files.push(file(out_dir, "src/store.ts", store, "gen-web"));
        }
    }
    files.push(file(out_dir, "index.html", index_html(&title), "gen-web"));
    files.push(file(out_dir, "src/main.tsx", main_tsx(), "gen-web"));
    files.push(file(out_dir, "src/types.ts", types_ts(program), "gen-web"));
    files.push(file(
        out_dir,
        "src/validators.ts",
        validators_ts(program),
        "gen-web",
    ));
    // 规则一致性向量 · Web 端行为测试（F-004；vitest 执行）
    if let Some(test) = validators_test_ts(program) {
        files.push(file(out_dir, "src/validators.test.ts", test, "gen-web"));
    }
    files.push(file(out_dir, "src/api.ts", api_ts(program), "gen-web"));
    // 授权规则 + 角色感知 hook（操作级规则或字段级策略任一存在时生成）
    if !frontend_access_rules(program).is_empty()
        || !crate::dsl::field_policy_roles(program).is_empty()
    {
        files.push(file(
            out_dir,
            "src/access.ts",
            access_ts(program),
            "gen-web",
        ));
    }
    files.push(file(out_dir, "src/ui.tsx", ui_tsx(), "gen-web"));
    files.push(file(out_dir, "src/ui.css", ui_css(), "gen-web"));
    files.push(file(
        out_dir,
        "src/format.ts",
        format_ts(program),
        "gen-web",
    ));

    // 认证：登录页
    if program.auth.is_some() {
        files.push(file(
            out_dir,
            "src/pages/Login.tsx",
            login_page(program),
            "gen-web",
        ));
    }

    for page in &program.pages {
        let content = match &page.body {
            crate::dsl::PageBody::Table(t) => list_page(program, page, t, uses_zustand),
            crate::dsl::PageBody::Form(f) => edit_page(program, page, f, uses_rhf),
            crate::dsl::PageBody::Detail(d) => detail_page(program, page, d),
            crate::dsl::PageBody::Chart(c) => chart_page(program, page, c),
        };
        files.push(file(
            out_dir,
            &format!("src/pages/{}.tsx", page.name),
            content,
            "gen-web",
        ));
    }

    files.push(file(
        out_dir,
        "src/layout.tsx",
        layout_tsx(program),
        "gen-web",
    ));
    files.push(file(
        out_dir,
        "src/router.tsx",
        router_tsx(program),
        "gen-web",
    ));
    files.push(file(
        out_dir,
        "README.md",
        format!(
            "# {title} web (generated by Forma)\n\n```bash\nnpm install\nnpm run dev\n```\n需同时运行后端（Vite 已代理 /api → http://localhost:8080）。\n"
        ),
        "gen-web",
    ));

    let mut written = Vec::new();
    for f in files {
        let abs = project_dir.join(&f.path);
        let hash = sha256_hex(&f.content);
        let unchanged = abs.is_file()
            && crate::util::read_text(&abs)
                .map(|c| sha256_hex(&c) == hash)
                .unwrap_or(false);
        if !unchanged {
            write_text(&abs, &f.content)?;
        }
        written.push(f);
    }
    Ok(written)
}

fn file(
    out_dir: &str,
    rel: &str,
    content: String,
    generator: &str,
) -> crate::generators::GeneratedFile {
    crate::generators::GeneratedFile {
        path: format!("{out_dir}/{rel}"),
        content,
        generator: generator.into(),
    }
}

/// 工程是否需要 ECharts（V0.2：metric/table widget 由 React 组件渲染，不需要 echarts）。
fn needs_echarts(program: &Program) -> bool {
    program
        .charts
        .iter()
        .any(|c| !matches!(c.chart_type.as_str(), "metric" | "table"))
}

