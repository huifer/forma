// ── 类型映射 ────────────────────────────────────────────

fn ts_type(program: &Program, type_name: &str, optional: bool) -> String {
    let base = match type_name {
        "Uuid" | "String" | "Email" | "Text" | "Timestamp" | "Date" => "string".to_string(),
        "Int" | "Float" => "number".to_string(),
        "Decimal" => "string".to_string(),
        "Bool" => "boolean".to_string(),
        "Json" => "unknown".to_string(),
        other => {
            if super::is_enum(program, other) {
                let Some(e) = program.enums.iter().find(|e| e.name == other) else {
                    return "string".to_string();
                };
                let variants: Vec<String> = e
                    .variants
                    .iter()
                    .map(|v| format!("\"{}\"", v.name))
                    .collect();
                return variants.join(" | ");
            }
            "string".to_string()
        }
    };
    if optional {
        format!("{base} | null")
    } else {
        base
    }
}

fn types_ts(program: &Program) -> String {
    let mut out = String::from("// @generated by Forma (gen-web) — do not edit manually.\n\n");
    for e in &program.enums {
        let variants: Vec<String> = e
            .variants
            .iter()
            .map(|v| format!("\"{}\"", v.name))
            .collect();
        out.push_str(&format!(
            "export type {} = {};\n",
            e.name,
            variants.join(" | ")
        ));
    }
    out.push('\n');
    for entity in &program.entities {
        let mut fields = String::new();
        for f in &entity.fields {
            let name = crate::identity::to_snake_case(&f.name);
            if super::is_relation(program, &f.type_name) {
                fields.push_str(&format!("  {name}: string;\n"));
            } else {
                fields.push_str(&format!(
                    "  {name}: {};\n",
                    ts_type(program, &f.type_name, f.optional)
                ));
            }
        }
        out.push_str(&format!(
            "export interface {} {{\n{}}}\n\n",
            entity.name, fields
        ));

        let mut row_fields = fields.clone();
        for f in &entity.fields {
            if super::is_relation(program, &f.type_name) {
                let name = crate::identity::to_snake_case(&f.name);
                row_fields.push_str(&format!("  {name}_name: string | null;\n"));
            }
        }
        out.push_str(&format!(
            "export interface {}ListRow extends {} {{\n{}}}\n\n",
            entity.name, entity.name, row_fields
        ));

        out.push_str(&format!(
            "export interface Create{} {{\n{}}}\n\n",
            entity.name,
            input_ts(program, entity)
        ));
        out.push_str(&format!(
            "export interface Update{} {{\n{}}}\n\n",
            entity.name,
            input_ts(program, entity)
        ));
    }
    out
}

/// 表单/API 输入侧字段（id 除外；readonly/default 字段可空）
fn input_ts(program: &Program, entity: &crate::dsl::EntityDecl) -> String {
    let mut out = String::new();
    for f in &entity.fields {
        if super::has_attr(f, "id") {
            continue;
        }
        let name = crate::identity::to_snake_case(&f.name);
        if super::is_relation(program, &f.type_name) {
            let t = if f.optional {
                "string | null"
            } else {
                "string"
            };
            out.push_str(&format!("  {name}: {t};\n"));
            continue;
        }
        let readonly = super::has_attr(f, "readonly");
        let has_default = super::has_attr(f, "default");
        let base = ts_type(program, &f.type_name, false);
        if f.optional || has_default || readonly {
            out.push_str(&format!("  {name}: {base} | null;\n"));
        } else {
            out.push_str(&format!("  {name}: {base};\n"));
        }
    }
    out
}

// ── api.ts ──────────────────────────────────────────────

fn api_ts(program: &Program) -> String {
    let mut out = String::from("// @generated by Forma (gen-web) — do not edit manually.\n\n");
    let mut imports = String::from("import {\n");
    for entity in &program.entities {
        imports.push_str(&format!(
            "  {},\n  {}ListRow,\n  Create{},\n  Update{},\n",
            entity.name, entity.name, entity.name, entity.name
        ));
    }
    imports.push_str("} from \"./types\";\n\n");
    out.push_str(&imports);

    out.push_str(
        r#"const base = "/api";

export interface FieldError { field: string; message: string }

async function req<T>(url: string, init?: RequestInit): Promise<T> {
  const res = await fetch(url, { headers: { "Content-Type": "application/json" }, ...init });
  if (!res.ok) {
    const body = await res.json().catch(() => ({}) as any);
    const err = new Error(body.error ?? res.statusText) as any;
    err.status = res.status;
    err.fields = body.fields as FieldError[] | undefined;
    throw err;
  }
  if (res.status === 204) return undefined as T;
  return res.json() as Promise<T>;
}

function qs(params: Record<string, unknown>): string {
  const usp = new URLSearchParams();
  for (const [k, v] of Object.entries(params)) {
    if (v === null || v === undefined || v === "") continue;
    usp.set(k, String(v));
  }
  const s = usp.toString();
  return s ? `?${s}` : "";
}
"#,
    );
    out.push('\n');

    for entity in &program.entities {
        let name = &entity.name;
        let plural = crate::identity::to_snake_case(&super::pluralize(name));
        let mut params_fields = String::new();
        if let Some(api) = program.apis.iter().find(|a| a.entity == *name) {
            if let Some(list) = &api.list {
                for (f, contains) in &list.filters {
                    let pname = crate::identity::to_snake_case(f);
                    let suffix = if *contains { "_contains" } else { "" };
                    params_fields
                        .push_str(&format!("  {pname}{suffix}?: string | number | null;\n"));
                }
            }
        }
        out.push_str(&format!(
            "export interface {name}ListParams {{\n  page?: number;\n  pageSize?: number;\n  q?: string | null;\n{params_fields}}}\n\n"
        ));
        out.push_str(&format!(
            "export const {name}Api = {{\n  list: (p: {name}ListParams = {{}}) =>\n    req<{name}ListRow[]>(`/api/{plural}${{qs(p as Record<string, unknown>)}}`),\n  get: (id: string) => req<{name}>(`/api/{plural}/${{id}}`),\n  create: (input: Create{name}) => req<{name}>(`/api/{plural}`, {{ method: \"POST\", body: JSON.stringify(input) }}),\n  update: (id: string, input: Update{name}) => req<{name}>(`/api/{plural}/${{id}}`, {{ method: \"PUT\", body: JSON.stringify(input) }}),\n  remove: (id: string) => req<{{ ok: boolean }}>(`/api/{plural}/${{id}}`, {{ method: \"DELETE\" }}),\n}};\n\n"
        ));
    }
    // api 块名别名（页面 submit/query 以块名引用）
    for api in &program.apis {
        let entity_api = format!("{}Api", api.entity);
        out.push_str(&format!(
            "export const {}Api = {};// alias\n",
            api.name, entity_api
        ));
    }
    out.push_str(&commands_api_ts(program));
    out
}

/// 命令类操作（spec §10）：输入接口 + execute 客户端。
fn commands_api_ts(program: &Program) -> String {
    let mut out = String::new();
    for cmd in &program.commands {
        let mut fields = String::new();
        for input in &cmd.input {
            let col = crate::identity::to_snake_case(&input.name);
            let base = match input.type_name.as_str() {
                "Int" | "Float" => "number".to_string(),
                "Bool" => "boolean".to_string(),
                "Decimal" => "string".to_string(),
                "Timestamp" | "Date" => "string".to_string(),
                _ => "string".to_string(),
            };
            let t = if input.optional {
                format!("{base} | null")
            } else {
                base
            };
            fields.push_str(&format!("  {col}: {t};\n"));
        }
        let label = super::pick_message(&cmd.label, &cmd.name);
        let mut body_obj = "{ ".to_string();
        let cols: Vec<String> = cmd
            .input
            .iter()
            .map(|i| crate::identity::to_snake_case(&i.name))
            .collect();
        body_obj.push_str(&cols.join(", "));
        body_obj.push_str(" }");
        out.push_str(&format!(
            "export interface {name}Input {{\n{fields}}}\n\nexport const {name}Api = {{\n  label: \"{label}\",\n  execute: (id: string, input: {name}Input) =>\n    req<{{ ok: boolean }}>(`/api{path}`.replace(\"{{id}}\", id), {{ method: \"POST\", body: JSON.stringify(input) }}),\n}};\n\n",
            name = cmd.name,
            label = escape_ts(&label),
            path = cmd.path,
        ));
        let _ = body_obj;
    }
    out
}

// ── validators.ts ───────────────────────────────────────

fn validators_ts(program: &Program) -> String {
    let mut out = String::from("// @generated by Forma (gen-web) — do not edit manually.\n// 与后端 validators.rs 同源：同一套 DSL 规则的双端编译。\n\n");
    out.push_str("import { FieldError } from \"./api\";\n");
    let mut type_imports: Vec<String> = Vec::new();
    for entity in &program.entities {
        type_imports.push(format!(
            "Create{}, Update{}, {}",
            entity.name, entity.name, entity.name
        ));
    }
    out.push_str(&format!(
        "import {{ {} }} from \"./types\";\n\n",
        type_imports.join(", ")
    ));
    for e in &program.enums {
        let set_name = crate::identity::to_snake_case(&e.name).to_uppercase();
        let variants: Vec<String> = e
            .variants
            .iter()
            .map(|v| format!("\"{}\"", v.name))
            .collect();
        out.push_str(&format!(
            "const {set_name}_VARIANTS = [{}];\n",
            variants.join(", ")
        ));
    }
    out.push('\n');

    for entity in &program.entities {
        for is_create in [true, false] {
            let kind = if is_create { "Create" } else { "Update" };
            let entity_name = &entity.name;
            out.push_str(&format!(
                "export function validate{kind}{entity_name}(input: any): FieldError[] {{\n  const errs: FieldError[] = [];\n"
            ));
            out.push_str(&ts_field_checks(program, entity));
            out.push_str(&ts_check_rules(program, entity));
            out.push_str("  return errs;\n}\n\n");
        }
    }
    out
}

fn ts_field_checks(program: &Program, entity: &crate::dsl::EntityDecl) -> String {
    let mut out = String::new();
    let mut rules_by_field: std::collections::HashMap<String, Vec<&crate::dsl::FieldConstraint>> =
        Default::default();
    for rules in &program.rules {
        for fr in &rules.field_rules {
            if fr.entity == entity.name {
                rules_by_field
                    .entry(fr.field.clone())
                    .or_default()
                    .extend(fr.constraints.iter());
            }
        }
    }

    for field in &entity.fields {
        if super::has_attr(field, "id") {
            continue;
        }
        let col = crate::identity::to_snake_case(&field.name);
        let is_relation = super::is_relation(program, &field.type_name);
        let has_default = super::has_attr(field, "default");
        let is_option = field.optional || has_default || super::has_attr(field, "readonly");
        let is_decimal = field.type_name == "Decimal";
        let is_text = matches!(field.type_name.as_str(), "String" | "Email" | "Text");

        // required
        let mut required_msg: Option<String> = None;
        if !is_relation && !field.optional && !has_default && is_text {
            required_msg = Some("必填 / required".into());
        }
        if let Some(constraints) = rules_by_field.get(&field.name) {
            for c in constraints {
                if let crate::dsl::FieldConstraint::Required(msg) = c {
                    required_msg = Some(super::pick_message(msg, "required"));
                }
            }
        }
        if let Some(msg) = required_msg {
            out.push_str(&format!(
                "  if (input.{col} === null || input.{col} === undefined || String(input.{col}).trim() === \"\") errs.push({{ field: \"{col}\", message: \"{}\" }});\n",
                escape_ts(&msg)
            ));
        }

        // min/max
        let mut mins: Vec<(f64, String)> = Vec::new();
        let mut maxs: Vec<(f64, String)> = Vec::new();
        for attr in &field.attrs {
            if matches!(attr.name.as_str(), "min" | "max") {
                if let Some(v) = attr.args.first().and_then(|a| a.parse::<f64>().ok()) {
                    let msg = format!(
                        "{} must be {} {}",
                        col,
                        if attr.name == "min" { ">=" } else { "<=" },
                        v
                    );
                    if attr.name == "min" {
                        mins.push((v, msg));
                    } else {
                        maxs.push((v, msg));
                    }
                }
            }
        }
        if let Some(constraints) = rules_by_field.get(&field.name) {
            for c in constraints {
                match c {
                    crate::dsl::FieldConstraint::Min(v, msg) => {
                        mins.push((*v, super::pick_message(msg, "too small")))
                    }
                    crate::dsl::FieldConstraint::Max(v, msg) => {
                        maxs.push((*v, super::pick_message(msg, "too large")))
                    }
                    _ => {}
                }
            }
        }
        for (v, msg) in mins {
            out.push_str(&ts_numeric_check(&col, is_option, is_decimal, v, "<", &msg));
        }
        for (v, msg) in maxs {
            out.push_str(&ts_numeric_check(&col, is_option, is_decimal, v, ">", &msg));
        }

        // 枚举成员
        if super::is_enum(program, &field.type_name) {
            let set_name = format!(
                "{}_VARIANTS",
                crate::identity::to_snake_case(&field.type_name).to_uppercase()
            );
            let cond = if is_option {
                format!("input.{col} != null && !{set_name}.includes(input.{col})")
            } else {
                format!("!{set_name}.includes(input.{col})")
            };
            out.push_str(&format!(
                "  if ({cond}) errs.push({{ field: \"{col}\", message: \"must be one of {}\" }});\n",
                field.type_name
            ));
        }
    }
    out
}

fn ts_numeric_check(
    col: &str,
    is_option: bool,
    is_decimal: bool,
    v: f64,
    cmp: &str,
    msg: &str,
) -> String {
    let value_expr = if is_decimal {
        format!("Number(input.{col} ?? 0)")
    } else if is_option {
        format!("(input.{col} ?? 0)")
    } else {
        format!("input.{col}")
    };
    if is_option || is_decimal {
        format!(
            "  if (input.{col} != null && {value_expr} {cmp} {v}) errs.push({{ field: \"{col}\", message: \"{}\" }});\n",
            escape_ts(msg)
        )
    } else {
        format!(
            "  if ({value_expr} {cmp} {v}) errs.push({{ field: \"{col}\", message: \"{}\" }});\n",
            escape_ts(msg)
        )
    }
}

/// check 规则 → TS 表达式。引用 old. 的规则跳过（后端权威执行）。
fn ts_check_rules(program: &Program, entity: &crate::dsl::EntityDecl) -> String {
    let mut out = String::new();
    for rules in &program.rules {
        for check in &rules.checks {
            if check.entity != entity.name {
                continue;
            }
            if expr_uses_old(&check.expr) {
                continue;
            }
            let cond = ts_expr(&check.expr, entity);
            let msg = super::pick_message(&check.message, "check failed");
            out.push_str(&format!(
                "  if (!({cond})) errs.push({{ field: \"__check\", message: \"{}\" }});\n",
                escape_ts(&msg)
            ));
        }
    }
    out
}

fn expr_uses_old(expr: &crate::dsl::Expr) -> bool {
    match expr {
        crate::dsl::Expr::Ref { old, .. } => *old,
        crate::dsl::Expr::Bin(_, a, b) => expr_uses_old(a) || expr_uses_old(b),
        crate::dsl::Expr::Not(a) => expr_uses_old(a),
        crate::dsl::Expr::Call(_, args) => args.iter().any(expr_uses_old),
        crate::dsl::Expr::List(items) => items.iter().any(expr_uses_old),
        _ => false,
    }
}

fn ts_expr(expr: &crate::dsl::Expr, entity: &crate::dsl::EntityDecl) -> String {
    match expr {
        crate::dsl::Expr::Num(v) => {
            if v.fract() == 0.0 {
                format!("{}", *v as i64)
            } else {
                format!("{v}")
            }
        }
        crate::dsl::Expr::Str(s) => format!("\"{}\"", escape_ts(s)),
        crate::dsl::Expr::Bool(b) => b.to_string(),
        crate::dsl::Expr::Null => "null".to_string(),
        crate::dsl::Expr::Ref { path, old } => {
            if *old {
                return "true".to_string();
            }
            let Some(field) = entity.fields.iter().find(|f| f.name == path[0]) else {
                return "undefined".to_string();
            };
            let col = crate::identity::to_snake_case(&field.name);
            if path.len() > 1 {
                return format!("({col}_name ?? \"\")");
            }
            if field.type_name == "Decimal" {
                return format!("Number(input.{col} ?? 0)");
            }
            if field.optional
                || super::has_attr(field, "default")
                || super::has_attr(field, "readonly")
            {
                if matches!(field.type_name.as_str(), "Timestamp" | "Date") {
                    return format!("(input.{col} ?? new Date().toISOString())");
                }
                return format!("(input.{col} ?? \"\")");
            }
            format!("input.{col}")
        }
        crate::dsl::Expr::List(items) => {
            let parts: Vec<String> = items.iter().map(|i| ts_expr(i, entity)).collect();
            format!("[{}]", parts.join(", "))
        }
        crate::dsl::Expr::Call(name, args) => {
            let rendered: Vec<String> = args.iter().map(|a| ts_expr(a, entity)).collect();
            match name.as_str() {
                "matches" => format!(
                    "new RegExp({}).test(String({}))",
                    rendered.get(1).cloned().unwrap_or_else(|| "\"\"".into()),
                    rendered.first().cloned().unwrap_or_default()
                ),
                _ => "true".to_string(),
            }
        }
        crate::dsl::Expr::Not(inner) => format!("!({})", ts_expr(inner, entity)),
        crate::dsl::Expr::Bin(op, a, b) => {
            let l = ts_expr(a, entity);
            let r = ts_expr(b, entity);
            let op_str = match op {
                crate::dsl::BinOp::Eq => "===",
                crate::dsl::BinOp::Ne => "!==",
                crate::dsl::BinOp::Lt => "<",
                crate::dsl::BinOp::Le => "<=",
                crate::dsl::BinOp::Gt => ">",
                crate::dsl::BinOp::Ge => ">=",
                crate::dsl::BinOp::And => "&&",
                crate::dsl::BinOp::Or => "||",
                crate::dsl::BinOp::Add => "+",
                crate::dsl::BinOp::Sub => "-",
                crate::dsl::BinOp::Mul => "*",
                crate::dsl::BinOp::Div => "/",
                crate::dsl::BinOp::In => {
                    return format!("({r}).includes({l})");
                }
            };
            format!("({l} {op_str} {r})")
        }
    }
}

fn escape_ts(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
}

