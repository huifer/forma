pub fn ts_type(program: &Program, type_name: &str, optional: bool) -> String {
    let base = match type_name {
        "Uuid" | "String" | "Email" | "Text" | "Timestamp" | "Date" => "string".to_string(),
        "Int" | "Float" => "number".to_string(),
        "Decimal" => "string".to_string(),
        "Bool" => "boolean".to_string(),
        "Json" => "unknown".to_string(),
        other => {
            if super::is_enum(program, other) {
                let Some(e) = program.enums.iter().find(|e| e.name == other) else {
                    return "string".to_string();
                };
                let variants: Vec<String> = e
                    .variants
                    .iter()
                    .map(|v| format!("\"{}\"", v.name))
                    .collect();
                return variants.join(" | ");
            }
            "string".to_string()
        }
    };
    if optional {
        format!("{base} | null")
    } else {
        base
    }
}

pub fn types_ts(program: &Program) -> String {
    let mut out = String::from("// @generated by Forma (gen-web) — do not edit manually.\n\n");
    if program
        .apis
        .iter()
        .any(|a| a.list.as_ref().and_then(|l| l.paginate.as_deref()) == Some("cursor"))
    {
        out.push_str("/** Cursor pagination envelope (RFC-0005 / spec:protocols §3.4.1). */\n");
        out.push_str(
            "export interface CursorPage<T> { items: T[]; nextCursor: string | null; }\n\n",
        );
    }
    for e in &program.enums {
        let variants: Vec<String> = e
            .variants
            .iter()
            .map(|v| format!("\"{}\"", v.name))
            .collect();
        out.push_str(&format!(
            "export type {} = {};\n",
            e.name,
            variants.join(" | ")
        ));
    }
    out.push('\n');
    for entity in &program.entities {
        let mut fields = String::new();
        for f in &entity.fields {
            let name = crate::identity::to_snake_case(&f.name);
            if super::is_relation(program, &f.type_name) {
                fields.push_str(&format!("  {name}: string;\n"));
            } else {
                fields.push_str(&format!(
                    "  {name}: {};\n",
                    ts_type(program, &f.type_name, f.optional)
                ));
            }
        }
        out.push_str(&format!(
            "export interface {} {{\n{}}}\n\n",
            entity.name, fields
        ));

        let mut row_fields = fields.clone();
        for f in &entity.fields {
            if super::is_relation(program, &f.type_name) {
                let name = crate::identity::to_snake_case(&f.name);
                row_fields.push_str(&format!("  {name}_name: string | null;\n"));
            }
        }
        out.push_str(&format!(
            "export interface {}ListRow extends {} {{\n{}}}\n\n",
            entity.name, entity.name, row_fields
        ));

        out.push_str(&format!(
            "export interface Create{} {{\n{}}}\n\n",
            entity.name,
            input_ts(program, entity)
        ));
        out.push_str(&format!(
            "export interface Update{} {{\n{}}}\n\n",
            entity.name,
            input_ts(program, entity)
        ));
    }
    out
}

/// 表单/API 输入侧字段（id 除外；readonly/default 字段可空）
fn input_ts(program: &Program, entity: &crate::dsl::EntityDecl) -> String {
    let mut out = String::new();
    for f in &entity.fields {
        if super::has_attr(f, "id") {
            continue;
        }
        let name = crate::identity::to_snake_case(&f.name);
        if super::is_relation(program, &f.type_name) {
            let t = if f.optional {
                "string | null"
            } else {
                "string"
            };
            out.push_str(&format!("  {name}: {t};\n"));
            continue;
        }
        let readonly = super::has_attr(f, "readonly");
        let has_default = super::has_attr(f, "default");
        let base = ts_type(program, &f.type_name, false);
        if f.optional || has_default || readonly {
            out.push_str(&format!("  {name}: {base} | null;\n"));
        } else {
            out.push_str(&format!("  {name}: {base};\n"));
        }
    }
    out
}

/// 规则一致性向量 · Web 端行为测试（F-004）：
/// 与 Flutter 端 `rule_vector_test.dart` 由**同一派生函数**产出（同源保证），
/// 在 vitest 中真实执行生成的 TS 校验器。
fn validators_test_ts(program: &Program) -> Option<String> {
    let mut groups = String::new();
    let mut imports: Vec<String> = Vec::new();
    for entity in &program.entities {
        let cases = crate::validation_vectors::behavior_cases(program, &entity.name);
        if cases.is_empty() {
            continue;
        }
        imports.push(format!("validateCreate{0},", entity.name));
        // 基准输入 helper（any 类型——校验器契约就是 any）
        let mut base_pairs = String::new();
        for f in &entity.fields {
            if super::has_attr(f, "id") {
                continue;
            }
            let key = crate::validation_vectors::input_key(f, false);
            let value = if crate::validation_vectors::is_optional_input(program, f) {
                "null".to_string()
            } else {
                crate::validation_vectors::base_value(program, f, false)
                    .unwrap_or_else(|| "null".into())
            };
            base_pairs.push_str(&format!("    {key}: {value},\n"));
        }
        groups.push_str(&format!(
            "describe('规则一致性向量 · {0}', () => {{\n  function input(overrides: Record<string, unknown> = {{}}): any {{\n    return {{\n{base_pairs}      ...overrides,\n    }};\n  }}\n\n",
            entity.name
        ));
        for c in &cases {
            let key = program
                .entities
                .iter()
                .find(|e| e.name == c.entity)
                .and_then(|e| e.fields.iter().find(|f| f.name == c.field))
                .map(|f| crate::validation_vectors::input_key(f, false))
                .unwrap_or_else(|| c.field.clone());
            let literal = entity
                .fields
                .iter()
                .find(|f| f.name == c.field)
                .map(|f| crate::validation_vectors::case_literal(f, &c.value))
                .unwrap_or_default();
            let expect = if matches!(
                c.kind,
                crate::validation_vectors::CaseKind::MinBoundary
                    | crate::validation_vectors::CaseKind::MaxBoundary
            ) {
                "toBe(false)"
            } else {
                "toBe(true)"
            };
            let boundary = if c.boundary_display.is_empty() {
                String::new()
            } else {
                format!(" {}", c.boundary_display)
            };
            groups.push_str(&format!(
                "  test('{kind}{boundary}', () => {{\n    const errs = validateCreate{entity}({{ ...input(), {key}: {literal} }});\n    expect(errs.some((e) => e.field === '{field}')).{expect};\n  }});\n\n",
                kind = describe_kind(c.kind),
                boundary = boundary,
                entity = c.entity,
                field = c.field,
                key = key,
                literal = literal,
                expect = expect,
            ));
        }
        groups.push_str("});\n\n");
    }
    if groups.is_empty() {
        return None;
    }
    let import_list = imports.join("\n  ");
    Some(format!(
        r#"// @generated by Forma (gen-web) — do not edit manually.
// 规则一致性向量 · Web 端行为验证（F-004 / P1-3）。
//
// 与 Flutter 端 `test/rule_vector_test.dart` 由**同一派生函数**（validation_vectors.rs）产出：
// 同一组语义用例（边界值 / 接受 / 拒绝），在 vitest 中真实执行生成的 TS 校验器。
// Rust 侧的字面量一致性断言在 `crates/forma/tests/rule_vectors.rs`。

import {{ describe, expect, test }} from "vitest";
import {{
  {import_list}
}} from "./validators";

{groups}"#
    ))
}

fn describe_kind(kind: crate::validation_vectors::CaseKind) -> &'static str {
    match kind {
        crate::validation_vectors::CaseKind::MinBelow => "低于下界",
        crate::validation_vectors::CaseKind::MinBoundary => "下界",
        crate::validation_vectors::CaseKind::MaxAbove => "超过上界",
        crate::validation_vectors::CaseKind::MaxBoundary => "上界",
        crate::validation_vectors::CaseKind::RequiredEmpty => "必填缺省",
    }
}

