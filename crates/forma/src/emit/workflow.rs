//! 工作流定义导出（轨道 B 重新排期）：DSL 命令 → 状态机工作流定义。
//!
//! 从 DSL 的实体（状态字段 = 枚举）与命令（pre 条件 = 迁移守卫、effect = 状态迁移、
//! audit = 审计钩子）派生**工作流定义**：机读 `workflow/workflow.json`（状态机：
//! states / transitions / guards）与人读 `workflow/README.md`。
//!
//! 零新增依赖；确定性输出；Runtime 可据此驱动流程（REST 调用命令端点）。

use crate::dsl::{is_enum, Program};
use crate::generators::GeneratedFile;
use serde_json::{json, Value};
use std::path::Path;

/// 实体的枚举状态字段（首个）：作为工作流的状态属性。
fn status_field<'a>(
    program: &'a Program,
    entity: &'a crate::dsl::EntityDecl,
) -> Option<(&'a str, &'a crate::dsl::EnumDecl)> {
    for f in &entity.fields {
        if let Some(e) = program.enums.iter().find(|e| e.name == f.type_name) {
            return Some((f.name.as_str(), e));
        }
    }
    None
}

fn workflow_json(program: &Program) -> Value {
    let mut states: Vec<Value> = Vec::new();
    let mut transitions: Vec<Value> = Vec::new();

    for entity in &program.entities {
        let Some((sf, e)) = status_field(program, entity) else {
            continue;
        };
        let states_list: Vec<Value> = e
            .variants
            .iter()
            .map(|v| json!({ "name": v.name, "label": crate::dsl::pick_message(&v.labels, &v.name) }))
            .collect();
        states.push(json!({
            "entity": entity.name,
            "field": sf,
            "values": states_list,
        }));
    }

    for cmd in &program.commands {
        let Some(effect) = cmd.effects.first() else {
            continue;
        };
        transitions.push(json!({
            "name": cmd.name,
            "method": cmd.method,
            "path": cmd.path,
            "entity": effect.entity,
            "from": serde_json::Value::Null, // pre 表达式（运行时求值，不做静态解析）
            "to": format!("{}.{}", effect.entity, effect.field),
            "effect_value": match &effect.value {
                crate::dsl::EffectValue::Ident(v) => json!(v),
                crate::dsl::EffectValue::Str(v) => json!(v),
                crate::dsl::EffectValue::Bool(v) => json!(v),
                crate::dsl::EffectValue::Num(v) => json!(v),
                _ => Value::Null,
            },
            "audit": cmd.audit,
            "requires_approval": is_enum(program, &effect.field) || effect.field == "paid",
        }));
    }

    json!({
        "schema": "forma-workflow/v1",
        "states": states,
        "transitions": transitions,
    })
}

fn readme(program: &Program, spec: &Value) -> String {
    let app = program
        .app
        .as_ref()
        .map(|a| a.name.clone())
        .unwrap_or_default();
    let mut out = "# 工作流定义（generated by Forma）\n\n由 DSL 的状态枚举与命令派生；`workflow.json` 为机读契约（`forma-workflow/v1`）。\n驱动方式：按 `transitions` 顺序调用命令端点（REST），由服务端权威执行 pre/effect/audit。\n\n".to_string();
    let ts = spec["transitions"].as_array().cloned().unwrap_or_default();
    out.push_str("| 迁移 | 实体 | 方法 | 审计 |\n|---|---|---|---|\n");
    for t in &ts {
        out.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            t["name"].as_str().unwrap_or(""),
            t["entity"].as_str().unwrap_or(""),
            t["method"].as_str().unwrap_or(""),
            if t["audit"].is_null() { "—" } else { "✓" },
        ));
    }
    if ts.is_empty() {
        out.push_str("（无命令声明 → 无迁移）\n");
    }
    let _ = app;
    out
}

pub fn emit_workflow(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.commands.is_empty() {
        return Ok(vec![]);
    }
    let spec = workflow_json(program);
    let files = vec![
        (
            format!("{out_dir}/workflow.json"),
            serde_json::to_string_pretty(&spec).unwrap_or_default(),
        ),
        (format!("{out_dir}/README.md"), readme(program, &spec)),
    ];
    let mut out = Vec::new();
    for (path, content) in files {
        out.push(GeneratedFile {
            path,
            content,
            generator: "gen-workflow".into(),
        });
    }
    for f in &out {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(out)
}
