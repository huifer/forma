fn csharp_type(program: &Program, f: &crate::dsl::FieldDecl) -> &'static str {
    match scalar_kind(program, f) {
        "number" => "long",
        "bool" => "bool",
        "decimal" => "decimal",
        "datetime" => "DateTime",
        "json" => "string",
        "relation" => "string",
        _ => "string",
    }
}

fn csharp_models(program: &Program) -> String {
    let mut s = String::from(
        "// @generated by Forma (gen-dotnet) — do not edit manually.\nusing System;\n\nnamespace FormaApp;\n\n",
    );
    for e in &program.entities {
        s.push_str(&format!("public class {} {{\n", e.name));
        for f in &e.fields {
            s.push_str(&format!(
                "    public {} {} {{ get; set; }}\n",
                csharp_type(program, f),
                capitalize(&to_snake_case(&f.name))
            ));
        }
        s.push_str("}\n\n");
    }
    s
}

fn csharp_program(program: &Program) -> String {
    let mut s = String::from(
        r#"// @generated by Forma (gen-dotnet) — do not edit manually.
using Microsoft.AspNetCore.Builder;
using Microsoft.Extensions.DependencyInjection;
using System.Collections.Generic;
using System.Linq;

var builder = WebApplication.CreateBuilder(args);
var app = builder.Build();
var store = new Dictionary<string, object>();

"#,
    );
    for api in &program.apis {
        let plural = to_snake_case(&crate::dsl::pluralize(&api.entity));
        let cls = &api.entity;
        s.push_str(&format!(
            r#"app.MapGet("/api/{plural}", (int? page, int? pageSize) =>
    Results.Ok(new List<{cls}>());
app.MapGet("/api/{plural}/{{id}}", (string id) => Results.Ok(new {cls}());
app.MapPost("/api/{plural}", ({cls} row) => Results.Ok(row));
app.MapPut("/api/{plural}/{{id}}", (string id, {cls} row) => Results.Ok(row));
app.MapDelete("/api/{plural}/{{id}}", (string id) => Results.Ok(new {{ ok = true }}));

"#,
            plural = plural, cls = cls
        ));
    }
    s.push_str("app.Urls.Add(\"http://0.0.0.0:\" + (Environment.GetEnvironmentVariable(\"PORT\") ?? \"8080\"));\napp.Run();\n");
    s
}

