//! 后端扩栈（轨道 B 重新排期）：Go/Gin+GORM、PHP/Laravel、.NET 8 Minimal API。
//!
//! 三者同构：Program → 可运行的 CRUD 后端（实体模型 + 迁移由 db target 负责），
//! 与 NestJS/Hono/FastAPI/Spring Boot 同属「有限但真实」子集——标量字段、枚举、
//! 关系外键、CRUD、offset 列表；显式拒绝 auth/access/tenant/commands/跨字段 rules。
//! 产物不依赖真实数据库运行时即可编译（编译器侧零新增依赖）。

use crate::dsl::{has_attr, is_enum, is_relation, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

fn reject_unsupported(program: &Program) -> anyhow::Result<()> {
    let mut bad = Vec::new();
    if program.auth.is_some() { bad.push("auth module"); }
    if !program.commands.is_empty() { bad.push("command operations"); }
    if program.rules.iter().any(|r| !r.access.is_empty() || !r.guards.is_empty() || !r.checks.is_empty()) { bad.push("access/field rules"); }
    if crate::dsl::tenant_enabled(program) { bad.push("@tenant"); }
    if bad.is_empty() { Ok(()) } else {
        anyhow::bail!("target does not support: {} (use backend.language: rust for full semantics)", bad.join(", "))
    }
}

fn scalar_kind(program: &Program, f: &crate::dsl::FieldDecl) -> &'static str {
    match f.type_name.as_str() {
        "Int" | "Float" => "number",
        "Bool" => "bool",
        "Decimal" => "decimal",
        "Timestamp" | "Date" => "datetime",
        "Json" => "json",
        other if is_enum(program, other) => "enum",
        _ if is_relation(program, &f.type_name) => "relation",
        _ => "string",
    }
}

// ── Go / Gin + GORM ──────────────────────────────────────────

fn go_type(program: &Program, f: &crate::dsl::FieldDecl) -> &'static str {
    match scalar_kind(program, f) {
        "number" => "int64",
        "bool" => "bool",
        "decimal" => "float64",
        "datetime" => "time.Time",
        "json" => "string",
        "relation" => "string",
        _ => "string",
    }
}

fn gin_models(program: &Program) -> String {
    let needs_time = program.entities.iter().any(|e| e.fields.iter().any(|f| matches!(f.type_name.as_str(), "Timestamp" | "Date")));
    let header = if needs_time {
        "// @generated by Forma (gen-gin) — do not edit manually.\npackage main\n\nimport \"time\"\n\n"
    } else {
        "// @generated by Forma (gen-gin) — do not edit manually.\npackage main\n\n"
    };
    let mut s = String::from(header);
    for e in &program.entities {
        s.push_str(&format!("type {} struct {{\n", e.name));
        for f in &e.fields {
            let col = column_key(program, f);
            let gorm = if has_attr(f, "id") { " `gorm:\"primaryKey\"`" } else { "" };
            s.push_str(&format!("    {} {}{}\n", capitalize(&to_snake_case(&f.name)), go_type(program, f), gorm));
            let _ = col;
        }
        s.push_str("}\n\n");
    }
    s
}

fn gin_main(program: &Program) -> String {
    let mut s = String::from(
        r#"// @generated by Forma (gen-gin) — do not edit manually.
package main

import (
    "net/http"
    "os"
    "strconv"

    "github.com/gin-gonic/gin"
    "gorm.io/driver/mysql"
    "gorm.io/gorm"
)

func main() {
    dsn := os.Getenv("DATABASE_URL")
    db, err := gorm.Open(mysql.Open(dsn), &gorm.Config{})
    if err != nil { panic(err) }
    r := gin.Default()
"#,
    );
    for api in &program.apis {
        let e = program.entities.iter().find(|x| x.name == api.entity);
        let Some(_e) = e else { continue };
        let plural = to_snake_case(&crate::dsl::pluralize(&api.entity));
        let cls = &api.entity;
        s.push_str(&format!(
            r#"    r.GET("/api/{plural}", func(c *gin.Context) {{
        page, _ := strconv.Atoi(c.DefaultQuery("page", "1"))
        size, _ := strconv.Atoi(c.DefaultQuery("pageSize", "20"))
        if page < 1 {{ page = 1 }}
        var rows []{cls}
        db.Limit(size).Offset((page - 1) * size).Find(&rows)
        c.JSON(http.StatusOK, rows)
    }})
    r.POST("/api/{plural}", func(c *gin.Context) {{
        var row {cls}
        if err := c.ShouldBindJSON(&row); err != nil {{ c.JSON(http.StatusBadRequest, gin.H{{"error": err.Error()}}) ; return }}
        db.Create(&row)
        c.JSON(http.StatusOK, row)
    }})
    r.GET("/api/{plural}/:id", func(c *gin.Context) {{
        var row {cls}
        if db.First(&row, "id = ?", c.Param("id")).Error != nil {{ c.JSON(http.StatusNotFound, gin.H{{}}) ; return }}
        c.JSON(http.StatusOK, row)
    }})
    r.PUT("/api/{plural}/:id", func(c *gin.Context) {{
        var row {cls}
        if db.First(&row, "id = ?", c.Param("id")).Error != nil {{ c.JSON(http.StatusNotFound, gin.H{{}}) ; return }}
        if err := c.ShouldBindJSON(&row); err != nil {{ c.JSON(http.StatusBadRequest, gin.H{{"error": err.Error()}}) ; return }}
        db.Save(&row)
        c.JSON(http.StatusOK, row)
    }})
    r.DELETE("/api/{plural}/:id", func(c *gin.Context) {{
        db.Delete(&{cls}{{}}, "id = ?", c.Param("id"))
        c.JSON(http.StatusOK, gin.H{{"ok": true}})
    }})
"#,
            plural = plural, cls = cls,
        ));
    }
    s.push_str("    port := os.Getenv(\"PORT\"); if port == \"\" { port = \"8080\" }\n    r.Run(\":\" + port)\n}\n");
    s
}

fn go_mod(app: &str) -> String {
    format!(
        "module dev.forma/{app}\n\ngo 1.22\n\nrequire (\n    github.com/gin-gonic/gin v1.10.0\n    gorm.io/driver/mysql v1.5.7\n    gorm.io/gorm v1.25.10\n)\n"
    )
}

// ── PHP / Laravel ────────────────────────────────────────────

fn php_controller(program: &Program, api: &crate::dsl::ApiDecl) -> String {
    let cls = &api.entity;
    let plural = to_snake_case(&crate::dsl::pluralize(&api.entity));
    let mut s = format!(
        r#"<?php
// @generated by Forma (gen-laravel) — do not edit manually.
namespace App\Http\Controllers;

use App\Models\{cls};
use Illuminate\Http\Request;
use Illuminate\Routing\Controller;

class {cls}Controller extends Controller
{{
    public function index(Request $request)
    {{
        $size = (int) $request->query('pageSize', 20);
        $page = (int) $request->query('page', 1);
        return response()->json({cls}::query()->forPage(max(1, $page), $size)->get());
    }}

    public function show(string $id)
    {{
        return response()->json({cls}::findOrFail($id));
    }}

    public function store(Request $request)
    {{
        $row = new {cls}();
__FILL__        $row->save();
        return response()->json($row);
    }}

    public function update(Request $request, string $id)
    {{
        $row = {cls}::findOrFail($id);
__FILL__        $row->save();
        return response()->json($row);
    }}

    public function destroy(string $id)
    {{
        {cls}::destroy($id);
        return response()->json(['ok' => true]);
    }}
}}
"#,
        cls = cls,
    );
    let mut fill = String::new();
    if let Some(e) = program.entities.iter().find(|x| x.name == api.entity) {
        for f in &e.fields {
            if has_attr(f, "id") || has_attr(f, "readonly") { continue; }
            let key = column_key(program, f);
            fill.push_str(&format!(
                "        $row->{} = $request->input('{}');\n",
                key, key
            ));
        }
    }
    let _ = plural;
    s = s.replace("__FILL__", &fill);
    s
}

fn php_model(program: &Program, entity: &crate::dsl::EntityDecl) -> String {
    let table = to_snake_case(&crate::dsl::pluralize(&entity.name));
    let mut fill = String::new();
    for f in &entity.fields {
        if has_attr(f, "id") || has_attr(f, "readonly") { continue; }
        fill.push_str(&format!("        '{}',\n", column_key(program, f)));
    }
    format!(
        r#"<?php
// @generated by Forma (gen-laravel) — do not edit manually.
namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class {cls} extends Model
{{
    protected $table = '{table}';
    protected $keyType = 'string';
    public $incrementing = false;
    protected $fillable = [
__FILL__    ];
}}
"#,
        cls = entity.name, table = table
    )
    .replace("__FILL__", &fill)
}

