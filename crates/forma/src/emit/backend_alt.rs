// ── helpers ──────────────────────────────────────────────────

fn column_key(program: &Program, f: &crate::dsl::FieldDecl) -> String {
    let n = to_snake_case(&f.name);
    if is_relation(program, &f.type_name) { format!("{n}_id") } else { n }
}

fn capitalize(s: &str) -> String {
    let mut cs = s.chars();
    match cs.next() {
        Some(c) => c.to_uppercase().collect::<String>() + cs.as_str(),
        None => String::new(),
    }
}

fn write_files(project_dir: &Path, files: &[(&str, String)], generator: &'static str) -> anyhow::Result<Vec<GeneratedFile>> {
    let mut out = Vec::new();
    for (path, content) in files {
        out.push(GeneratedFile {
            path: path.to_string(),
            content: content.clone(),
            generator: generator.into(),
        });
    }
    for f in &out {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(out)
}

fn readme(framework: &str) -> String {
    format!(
        "# {framework} backend（generated by Forma）\n\n实体模型与 CRUD 路由由 DSL 生成；数据库 DDL 由 `db` target 负责。\n"
    )
}

pub fn emit_gin(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() { return Ok(vec![]); }
    reject_unsupported(program)?;
    let app = to_snake_case(app_name);
    let files = vec![
        (format!("{out_dir}/go.mod"), go_mod(&app)),
        (format!("{out_dir}/main.go"), gin_main(program)),
        (format!("{out_dir}/models.go"), gin_models(program)),
        (format!("{out_dir}/README.md"), readme("Go / Gin + GORM")),
    ];
    let owned: Vec<(String, String)> = files;
    let refs: Vec<(&str, String)> = owned.iter().map(|(p, c)| (p.as_str(), c.clone())).collect();
    write_files(project_dir, &refs, "gen-gin")
}

pub fn emit_laravel(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() { return Ok(vec![]); }
    reject_unsupported(program)?;
    let app = to_snake_case(app_name).replace('_', "-");
    let mut files = vec![
        (format!("{out_dir}/composer.json"), composer_json(&app)),
        (format!("{out_dir}/README.md"), readme("PHP / Laravel")),
    ];
    for e in &program.entities {
        files.push((format!("{out_dir}/app/Models/{}.php", e.name), php_model(program, e)));
    }
    for api in &program.apis {
        files.push((
            format!("{out_dir}/app/Http/Controllers/{}Controller.php", api.entity),
            php_controller(program, api),
        ));
    }
    let refs: Vec<(&str, String)> = files.iter().map(|(p, c)| (p.as_str(), c.clone())).collect();
    write_files(project_dir, &refs, "gen-laravel")
}

pub fn emit_dotnet(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() { return Ok(vec![]); }
    reject_unsupported(program)?;
    let app = to_snake_case(app_name);
    let files = [
        (format!("{out_dir}/{app}.csproj"), csproj(&app)),
        (format!("{out_dir}/Program.cs"), csharp_program(program)),
        (format!("{out_dir}/Models.cs"), csharp_models(program)),
        (format!("{out_dir}/README.md"), readme(".NET 8 Minimal API")),
    ];
    let refs: Vec<(&str, String)> = files.iter().map(|(p, c)| (p.as_str(), c.clone())).collect();
    write_files(project_dir, &refs, "gen-dotnet")
}
