//! MongoDB target（轨道 B 重新排期）：Program → 集合设计（文档模型）。
//!
//! MongoDB 不是关系型存储——没有表 / SQL DDL。本 emitter 从 DSL 的实体、字段、
//! 索引、唯一约束派生**集合设计**：JSON Schema 校验器（`$jsonSchema`）、索引定义、
//! 以及可直接执行的 mongo shell 初始化/升级脚本。与 Redis 键设计同属「文档/键值模型
//! 的纯函数派生」，不依赖真实 MongoDB 运行时（零新增依赖）。
//!
//! - 字段键名沿用 DSL 物理命名（关系 → `{rel}_id`；
//! - 类型走 BSON：string / int / double / decimal / bool / date / object；
//! - 索引与唯一约束派生为 `createIndex`（`unique: true`）。

use super::mysql::plan_tables;
use crate::dsl::{is_enum, is_relation, FieldDecl, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use serde_json::{json, Value};
use std::path::Path;

fn bson_type(program: &Program, f: &FieldDecl) -> &'static str {
    match f.type_name.as_str() {
        "Int" => "int",
        "Float" => "double",
        "Decimal" => "decimal",
        "Bool" => "bool",
        "Timestamp" | "Date" => "date",
        "Json" => "object",
        other if is_enum(program, other) => "string",
        _ if is_relation(program, &f.type_name) => "string",
        _ => "string",
    }
}

fn collection_spec(program: &Program) -> Value {
    let plans = plan_tables(program);
    let mut collections: Vec<Value> = Vec::new();
    for table in &plans {
        let entity = program
            .entities
            .iter()
            .find(|e| e.name == table.entity)
            .unwrap_or_else(|| panic!("table plan references unknown entity {}", table.entity));
        let mut props = serde_json::Map::new();
        let mut required: Vec<String> = Vec::new();
        for f in &entity.fields {
            let key = if is_relation(program, &f.type_name) {
                format!("{}_id", to_snake_case(&f.name))
            } else {
                to_snake_case(&f.name)
            };
            props.insert(key.clone(), json!({ "bsonType": bson_type(program, f) }));
            if !f.optional && !crate::dsl::has_attr(f, "default") {
                required.push(key);
            }
        }
        let mut indexes: Vec<Value> = Vec::new();
        for u in &table.uniques {
            indexes.push(json!({ "key": u, "unique": true }));
        }
        for i in &table.indexes {
            indexes.push(json!({ "key": i, "unique": false }));
        }
        collections.push(json!({
            "name": table.table,
            "entity": entity.name,
            "validator": {
                "$jsonSchema": {
                    "bsonType": "object",
                    "required": required,
                    "properties": props,
                }
            },
            "indexes": indexes,
        }));
    }
    json!({ "collections": collections })
}

fn readme(program: &Program, spec: &Value) -> String {
    let mut out = String::from(
        "# MongoDB 集合设计（generated by Forma）\n\n由 DSL 派生；`collections.json` 为机读契约，`0001_init.js` 为可执行初始化脚本。\n\n",
    );
    let cols = spec["collections"].as_array().cloned().unwrap_or_default();
    out.push_str("| 集合 | 实体 | 必填字段 | 索引 |\n|---|---|---|---|\n");
    for c in &cols {
        let req = c["validator"]["$jsonSchema"]["required"]
            .as_array()
            .map(|a| a.iter().filter_map(|v| v.as_str()).collect::<Vec<_>>().join(", "))
            .unwrap_or_default();
        let idx = c["indexes"].as_array().map(|a| a.len()).unwrap_or(0);
        out.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            c["name"].as_str().unwrap_or(""),
            c["entity"].as_str().unwrap_or(""),
            if req.is_empty() { "—".into() } else { req },
            idx
        ));
    }
    let _ = program;
    out
}

fn shell_script(spec: &Value, header: &str) -> String {
    let mut out = String::from(header);
    for c in spec["collections"].as_array().cloned().unwrap_or_default() {
        let name = c["name"].as_str().unwrap_or("");
        let validator = serde_json::to_string(&c["validator"]).unwrap_or_default();
        out.push_str(&format!(
            "if (!db.getCollectionNames().includes('{name}')) {{\n    db.createCollection('{name}', {{ validator: {validator} }});\n}}\n"
        ));
        for i in c["indexes"].as_array().cloned().unwrap_or_default() {
            let keys = serde_json::to_string(&i["key"]).unwrap_or_default();
            let unique = i["unique"].as_bool().unwrap_or(false);
            out.push_str(&format!(
                "db.{name}.createIndex({keys}, {{ unique: {unique}, background: true }});\n"
            ));
        }
        out.push('\n');
    }
    out
}

pub fn emit_mongodb(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    let spec = collection_spec(program);
    let header_init = "// @generated by Forma (gen-mongodb) — do not edit manually.\n// Mongo shell init (`mongosh <db> 0001_init.js`)\n\n";
    let header_up = "// @generated by Forma (gen-mongodb) — upgrade migration (`mongosh <db> 0001_upgrade.js`)\n\n";
    let files = vec![
        (
            format!("{out_dir}/collections.json"),
            serde_json::to_string_pretty(&spec).unwrap_or_default(),
        ),
        (format!("{out_dir}/README.md"), readme(program, &spec)),
        (
            format!("{out_dir}/0001_init.js"),
            shell_script(&spec, header_init),
        ),
        (
            format!("{out_dir}/migrations/0001_upgrade.js"),
            shell_script(&spec, header_up),
        ),
    ];
    let mut out = Vec::new();
    for (path, content) in files {
        out.push(GeneratedFile {
            path,
            content,
            generator: "gen-mongodb".into(),
        });
    }
    for f in &out {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(out)
}
