//! tRPC target（轨道 B 重新排期）：Program → tRPC 网关（TypeScript）。
//!
//! 与 GraphQL 网关同构：不直连数据库，procedures 经 `REST_BASE` 委托到生成的 REST 后端。
//! - 每个 api 块 → router，operations 裁剪为 list/get/create/update/delete procedures；
//! - 输入用 zod 从 DSL 字段派生（Create/Update 输入、id、列表参数）；
//! - 关系字段输入键为裸关系名（后端 serde 契约）；Decimal → string；
//! - 自包含 `package.json` / `tsconfig.json` / `src/*.ts` / README。

use crate::dsl::Program;
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

fn zod_type(type_name: &str) -> &'static str {
    match type_name {
        "Int" | "Float" => "z.number()",
        "Bool" => "z.boolean()",
        "Decimal" => "z.string()",
        "Timestamp" | "Date" => "z.string()",
        "Json" => "z.unknown()",
        _ => "z.string()",
    }
}

fn package_json(app: &str) -> String {
    format!(
        r#"{{
  "name": "{app}-trpc",
  "private": true,
  "version": "0.1.0",
  "type": "module",
  "scripts": {{ "typecheck": "tsc --noEmit", "start": "tsx src/server.ts" }},
  "dependencies": {{ "@trpc/server": "^11.0.0", "zod": "^3.23.0" }},
  "devDependencies": {{ "@types/node": "^20.0.0", "tsx": "^4.19.0", "typescript": "^5.5.4" }}
}}
"#
    )
}

fn tsconfig_json() -> String {
    r#"{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "strict": true,
    "skipLibCheck": true,
    "noEmit": true,
    "types": ["node"]
  },
  "include": ["src/**/*.ts"]
}
"#
    .to_string()
}

fn context_ts() -> String {
    r#"// @generated by Forma (gen-trpc) — do not edit manually.
export const REST_BASE = process.env.REST_BASE ?? "http://localhost:8080";

export async function rest(path: string, init?: RequestInit): Promise<unknown> {
  const res = await fetch(`${REST_BASE}${path}`, {
    ...init,
    headers: { "content-type": "application/json", ...(init?.headers ?? {}) },
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`REST ${res.status}: ${JSON.stringify(body)}`);
  return body;
}
"#
    .to_string()
}

fn router_ts(program: &Program) -> String {
    let mut out = String::from(
        r#"// @generated by Forma (gen-trpc) — do not edit manually.
import { initTRPC } from "@trpc/server";
import { z } from "zod";
import { rest } from "./context";

const t = initTRPC.create();
const publicProcedure = t.procedure;

"#,
    );
    for api in &program.apis {
        let entity = program.entities.iter().find(|e| e.name == api.entity);
        let plural = to_snake_case(&crate::dsl::pluralize(&api.entity));
        let router = format!("{}Router", api.name.to_lowercase());
        out.push_str(&format!("const {router} = t.router({{\n"));
        if api.operations.iter().any(|o| o == "list") {
            let mut filters = String::new();
            if let Some(list) = &api.list {
                for (f, _) in &list.filters {
                    filters.push_str(&format!("    {}: z.string().nullish(),\n", to_snake_case(f)));
                }
            }
            let block = r#"  list: publicProcedure.input(z.object({
    page: z.number().int().positive().nullish(),
    pageSize: z.number().int().positive().nullish(),
    q: z.string().nullish(),
__FILTERS__  })).query(({ input }) => {
    const qs = new URLSearchParams();
    for (const [k, v] of Object.entries(input)) {
      if (v !== null && v !== undefined) qs.set(k, String(v));
    }
    return rest(`/api/__PLURAL__?${qs.toString()}`);
  }),
"#
            .replace("__FILTERS__", &filters).replace("__PLURAL__", &plural);
            out.push_str(&block);
        }
        if api.operations.iter().any(|o| o == "get") {
            out.push_str(
                &r#"  get: publicProcedure.input(z.object({ id: z.string() })).query(({ input }) => rest(`/api/__PLURAL__/${input.id}`)),
"#
                .replace("__PLURAL__", &plural),
            );
        }
        if api.operations.iter().any(|o| o == "create") {
            if let Some(e) = entity {
                let mut shape = String::new();
                for f in e.fields.iter().filter(|f| {
                    !crate::dsl::has_attr(f, "id") && !crate::dsl::has_attr(f, "readonly")
                }) {
                    let key = to_snake_case(&f.name);
                    let optional = if f.optional { ".optional()" } else { "" };
                    shape.push_str(&format!("    {}: {}{},\n", key, zod_type(&f.type_name), optional));
                }
                let block = r#"  create: publicProcedure.input(z.object({
__SHAPE__  })).mutation(({ input }) => rest(`/api/__PLURAL__`, { method: "POST", body: JSON.stringify(input) })),
"#
                .replace("__SHAPE__", &shape).replace("__PLURAL__", &plural);
                out.push_str(&block);
            }
        }
        if api.operations.iter().any(|o| o == "update") {
            out.push_str(
                &r#"  update: publicProcedure.input(z.object({ id: z.string(), body: z.record(z.unknown()) })).mutation(({ input }) => rest(`/api/__PLURAL__/${input.id}`, { method: "PUT", body: JSON.stringify(input.body) })),
"#
                .replace("__PLURAL__", &plural),
            );
        }
        if api.operations.iter().any(|o| o == "delete") {
            out.push_str(
                &r#"  delete: publicProcedure.input(z.object({ id: z.string() })).mutation(({ input }) => rest(`/api/__PLURAL__/${input.id}`, { method: "DELETE" })),
"#
                .replace("__PLURAL__", &plural),
            );
        }
        out.push_str("});\n\n");
    }
    out.push_str("export const appRouter = t.router({\n");
    for api in &program.apis {
        out.push_str(&format!("  {}: {}Router,\n", api.name.to_lowercase(), api.name.to_lowercase()));
    }
    out.push_str("});\n\nexport type AppRouter = typeof appRouter;\n");
    out
}

fn server_ts() -> String {
    r#"// @generated by Forma (gen-trpc) — do not edit manually.
import { createHTTPServer } from "@trpc/server/adapters/standalone";
import { appRouter } from "./router";

const port = Number(process.env.PORT ?? 4000);
createHTTPServer({ router: appRouter, createContext: () => ({}) }).listen(port);
console.log(`tRPC gateway listening on http://localhost:${port}`);
"#
    .to_string()
}

fn readme_md(app: &str) -> String {
    format!(
        "# {app} tRPC 网关\n\n```bash\nnpm install\nnpm run typecheck\nREST_BASE=http://localhost:8080 npm start\n```\n\nprocedures 经 `REST_BASE` 委托到生成的 REST 后端（与 GraphQL 网关同构），不直连数据库。\n"
    )
}

pub fn emit_trpc(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.apis.is_empty() {
        return Ok(vec![]);
    }
    let app = program
        .app
        .as_ref()
        .map(|a| a.name.clone())
        .unwrap_or_else(|| "forma-app".into());
    let files = vec![
        ("package.json", package_json(&app)),
        ("tsconfig.json", tsconfig_json()),
        ("src/context.ts", context_ts()),
        ("src/router.ts", router_ts(program)),
        ("src/server.ts", server_ts()),
        ("README.md", readme_md(&app)),
    ];
    let mut out = Vec::new();
    for (name, content) in files {
        out.push(GeneratedFile {
            path: format!("{out_dir}/{name}"),
            content,
            generator: "gen-trpc".into(),
        });
    }
    for f in &out {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(out)
}
