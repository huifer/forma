//! Playwright e2e 生成（轨道 B 重新排期）：Program → 可运行的端到端测试套件。
//!
//! 自包含（不改 Web 工程 package.json）：`{web_out}/e2e/` 下生成
//! `package.json` / `playwright.config.ts` / `crud.spec.ts` / `README.md`。
//! 测试用例从 DSL 的表格页 + api operations 静态展开：
//! - 列表页渲染（路由 + 表格 + 搜索框）；
//! - 分页控件（offset 模式）；
//! - 新建页（仅当 api 声明 create）；
//! - 命令按钮（仅当存在空 input 命令）。

use crate::dsl::{PageBody, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

fn config_ts() -> String {
    r#"// @generated by Forma (gen-playwright) — do not edit manually.
import { defineConfig, devices } from "@playwright/test";

const baseURL = process.env.E2E_BASE_URL ?? "http://localhost:5173";

export default defineConfig({
  testDir: ".",
  fullyParallel: true,
  reporter: "list",
  use: { baseURL, trace: "on-first-retry" },
  projects: [{ name: "chromium", use: { ...devices["Desktop Chrome"] } }],
});
"#
    .to_string()
}

fn package_json() -> String {
    r#"{
  "name": "forma-e2e",
  "private": true,
  "version": "0.1.0",
  "scripts": { "test": "playwright test", "typecheck": "tsc --noEmit", "install-browsers": "playwright install chromium" },
  "devDependencies": { "@playwright/test": "^1.47.0", "@types/node": "^20.0.0", "typescript": "^5.5.4" }
}
"#
    .to_string()
}

