//! db-mysql 适配层：Program → MySQL 8 DDL。

use super::{pluralize, EntityDecl, FieldDecl, Program};
use crate::util::{sha256_hex, write_text};
use anyhow::Result;
use std::path::Path;

/// 类型映射：DSL → MySQL。返回 (类型, 是否文本)
fn mysql_type(program: &Program, field: &FieldDecl) -> String {
    match field.type_name.as_str() {
        "Uuid" => "CHAR(36)".into(),
        "String" => {
            let n = field
                .type_args
                .first()
                .and_then(|a| a.parse::<usize>().ok())
                .unwrap_or(255);
            format!("VARCHAR({n})")
        }
        "Email" => "VARCHAR(320)".into(),
        "Text" => "TEXT".into(),
        "Int" => "BIGINT".into(),
        "Float" => "DOUBLE".into(),
        "Decimal" => {
            let p = field
                .type_args
                .first()
                .and_then(|a| a.parse::<usize>().ok())
                .unwrap_or(12);
            let s = field
                .type_args
                .get(1)
                .and_then(|a| a.parse::<usize>().ok())
                .unwrap_or(2);
            format!("DECIMAL({p},{s})")
        }
        "Bool" => "TINYINT(1)".into(),
        "Timestamp" => "DATETIME(3)".into(),
        "Date" => "DATE".into(),
        "Json" => "JSON".into(),
        other => {
            if super::is_enum(program, other) {
                "VARCHAR(64)".into()
            } else {
                "CHAR(36)".into() // 实体引用 → FK 列
            }
        }
    }
}

pub fn emit_mysql(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> Result<Vec<crate::generators::GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    let order = topo_entities(program);
    let mut sql = "-- @generated by Forma (gen-mysql) — do not edit manually.\n-- Target: MySQL 8.x, InnoDB, utf8mb4\n\n".to_string();

    for entity in order {
        sql.push_str(&render_table(program, entity));
        sql.push_str("\n\n");
    }

    let rel = format!("{out_dir}/migrations/0001_init.sql");
    let abs = project_dir.join(&rel);
    let content_hash = sha256_hex(&sql);
    let unchanged = abs.is_file()
        && crate::util::read_text(&abs)
            .map(|c| crate::util::sha256_hex(&c) == content_hash)
            .unwrap_or(false);
    if !unchanged {
        write_text(&abs, &sql)?;
    }

    Ok(vec![crate::generators::GeneratedFile {
        path: rel,
        content: sql,
        generator: "gen-mysql".into(),
    }])
}

/// 关系拓扑排序：被引用的表先建；环回退到声明顺序。
fn topo_entities(program: &Program) -> Vec<&EntityDecl> {
    let mut emitted: Vec<String> = Vec::new();
    let mut ordered: Vec<&EntityDecl> = Vec::new();
    let mut remaining: Vec<&EntityDecl> = program.entities.iter().collect();

    loop {
        let mut progressed = false;
        remaining.retain(|entity| {
            let deps_ready = entity.fields.iter().all(|f| {
                !super::is_relation(program, &f.type_name) || emitted.contains(&f.type_name)
            });
            if deps_ready {
                emitted.push(entity.name.clone());
                ordered.push(entity);
                progressed = true;
                false
            } else {
                true
            }
        });
        if remaining.is_empty() || !progressed {
            // 环：按声明顺序放行剩余
            for e in remaining.drain(..) {
                ordered.push(e);
            }
            break;
        }
    }
    ordered
}

fn render_table(program: &Program, entity: &EntityDecl) -> String {
    let table = crate::identity::to_snake_case(&pluralize(&entity.name));
    let mut lines: Vec<String> = Vec::new();
    let mut fk: Vec<String> = Vec::new();
    let mut unique_keys: Vec<String> = Vec::new();
    let mut index_keys: Vec<String> = Vec::new();

    for field in &entity.fields {
        let col = crate::identity::to_snake_case(&field.name);
        if super::is_relation(program, &field.type_name) {
            let fk_col = format!("{col}_id");
            let required = !field.optional && super::has_attr(field, "required");
            lines.push(format!(
                "  {fk_col} CHAR(36){}",
                if required { " NOT NULL" } else { " NULL" }
            ));
            let ref_table = crate::identity::to_snake_case(&pluralize(&field.type_name));
            let fk_name = format!("fk_{table}_{col}");
            fk.push(format!(
                "  CONSTRAINT {fk_name} FOREIGN KEY ({fk_col}) REFERENCES {ref_table} (id)"
            ));
            continue;
        }
        let mut def = format!("  {col} {}", mysql_type(program, field));
        if field.optional {
            def.push_str(" NULL");
        } else {
            def.push_str(" NOT NULL");
        }
        if super::has_attr(field, "unique") {
            def.push_str(" UNIQUE");
        }
        lines.push(def);
    }

    let pk = entity
        .fields
        .iter()
        .find(|f| super::has_attr(f, "id"))
        .map(|f| crate::identity::to_snake_case(&f.name))
        .unwrap_or_else(|| "id".into());
    lines.push(format!("  PRIMARY KEY ({pk})"));

    for (i, cols) in entity.uniques.iter().enumerate() {
        let cols_sql = cols
            .iter()
            .map(|c| fk_column_name(program, entity, c))
            .collect::<Vec<_>>()
            .join(", ");
        unique_keys.push(format!("  UNIQUE KEY uq_{table}_{i} ({cols_sql})"));
    }
    for (i, cols) in entity.indexes.iter().enumerate() {
        let cols_sql = cols
            .iter()
            .map(|c| fk_column_name(program, entity, c))
            .collect::<Vec<_>>()
            .join(", ");
        index_keys.push(format!("  KEY idx_{table}_{i} ({cols_sql})"));
    }

    lines.extend(unique_keys);
    lines.extend(index_keys);
    lines.extend(fk);

    format!(
        "CREATE TABLE {table} (\n{}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;",
        lines.join(",\n")
    )
}

/// index/unique 引用关系字段时指向其 FK 列。
fn fk_column_name(program: &Program, entity: &EntityDecl, col: &str) -> String {
    if let Some(field) = entity.fields.iter().find(|f| f.name == col) {
        if super::is_relation(program, &field.type_name) {
            return format!("{}_id", crate::identity::to_snake_case(col));
        }
    }
    crate::identity::to_snake_case(col)
}
