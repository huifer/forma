//! Desktop target（轨道 B 重新排期）：Program → Electron / Tauri 包装工程。
//!
//! 桌面端复用已生成的 Web 产物（不重写 UI）：
//! - `electron`：`main.cjs` 用 BrowserWindow 加载 `FORMA_DIST`（Web 构建产物）或
//!   `FORMA_URL`（开发服务器）；`preload.cjs` 提供最小 contextBridge；
//! - `tauri`：`src-tauri/` 标准脚手架（tauri.conf.json / Cargo.toml / build.rs / main.rs），
//!   `frontendDist` 指向 Web 构建产物。
//!
//! 零新增依赖（编译器侧）；桌面依赖由各自生态在构建时安装。

use crate::dsl::Program;
use crate::generators::GeneratedFile;
use std::path::Path;

fn electron_files(app: &str) -> Vec<(&'static str, String)> {
    vec![
        (
            "package.json",
            format!(
                r#"{{
  "name": "{app}-desktop",
  "version": "0.1.0",
  "private": true,
  "main": "main.cjs",
  "scripts": {{ "start": "electron ." }},
  "devDependencies": {{ "electron": "^31.0.0" }}
}}
"#
            ),
        ),
        (
            "main.cjs",
            r#"// @generated by Forma (gen-desktop/electron) — do not edit manually.
const {{ app, BrowserWindow }} = require('electron');
const path = require('node:path');

function createWindow() {
  const win = new BrowserWindow({{
    width: 1280,
    height: 800,
    webPreferences: {{ preload: path.join(__dirname, 'preload.cjs'), contextIsolation: true }},
  }});
  const dist = process.env.FORMA_DIST;
  if (dist) {{
    win.loadFile(path.resolve(dist, 'index.html'));
  }} else {{
    win.loadURL(process.env.FORMA_URL ?? 'http://localhost:5173');
  }}
}

app.whenReady().then(() => {{
  createWindow();
  app.on('activate', () => {{ if (BrowserWindow.getAllWindows().length === 0) createWindow(); }});
}});
app.on('window-all-closed', () => {{ if (process.platform !== 'darwin') app.quit(); }});
"#
            .to_string(),
        ),
        (
            "preload.cjs",
            r#"// @generated by Forma (gen-desktop/electron) — do not edit manually.
const {{ contextBridge }} = require('electron');
contextBridge.exposeInMainWorld('forma', {
  platform: 'electron',
});
"#
            .to_string(),
        ),
        (
            "README.md",
            format!(
                "# {app} Desktop（Electron）\n\n```bash\ncd electron\nnpm install\nFORMA_DIST=../../generated/web/dist npm start   # 加载已构建 Web\nFORMA_URL=http://localhost:5173 npm start          # 开发模式\n```\n\nUI 由 Web 目标生成；桌面壳只负责窗口与加载。\n"
            ),
        ),
    ]
}

fn tauri_files(app: &str, version: &str) -> Vec<(&'static str, String)> {
    let conf = serde_json::json!({
        "$schema": "https://schema.tauri.app/config/2",
        "productName": app,
        "version": version,
        "identifier": format!("dev.forma.{}", app.to_lowercase()),
        "build": { "frontendDist": "../../generated/web/dist" },
        "app": {
            "windows": [{ "title": app, "width": 1280, "height": 800 }],
            "security": { "csp": null }
        },
        "bundle": { "active": true, "targets": "all" }
    });
    vec![
        (
            "tauri.conf.json",
            serde_json::to_string_pretty(&conf).unwrap_or_default(),
        ),
        (
            "Cargo.toml",
            r#"[package]
name = "forma-desktop"
version = "0.1.0"
edition = "2021"

[build-dependencies]
tauri-build = { version = "2", features = [] }

[dependencies]
tauri = { version = "2", features = [] }
"#
            .to_string(),
        ),
        (
            "build.rs",
            "// @generated by Forma (gen-desktop/tauri) — do not edit manually.\nfn main() {\n    tauri_build::build()\n}\n"
                .to_string(),
        ),
        (
            "src/main.rs",
            "// @generated by Forma (gen-desktop/tauri) — do not edit manually.\n#![cfg_attr(not(debug_assertions), windows_subsystem = \"windows\")]\n\nfn main() {\n    tauri::Builder::default()\n        .run(tauri::generate_context!())\n        .expect(\"error while running tauri application\");\n}\n"
                .to_string(),
        ),
        (
            "README.md",
            format!(
                "# {app} Desktop（Tauri 2）\n\n```bash\ncd src-tauri\ncargo install tauri-cli --version '^2'   # 首次\ncargo tauri dev      # 开发（需 Web dev server）\ncargo tauri build    # 打包\n```\n\n`tauri.conf.json` 的 `build.frontendDist` 指向 Web 构建产物（默认 `../../generated/web/dist`）。\n"
            ),
        ),
    ]
}

pub fn emit_desktop(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    framework: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    let app = program
        .app
        .as_ref()
        .map(|a| a.name.clone())
        .unwrap_or_else(|| "forma-app".into());
    let version = program
        .app
        .as_ref()
        .map(|a| a.version.clone())
        .unwrap_or_else(|| "0.1.0".into());
    let files = match framework {
        "electron" => electron_files(&app),
        "tauri" => tauri_files(&app, &version),
        other => anyhow::bail!("unsupported desktop framework '{other}'; supported: electron | tauri"),
    };
    let sub = if framework == "electron" { "electron" } else { "src-tauri" };
    let mut out = Vec::new();
    for (name, content) in files {
        out.push(GeneratedFile {
            path: format!("{out_dir}/{sub}/{name}"),
            content,
            generator: "gen-desktop".into(),
        });
    }
    for f in &out {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(out)
}
