//! 原生/小程序移动端扩栈（轨道 B 重新排期）：SwiftUI / Jetpack Compose / 微信小程序 / uni-app。
//!
//! 四者共享 DSL 表格页与 REST 契约，生成最小可运行工程的列表页骨架：
//! - SwiftUI：`Package.swift` + `ContentView.swift` + 每页 `{Page}ListView.swift`（URLSession）；
//! - Compose：Gradle 工程 + `MainActivity.kt` + 每页 `{Page}ListScreen.kt`；
//! - 微信小程序：`app.json` / `app.js` + 每页 `index.{wxml,js,wxss,json}`（wx.request）；
//! - uni-app：`pages.json` / `App.vue` + 每页 `index.vue`（uni.request）。
//!
//! 显式边界：仅列表页（无表单/图表/命令对话框）；保持各平台原生目录约定。

use crate::dsl::{PageBody, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

fn table_pages(program: &Program) -> Vec<(String, String, String)> {
    let mut out = Vec::new();
    for p in &program.pages {
        let PageBody::Table(cfg) = &p.body else {
            continue;
        };
        let Some(api) = program.apis.iter().find(|a| a.name == cfg.query_api) else {
            continue;
        };
        out.push((
            p.name.clone(),
            crate::dsl::pick_message(&p.title, &p.name),
            to_snake_case(&crate::dsl::pluralize(&api.entity)),
        ));
    }
    out
}

fn write_all(
    project_dir: &Path,
    out_dir: &str,
    files: Vec<(String, String)>,
    gen: &'static str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    let mut out = Vec::new();
    for (rel, content) in files {
        out.push(GeneratedFile {
            path: format!("{out_dir}/{rel}"),
            content,
            generator: gen.into(),
        });
    }
    for f in &out {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(out)
}

// ── SwiftUI ──────────────────────────────────────────────────

fn swiftui_files(program: &Program, app: &str) -> Vec<(String, String)> {
    let pages = table_pages(program);
    let mut files = vec![
        ("Package.swift".into(), format!(
            "// swift-tools-version: 5.9\nimport PackageDescription\n\nlet package = Package(\n    name: \"{app}\",\n    // macOS 平台必须显式声明：NavigationStack / .navigationTitle 需要 macOS 13+ / 11+，\n    // 未声明时 swift build 在 macOS 上回落默认部署目标（10.13）→ 编译失败。\n    platforms: [.iOS(.v17), .macOS(.v13)],\n    products: [.executable(name: \"{app}\", targets: [\"{app}\"])],\n    targets: [.executableTarget(name: \"{app}\", path: \"Sources/{app}\")]\n)\n")),
        (format!("Sources/{app}/{app}App.swift"), format!(
            "// @generated by Forma (gen-swiftui) — do not edit manually.\nimport SwiftUI\n\n@main\nstruct {app}App: App {{\n    var body: some Scene {{\n        WindowGroup {{ ContentView() }}\n    }}\n}}\n")),
        (format!("Sources/{app}/ContentView.swift"), {
            let mut nav = String::from("// @generated by Forma (gen-swiftui) — do not edit manually.\nimport SwiftUI\n\nstruct ContentView: View {\n    var body: some View {\n        NavigationStack {\n            List {\n");
            for (name, title, _) in &pages {
                nav.push_str(&format!("                NavigationLink(\"{title}\") {{ {name}ListView() }}\n"));
            }
            nav.push_str("            }\n            .navigationTitle(\"Forma\")\n        }\n    }\n}\n");
            nav
        }),
        ("README.md".into(), format!("# {app} SwiftUI（generated by Forma）\n\n```bash\nswift run\n```\n\n列表页经 `URLSession` 请求 `API_BASE`（默认 `http://localhost:8080/api`）。\n")),
    ];
    for (name, title, plural) in &pages {
        let view = format!(
            r#"// @generated by Forma (gen-swiftui) — do not edit manually.
import SwiftUI

struct {name}ListView: View {{
    @State private var rows: [String] = []
    private let apiBase = ProcessInfo.processInfo.environment["API_BASE"] ?? "http://localhost:8080/api"

    var body: some View {{
        List(rows, id: \.self) {{ row in Text(row) }}
            .navigationTitle("{title}")
            .task {{ await load() }}
    }}

    private func load() async {{
        guard let url = URL(string: "\(apiBase)/{plural}") else {{ return }}
        do {{
            let (data, _) = try await URLSession.shared.data(from: url)
            if let json = try? JSONSerialization.jsonObject(with: data) as? [[String: Any]] {{
                rows = json.compactMap {{ $0["id"] as? String }}
            }}
        }} catch {{ /* 错误由宿主日志处理 */ }}
    }}
}}
"#
        );
        files.push((format!("Sources/{app}/{name}ListView.swift"), view));
    }
    files
}

// ── Jetpack Compose ───────────────────────────────────────────

fn compose_files(program: &Program, app: &str) -> Vec<(String, String)> {
    let pages = table_pages(program);
    let pkg = format!("dev.forma.{}", to_snake_case(app));
    let path = pkg.replace('.', "/");
    let mut files = vec![
        ("settings.gradle.kts".into(), format!("rootProject.name = \"{app}\"\n")),
        ("app/build.gradle.kts".into(),
            "plugins {\n    id(\"com.android.application\")\n    id(\"org.jetbrains.kotlin.android\")\n}\nandroid {\n    namespace = \"dev.forma.app\"\n    compileSdk = 34\n}\ndependencies {\n    implementation(platform(\"androidx.compose:compose-bom:2024.09.00\"))\n    implementation(\"androidx.activity:activity-compose:1.9.0\")\n    implementation(\"androidx.compose.material3:material3\")\n}\n".into()),
        (format!("app/src/main/java/{path}/MainActivity.kt"), {
            let mut nav = String::from("// @generated by Forma (gen-compose) — do not edit manually.\npackage dev.forma.app\n\nimport android.os.Bundle\nimport androidx.activity.ComponentActivity\nimport androidx.activity.compose.setContent\nimport androidx.compose.material3.*\nimport androidx.compose.runtime.*\n\nclass MainActivity : ComponentActivity() {\n    override fun onCreate(savedInstanceState: Bundle?) {\n        super.onCreate(savedInstanceState)\n        setContent { MaterialTheme { AppNav() } }\n    }\n}\n\n@Composable\nfun AppNav() {\n    var route by remember { mutableStateOf(\"home\") }\n    when (route) {\n");
            for (name, _, _) in &pages {
                nav.push_str(&format!("        \"{name}\" -> {name}ListScreen()\n"));
            }
            nav.push_str("        else -> Column {\n");
            for (name, title, _) in &pages {
                nav.push_str(&format!("            Button(onClick = {{ route = \"{name}\" }}) {{ Text(\"{title}\") }}\n"));
            }
            nav.push_str("    }\n}\n}\n");
            nav
        }),
        ("README.md".into(), format!("# {app} Jetpack Compose（generated by Forma）\n\n用 Android Studio 打开 `app/`，Sync Gradle 后运行。\n")),
    ];
    for (name, title, plural) in &pages {
        let screen = format!(
            r#"// @generated by Forma (gen-compose) — do not edit manually.
package dev.forma.app

import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.net.URL

@Composable
fun {name}ListScreen() {{
    var rows by remember {{ mutableStateOf(emptyList<String>()) }}
    LaunchedEffect(Unit) {{
        rows = withContext(Dispatchers.IO) {{
            try {{ URL("http://10.0.2.2:8080/api/{plural}").readText().split(",") }} catch (e: Exception) {{ emptyList() }}
        }}
    }}
    Text("{title}")
    LazyColumn {{ items(rows) {{ row -> ListItem(headlineContent = {{ Text(row) }}) }} }}
}}
"#
        );
        files.push((
            format!("app/src/main/java/{path}/{name}ListScreen.kt"),
            screen,
        ));
    }
    files
}

// ── 微信小程序 ────────────────────────────────────────────────

fn miniprogram_files(program: &Program, app: &str) -> Vec<(String, String)> {
    let pages = table_pages(program);
    let mut app_json_pages = String::new();
    for (name, _, _) in &pages {
        app_json_pages.push_str(&format!("    \"pages/{}/index\",\n", to_snake_case(name)));
    }
    let app_json = format!(
        "{{\n  \"pages\": [\n{app_json_pages}  ],\n  \"window\": {{ \"navigationBarTitleText\": \"{app}\" }}\n}}\n"
    );
    let mut files = vec![
        ("app.json".into(), app_json),
        ("app.js".into(), "// @generated by Forma (gen-miniprogram) — do not edit manually.\nApp({ globalData: { apiBase: 'http://localhost:8080/api' } });\n".into()),
        ("app.wxss".into(), "/* @generated by Forma (gen-miniprogram) */\n".into()),
        ("project.config.json".into(), "{\"compileType\":\"miniprogram\",\"setting\":{\"urlCheck\":false}}\n".into()),
        ("README.md".into(), format!("# {app} 微信小程序（generated by Forma）\n\n用微信开发者工具导入本目录；API 基址在 `app.js` 的 `globalData.apiBase`。\n")),
    ];
    for (name, title, plural) in &pages {
        let dir = to_snake_case(name);
        files.push((
            format!("pages/{dir}/index.json"),
            format!("{{\n  \"navigationBarTitleText\": \"{title}\"\n}}\n"),
        ));
        let wxml = r#"<!-- @generated by Forma (gen-miniprogram) — do not edit manually. -->
<view class="container">
  <view wx:for="{{rows}}" wx:key="id">
    <text>{{item.id}}</text>
  </view>
</view>
"#;
        files.push((format!("pages/{dir}/index.wxml"), wxml.to_string()));
        let js = format!(
            r#"// @generated by Forma (gen-miniprogram) — do not edit manually.
Page({{
  data: {{ rows: [] }},
  onLoad() {{
    const base = getApp().globalData.apiBase;
    wx.request({{
      url: base + '/{plural}',
      success: (res) => this.setData({{ rows: Array.isArray(res.data) ? res.data : [] }}),
    }});
  }},
}});
"#
        );
        files.push((format!("pages/{dir}/index.js"), js));
        files.push((
            format!("pages/{dir}/index.wxss"),
            "/* @generated by Forma (gen-miniprogram) */\n.container { padding: 16px; }\n".into(),
        ));
    }
    files
}

// ── uni-app ──────────────────────────────────────────────────

fn uniapp_files(program: &Program, app: &str) -> Vec<(String, String)> {
    let pages = table_pages(program);
    let mut page_entries = String::new();
    for (name, title, _) in &pages {
        let dir = to_snake_case(name);
        page_entries.push_str(&format!(
            "    {{ \"path\": \"pages/{dir}/index\", \"style\": {{ \"navigationBarTitleText\": \"{title}\" }} }},\n"
        ));
    }
    let pages_json = format!(
        "{{\n  \"pages\": [\n{page_entries}  ],\n  \"globalStyle\": {{ \"navigationBarTextStyle\": \"black\" }}\n}}\n"
    );
    let mut files = vec![
        ("pages.json".into(), pages_json),
        ("manifest.json".into(), format!("{{\n  \"name\": \"{app}\",\n  \"appid\": \"\",\n  \"vueVersion\": \"3\"\n}}\n")),
        ("App.vue".into(), "<script>\n// @generated by Forma (gen-uniapp) — do not edit manually.\nexport default { onLaunch() {} };\n</script>\n\n<style>\n/* @generated by Forma (gen-uniapp) */\n</style>\n".into()),
        ("main.js".into(), "// @generated by Forma (gen-uniapp) — do not edit manually.\nimport { createSSRApp } from 'vue';\nimport App from './App.vue';\nexport function createApp() { return { app: createSSRApp(App) }; }\n".into()),
        ("README.md".into(), format!("# {app} uni-app（generated by Forma）\n\n用 HBuilderX 导入本目录，或 `npm run dev:%platform%`。\n")),
    ];
    for (name, title, plural) in &pages {
        let dir = to_snake_case(name);
        let vue = format!(
            r#"<!-- @generated by Forma (gen-uniapp) — do not edit manually. -->
<template>
  <view class="container">
    <text>{title}</text>
    <view v-for="row in rows" :key="row.id">{{{{ row.id }}}}</view>
  </view>
</template>

<script>
export default {{
  data() {{ return {{ rows: [] }}; }},
  onLoad() {{
    uni.request({{
      url: 'http://localhost:8080/api/{plural}',
      success: (res) => {{ this.rows = Array.isArray(res.data) ? res.data : []; }},
    }});
  }},
}};
</script>

<style>
.container {{ padding: 16px; }}
</style>
"#
        );
        files.push((format!("pages/{dir}/index.vue"), vue));
        let _ = title;
    }
    files
}

pub fn emit_swiftui(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.pages.is_empty() {
        return Ok(vec![]);
    }
    let app = program
        .app
        .as_ref()
        .map(|a| to_snake_case(&a.name))
        .unwrap_or_else(|| "app".into());
    write_all(
        project_dir,
        out_dir,
        swiftui_files(program, &app),
        "gen-swiftui",
    )
}

