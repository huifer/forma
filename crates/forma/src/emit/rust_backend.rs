pub fn emit_rust_backend(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> Result<Vec<crate::generators::GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    // 设计宪法 6.2：不支持的构造显式报错，不做静默降级（cursor 分页尚无 emitter 实现）
    for api in &program.apis {
        if let Some(list) = &api.list {
            if let Some(p) = &list.paginate {
                if p != "offset" {
                    anyhow::bail!(
                        "api {}.list: paginate `{p}` 尚无 emitter 实现（当前仅支持 offset）。\
                         如需 cursor 分页请先在 emitter 落地。",
                        api.entity
                    );
                }
            }
        }
    }
    let pkg = format!("{}-backend", app_name.to_lowercase());
    let mut files: Vec<crate::generators::GeneratedFile> = Vec::new();

    files.push(file(out_dir, "Cargo.toml", cargo_toml(&pkg), "gen-rust"));
    files.push(file(out_dir, "src/error.rs", error_rs(), "gen-rust"));
    files.push(file(
        out_dir,
        "src/models.rs",
        models_rs(program),
        "gen-rust",
    ));
    files.push(file(
        out_dir,
        "src/validators.rs",
        validators_rs(program),
        "gen-rust",
    ));
    files.push(file(out_dir, "src/repo.rs", repo_rs(program), "gen-rust"));
    files.push(file(
        out_dir,
        "src/routes.rs",
        routes_rs(program),
        "gen-rust",
    ));
    files.push(file(out_dir, "src/main.rs", main_rs(program), "gen-rust"));
    files.push(file(
        out_dir,
        ".env.example",
        "DATABASE_URL=mysql://root:root@localhost:3306/school\n".into(),
        "gen-rust",
    ));
    files.push(file(
        out_dir,
        "README.md",
        format!(
            "# {app_name} backend (generated by Forma)\n\n```bash\n# 1. create schema\nmysql -u root -p < ../db/migrations/0001_init.sql\n# 2. run\nexport DATABASE_URL=mysql://root:root@localhost:3306/school\ncargo run\n```\nAPI base: http://localhost:8080/api\n"
        ),
        "gen-rust",
    ));

    // 写盘（内容不变则跳过）
    let mut written = Vec::new();
    for f in files {
        let abs = project_dir.join(&f.path);
        let hash = sha256_hex(&f.content);
        let unchanged = abs.is_file()
            && crate::util::read_text(&abs)
                .map(|c| sha256_hex(&c) == hash)
                .unwrap_or(false);
        if !unchanged {
            write_text(&abs, &f.content)?;
        }
        written.push(f);
    }
    Ok(written)
}

fn file(
    out_dir: &str,
    rel: &str,
    content: String,
    generator: &str,
) -> crate::generators::GeneratedFile {
    crate::generators::GeneratedFile {
        path: format!("{out_dir}/{rel}"),
        content,
        generator: generator.into(),
    }
}

