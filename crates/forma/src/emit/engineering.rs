//! M9 工程化：为生成项目产出 Makefile + GitHub Actions CI 模板。
//!
//! 后端 Makefile：build / check / test / run / migrate / seed / docker 全生命周期。
//! 后端 CI：GitHub Actions workflow（cargo check + cargo build）。
//! Web CI：npm install + tsc + vitest + vite build。

use crate::dsl::Program;
use crate::generators::GeneratedFile;
use std::path::Path;

pub fn emit_backend_engineering(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    let has_auth = program.auth.is_some();
    let has_web = !program.pages.is_empty();
    let db_name = crate::identity::to_snake_case(app_name).replace('_', "-");

    let mut files = Vec::new();

    // ── Makefile ──
    let migrate_dir = "../db/migrations";
    let seed_dir = "../db/seed";
    let mut makefile = format!(
        r#"# @generated by Forma (gen-rust) — do not edit manually.
# {app} backend 工程化目标：build / check / test / run / migrate / seed / docker

APP_NAME      = {app}
DATABASE_URL ?= mysql://root:root@localhost:3306/{db}
PORT         ?= 8080

.PHONY: build check test run migrate seed docker fmt

build:
	cargo build --release

check:
	cargo check

test:
	cargo test

fmt:
	cargo fmt

run:
	DATABASE_URL=$(DATABASE_URL) PORT=$(PORT) cargo run

"#,
        app = app_name,
        db = db_name
    );

    // 迁移目标（数据库迁移文件在 ../db/migrations）
    makefile.push_str(&format!(
        r#"migrate:
	@echo "applying migrations from {migrate_dir}..."
	@for f in {migrate_dir}/*_init.sql {migrate_dir}/*_upgrade.sql; do \\
		[ -f "$$f" ] || continue; \\
		echo "  → $$(basename $$f)"; \\
		mysql -u root -p "$$(DATABASE_URL)" < "$$f" || exit 1; \\
	done

seed:
	@echo "applying seed data from {seed_dir}..."
	@for f in {seed_dir}/*.sql; do \\
		[ -f "$$f" ] || continue; \\
		echo "  → $$(basename $$f)"; \\
		mysql -u root -p "$$(DATABASE_URL)" < "$$f" || exit 1; \\
	done

docker:
	cd .. && docker-compose up --build
"#
    ));

    files.push(GeneratedFile {
        path: format!("{out_dir}/Makefile"),
        content: makefile,
        generator: "gen-rust".into(),
    });

    // ── GitHub Actions CI ──
    let mut ci = String::from(
        r#"# @generated by Forma (gen-rust) — do not edit manually.
name: CI

on:
  push:
    branches: [main]
  pull_request:

jobs:
"#,
    );

    // backend job
    ci.push_str(
        r#"  backend:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: dtolnay/rust-toolchain@stable
      - uses: Swatinem/rust-cache@v2
      - name: Check
        run: cargo check
      - name: Test
        run: cargo test
      - name: Build
        run: cargo build --release
"#,
    );

    // web job（有 Web 页面时）
    if has_web {
        ci.push_str(
            r#"
  web:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - name: Install + Type check + Test + Build
        working-directory: ../generated/web
        run: |
          npm install --no-audit --no-fund
          npx tsc --noEmit
          npx vitest run
          npm run build
"#,
        );
    }

    // Flutter job（有 mobile target 时）
    // 由调用方判断——这里通过检查是否有 mobile pages 来推断
    // 简化：不在 backend CI 里做 Flutter（属于 mobile target）

    ci.push_str("}\n");
    files.push(GeneratedFile {
        path: format!("{out_dir}/.github/workflows/ci.yml"),
        content: ci,
        generator: "gen-rust".into(),
    });

    let _ = has_auth;
    for f in &files {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(files)
}

pub fn emit_web_engineering(
    project_dir: &Path,
    _program: &Program,
    out_dir: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if _program.entities.is_empty() {
        return Ok(vec![]);
    }
    let mut files = Vec::new();
    // Web CI：npm install + tsc + vitest + build
    let ci = r#"# @generated by Forma (gen-web) — do not edit manually.
name: Web CI

on:
  push:
    branches: [main]
  pull_request:

jobs:
  web:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - name: Install
        run: npm install --no-audit --no-fund
      - name: Type check
        run: npx tsc --noEmit
      - name: Test
        run: npx vitest run
      - name: Build
        run: npm run build
"#;
    files.push(GeneratedFile {
        path: format!("{out_dir}/.github/workflows/ci.yml"),
        content: ci.to_string(),
        generator: "gen-web".into(),
    });
    for f in &files {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(files)
}
