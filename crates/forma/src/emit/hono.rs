//! Hono backend target（M10）：轻量 Node/TypeScript CRUD backend。
//!
//! 支持：标量字段、枚举、基础关系字符串引用、Decimal、list/get/create/update/delete。
//! 显式拒绝 auth/access/tenant/commands/cross-field checks/guards，避免安全语义静默降级。

use crate::dsl::{has_attr, is_enum, is_relation, FieldDecl, Program};
use crate::generators::GeneratedFile;
use crate::identity::to_snake_case;
use std::path::Path;

pub fn emit_hono(
    project_dir: &Path,
    program: &Program,
    out_dir: &str,
    app_name: &str,
) -> anyhow::Result<Vec<GeneratedFile>> {
    if program.entities.is_empty() {
        return Ok(vec![]);
    }
    reject_unsupported(program)?;
    let files = vec![
        file(out_dir, "package.json", package_json(app_name)),
        file(out_dir, "tsconfig.json", tsconfig()),
        file(out_dir, "src/types.ts", types_ts(program)),
        file(out_dir, "src/validators.ts", validators_ts(program)),
        file(out_dir, "src/index.ts", index_ts(program, app_name)),
        file(out_dir, "README.md", readme(app_name)),
    ];

    for f in &files {
        crate::util::write_text(&project_dir.join(&f.path), &f.content)?;
    }
    Ok(files)
}

fn reject_unsupported(program: &Program) -> anyhow::Result<()> {
    let mut unsupported = Vec::new();
    if program.auth.is_some() {
        unsupported.push("auth module (JWT/RBAC)");
    }
    if !program.commands.is_empty() {
        unsupported.push("command operations");
    }
    if program.rules.iter().any(|r| !r.access.is_empty()) {
        unsupported.push("access/row/field policies");
    }
    if program
        .rules
        .iter()
        .any(|r| !r.checks.is_empty() || !r.guards.is_empty())
    {
        unsupported.push("cross-field checks/guards");
    }
    if program
        .entities
        .iter()
        .flat_map(|e| &e.fields)
        .any(|f| has_attr(f, "tenant"))
    {
        unsupported.push("tenant isolation");
    }
    if !unsupported.is_empty() {
        anyhow::bail!(
            "Hono target currently supports scalar CRUD only; unsupported DSL features: {}. Select backend.language: rust to preserve full semantics",
            unsupported.join(", ")
        );
    }
    Ok(())
}

fn file(out_dir: &str, rel: &str, content: String) -> GeneratedFile {
    GeneratedFile {
        path: format!("{out_dir}/{rel}"),
        content,
        generator: "gen-hono".into(),
    }
}

fn package_json(app_name: &str) -> String {
    let name = to_snake_case(app_name).replace('_', "-");
    format!(
        r#"{{
  "name": "{name}-hono-backend",
  "version": "0.1.0",
  "private": true,
  "type": "module",
  "scripts": {{
    "dev": "tsx watch src/index.ts",
    "build": "tsc",
    "start": "node dist/index.js"
  }},
  "dependencies": {{
    "@hono/node-server": "^1.13.0",
    "hono": "^4.6.0",
    "mysql2": "^3.11.0",
    "zod": "^3.23.8"
  }},
  "devDependencies": {{
    "@types/node": "^22.0.0",
    "tsx": "^4.19.0",
    "typescript": "^5.5.4"
  }}
}}
"#
    )
}

fn tsconfig() -> String {
    r#"{
  "compilerOptions": {
    "target": "ES2022",
    "module": "NodeNext",
    "moduleResolution": "NodeNext",
    "strict": true,
    "esModuleInterop": true,
    "skipLibCheck": true,
    "outDir": "dist",
    "rootDir": "src"
  },
  "include": ["src/**/*.ts"]
}
"#
    .to_string()
}

fn ts_type(program: &Program, field: &FieldDecl) -> String {
    if is_relation(program, &field.type_name) || is_enum(program, &field.type_name) {
        return "string".into();
    }
    match field.type_name.as_str() {
        "Int" | "Float" | "Decimal" => "number".into(),
        "Bool" => "boolean".into(),
        "Json" => "unknown".into(),
        _ => "string".into(),
    }
}

fn types_ts(program: &Program) -> String {
    let mut out = String::from("// @generated by Forma (gen-hono) — do not edit manually.\n\n");
    for entity in &program.entities {
        out.push_str(&format!("export interface {} {{\n", entity.name));
        for f in &entity.fields {
            let name = to_snake_case(&f.name);
            let name = if is_relation(program, &f.type_name) {
                format!("{}_id", name)
            } else {
                name
            };
            out.push_str(&format!(
                "  {name}{optional}: {ty};\n",
                optional = if f.optional { "?" } else { "" },
                ty = ts_type(program, f)
            ));
        }
        out.push_str("}\n\n");
    }
    out
}

fn validators_ts(program: &Program) -> String {
    let mut out = String::from(
        "// @generated by Forma (gen-hono) — do not edit manually.\nimport { z } from \"zod\";\n\n",
    );
    for entity in &program.entities {
        let mut fields = String::new();
        for f in &entity.fields {
            if has_attr(f, "id") || has_attr(f, "readonly") {
                continue;
            }
            let name = if is_relation(program, &f.type_name) {
                format!("{}_id", to_snake_case(&f.name))
            } else {
                to_snake_case(&f.name)
            };
            let base = match f.type_name.as_str() {
                "Int" => "z.number().int()".to_string(),
                "Float" | "Decimal" => "z.number()".to_string(),
                "Bool" => "z.boolean()".to_string(),
                "Json" => "z.unknown()".to_string(),
                _ => "z.string()".to_string(),
            };
            let optional = f.optional || has_attr(f, "default") || has_attr(f, "readonly");
            fields.push_str(&format!(
                "  {name}: {base}{optional},\n",
                optional = if optional { ".optional()" } else { "" }
            ));
        }
        out.push_str(&format!(
            "export const create{0}Schema = z.object({{\n{fields}}});\nexport const update{0}Schema = create{0}Schema.partial();\n\n",
            entity.name
        ));
    }
    out
}

fn index_ts(program: &Program, app_name: &str) -> String {
    let mut routes = String::new();
    let mut imports = String::new();
    for entity in &program.entities {
        let name = &entity.name;
        let plural = crate::dsl::pluralize(name).to_lowercase();
        imports.push_str(&format!(
            "import {{ create{name}Schema, update{name}Schema }} from \"./validators.js\";\n"
        ));
        let columns: Vec<String> = entity
            .fields
            .iter()
            .map(|f| {
                if is_relation(program, &f.type_name) {
                    format!("{}_id", to_snake_case(&f.name))
                } else {
                    to_snake_case(&f.name)
                }
            })
            .collect();
        let column_list = columns.join(", ");
        let insert_columns: Vec<String> = columns.iter().filter(|c| *c != "id").cloned().collect();
        let insert_list = insert_columns.join(", ");
        let insert_marks = vec!["?"; insert_columns.len()].join(", ");
        let insert_values = insert_columns
            .iter()
            .map(|c| format!("body.{c}"))
            .collect::<Vec<_>>()
            .join(", ");
        routes.push_str(&format!(
            r#"
app.get("/api/{plural}", async (c) => {{
  const page = Math.max(Number(c.req.query("page") ?? 1), 1);
  const pageSize = Math.min(Math.max(Number(c.req.query("pageSize") ?? 20), 1), 200);
  const [rows] = await db.query("SELECT {column_list} FROM {plural} LIMIT ? OFFSET ?", [pageSize, (page - 1) * pageSize]);
  return c.json(rows);
}});

app.get("/api/{plural}/:id", async (c) => {{
  const [rows] = await db.query("SELECT {column_list} FROM {plural} WHERE id = ?", [c.req.param("id")]);
  const row = (rows as any[])[0];
  return row ? c.json(row) : c.json({{ error: "not found", code: "FORMA_NOT_FOUND" }}, 404);
}});

app.post("/api/{plural}", async (c) => {{
  const body = create{name}Schema.parse(await c.req.json());
  const id = crypto.randomUUID();
  await db.query("INSERT INTO {plural} (id, {insert_list}) VALUES (?, {insert_marks})", [id, {insert_values}]);
  const [rows] = await db.query("SELECT {column_list} FROM {plural} WHERE id = ?", [id]);
  return c.json((rows as any[])[0], 201);
}});

app.put("/api/{plural}/:id", async (c) => {{
  const body = update{name}Schema.parse(await c.req.json());
  const fields = Object.keys(body);
  if (fields.length === 0) return c.json({{ error: "empty update", code: "FORMA_VALIDATION_FAILED" }}, 400);
  const values = fields.map((f) => (body as any)[f]);
  await db.query(`UPDATE {plural} SET ${{fields.map((f) => `\`${{f}}\` = ?`).join(", ")}} WHERE id = ?`, [...values, c.req.param("id")]);
  const [rows] = await db.query("SELECT {column_list} FROM {plural} WHERE id = ?", [c.req.param("id")]);
  return (rows as any[])[0] ? c.json((rows as any[])[0]) : c.json({{ error: "not found", code: "FORMA_NOT_FOUND" }}, 404);
}});

app.delete("/api/{plural}/:id", async (c) => {{
  const [result] = await db.query("DELETE FROM {plural} WHERE id = ?", [c.req.param("id")]);
  return c.json({{ ok: true, affected: (result as any).affectedRows ?? 0 }});
}});
"#,
            name = name,
            plural = plural,
            column_list = column_list,
            insert_list = insert_list,
            insert_marks = insert_marks,
            insert_values = insert_values,
        ));
    }
    format!(
        r#"// @generated by Forma (gen-hono) — do not edit manually.
import {{ serve }} from "@hono/node-server";
import {{ Hono }} from "hono";
import mysql from "mysql2/promise";
{imports}
const db = mysql.createPool(process.env.DATABASE_URL ?? "mysql://root:root@localhost:3306/{db}");
const app = new Hono();

{routes}
const port = Number(process.env.PORT ?? 8080);
serve({{ fetch: app.fetch, port }});
console.log(`Hono backend listening on http://0.0.0.0:${{port}}/api`);
"#,
        imports = imports,
        routes = routes,
        db = to_snake_case(app_name),
    )
}

fn readme(app_name: &str) -> String {
    format!(
        "# {app_name} Hono backend (generated by Forma)\n\n```bash\nnpm install\nnpm run dev\n```\n\nSet `DATABASE_URL` and `PORT` before starting.\n"
    )
}
