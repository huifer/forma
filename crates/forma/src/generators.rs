//! 代码生成器：JSON Schema → TS 类型/校验器；OpenAPI → Hono 路由；
//! SQL DDL → SQLite 迁移；JSON Forms → React 表单。

use crate::engine::GenerateContext;
use anyhow::Result;
use serde::Serialize;

#[derive(Debug, Clone, Serialize)]
pub struct GeneratedFile {
    /// 项目相对路径
    pub path: String,
    pub content: String,
    pub generator: String,
}

pub trait Generator {
    fn id(&self) -> &'static str;
    fn version(&self) -> &'static str;
    fn generate(&self, ctx: &GenerateContext<'_>) -> Result<Vec<GeneratedFile>>;
}

pub fn generated_header(generator: &str) -> String {
    format!("// @generated by Forma ({generator}) — do not edit manually.\n// Regenerate with: forma build")
}

pub fn default_generators() -> Vec<Box<dyn Generator>> {
    vec![
        Box::new(ts_types::TsTypesGenerator),
        Box::new(hono_routes::HonoRoutesGenerator),
        Box::new(sqlite_migration::SqliteMigrationGenerator),
        Box::new(react_forms::ReactFormsGenerator),
    ]
}

/// 实体过滤：ctx.entities 为空 = 全部。
pub fn entity_in_scope(ctx: &GenerateContext<'_>, entity_uri: Option<&str>) -> bool {
    match &ctx.entities {
        None => true,
        Some(list) if list.is_empty() => true,
        Some(list) => match entity_uri {
            Some(uri) => list.iter().any(|e| e == uri),
            None => false,
        },
    }
}

pub mod ts_types {
    use super::*;

    pub struct TsTypesGenerator;

    impl Generator for TsTypesGenerator {
        fn id(&self) -> &'static str {
            "ts-types"
        }
        fn version(&self) -> &'static str {
            "1"
        }

        fn generate(&self, ctx: &GenerateContext<'_>) -> Result<Vec<GeneratedFile>> {
            let out_dir = ctx
                .loaded
                .manifest
                .targets
                .typescript
                .clone()
                .unwrap_or_else(|| "generated/types".into());

            let types: Vec<&crate::graph::SemanticNode> = ctx
                .graph
                .nodes_by_kind(crate::graph::NodeKind::Type)
                .into_iter()
                .filter(|n| n.standard == crate::graph::Standard::JsonSchema)
                .filter(|n| entity_in_scope(ctx, n.data.get("entityUri").and_then(|v| v.as_str())))
                .collect();
            if types.is_empty() {
                return Ok(vec![]);
            }

            let mut interfaces: Vec<String> = Vec::new();
            let mut validators: Vec<String> = Vec::new();
            let mut names: Vec<String> = Vec::new();

            for node in &types {
                let id = node
                    .data
                    .get("$id")
                    .and_then(|v| v.as_str())
                    .unwrap_or("Entity");
                let ts_name = crate::identity::to_pascal_case(id);
                names.push(ts_name.clone());
                let required: Vec<String> = node
                    .data
                    .get("required")
                    .and_then(|v| v.as_array())
                    .map(|a| {
                        a.iter()
                            .filter_map(|x| x.as_str().map(String::from))
                            .collect()
                    })
                    .unwrap_or_default();
                let props: Vec<serde_json::Value> = node
                    .data
                    .get("properties")
                    .and_then(|v| v.as_array())
                    .cloned()
                    .unwrap_or_default();
                interfaces.push(render_interface(&ts_name, &props, &required));
                validators.push(render_validator(&ts_name, &props, &required));
            }

            let types_ts = format!(
                "{}\n\n{}\n/// Entity name registry（供 API 路由与测试引用）\nexport const FORMA_ENTITIES = {} as const;\n",
                generated_header(&format!("{}@{}", self.id(), self.version())),
                interfaces.join("\n\n"),
                serde_json::to_string(&names)?
            );
            let validators_ts = format!(
                "{}\n\nimport type {{ {} }} from './types.js';\n\n// 零依赖运行时校验（由 JSON Schema 子集生成：type / required / enum / minLength / maxLength）\n{}\n",
                generated_header(&format!("{}@{}", self.id(), self.version())),
                names.join(", "),
                validators.join("\n\n")
            );

            Ok(vec![
                GeneratedFile {
                    path: format!("{out_dir}/types.ts"),
                    content: types_ts,
                    generator: self.id().into(),
                },
                GeneratedFile {
                    path: format!("{out_dir}/validators.ts"),
                    content: validators_ts,
                    generator: self.id().into(),
                },
            ])
        }
    }

    fn ts_type(prop: &serde_json::Value) -> String {
        if let Some(enum_vals) = prop.get("enum").and_then(|v| v.as_array()) {
            if !enum_vals.is_empty() {
                let parts: Vec<String> = enum_vals
                    .iter()
                    .map(|v| serde_json::to_string(v).unwrap_or_default())
                    .collect();
                return parts.join(" | ");
            }
        }
        let t = prop
            .get("type")
            .and_then(|v| v.as_str())
            .unwrap_or("unknown");
        match t {
            "string" => "string".into(),
            "integer" | "number" => "number".into(),
            "boolean" => "boolean".into(),
            "object" => "Record<string, unknown>".into(),
            "array" => {
                let item = prop
                    .get("items")
                    .and_then(|v| v.get("type"))
                    .and_then(|v| v.as_str())
                    .unwrap_or("unknown");
                let inner = match item {
                    "string" => "string",
                    "integer" | "number" => "number",
                    "boolean" => "boolean",
                    _ => "unknown",
                };
                format!("{inner}[]")
            }
            _ => "unknown".into(),
        }
    }

    fn safe_prop_name(name: &str) -> String {
        let first_ok = name
            .chars()
            .next()
            .map(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
            .unwrap_or(false);
        let rest_ok = name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
        if first_ok && rest_ok {
            name.to_string()
        } else {
            serde_json::to_string(name).unwrap_or_default()
        }
    }

    fn render_interface(ts_name: &str, props: &[serde_json::Value], required: &[String]) -> String {
        let mut lines = vec![format!("export interface {ts_name} {{")];
        for prop in props {
            let name = prop
                .get("name")
                .and_then(|v| v.as_str())
                .unwrap_or_default();
            let is_required = required.iter().any(|r| r == name);
            let optional = if is_required { "" } else { "?" };
            let description = prop.get("description").and_then(|v| v.as_str());
            if let Some(d) = description {
                lines.push(format!("  /** {d} */"));
            }
            lines.push(format!(
                "  {}{}: {};",
                safe_prop_name(name),
                optional,
                ts_type(prop)
            ));
        }
        lines.push("}".to_string());
        lines.join("\n")
    }

    fn render_validator(ts_name: &str, props: &[serde_json::Value], required: &[String]) -> String {
        let mut checks = vec![
            "  if (typeof value !== 'object' || value === null) return false;".to_string(),
            "  const v = value as Record<string, unknown>;".to_string(),
        ];
        for prop in props {
            let name = prop
                .get("name")
                .and_then(|v| v.as_str())
                .unwrap_or_default();
            let is_required = required.iter().any(|r| r == name);
            if is_required {
                checks.push(format!("  if (!('{name}' in v)) return false;"));
            }

            let mut type_checks: Vec<String> = Vec::new();
            let t = prop.get("type").and_then(|v| v.as_str()).unwrap_or("");
            match t {
                "string" => {
                    type_checks.push(format!("typeof v['{name}'] === 'string'"));
                    if let Some(min) = prop.get("minLength").and_then(|v| v.as_u64()) {
                        type_checks.push(format!("(v['{name}'] as string).length >= {min}"));
                    }
                    if let Some(max) = prop.get("maxLength").and_then(|v| v.as_u64()) {
                        type_checks.push(format!("(v['{name}'] as string).length <= {max}"));
                    }
                }
                "integer" => type_checks.push(format!("Number.isInteger(v['{name}'])")),
                "number" => type_checks.push(format!(
                    "typeof v['{name}'] === 'number' && Number.isFinite(v['{name}'])"
                )),
                "boolean" => type_checks.push(format!("typeof v['{name}'] === 'boolean'")),
                _ => {}
            }
            if let Some(enum_vals) = prop.get("enum").and_then(|v| v.as_array()) {
                if !enum_vals.is_empty() && t != "integer" && t != "number" {
                    let parts: Vec<String> = enum_vals
                        .iter()
                        .map(|v| serde_json::to_string(v).unwrap_or_default())
                        .collect();
                    type_checks.push(format!(
                        "[{}].includes(v['{name}'] as string)",
                        parts.join(", ")
                    ));
                }
            }
            if !type_checks.is_empty() {
                let joined = type_checks.join(" && ");
                if is_required {
                    checks.push(format!("  if (!({joined})) return false;"));
                } else {
                    checks.push(format!(
                        "  if ('{name}' in v && v['{name}'] !== undefined && !({joined})) return false;"
                    ));
                }
            }
        }
        format!(
            "export function isValid{ts_name}(value: unknown): value is {ts_name} {{\n{}\n  return true;\n}}",
            checks.join("\n")
        )
    }
}

pub mod hono_routes {
    use super::*;
    use crate::graph::NodeKind;
    use crate::identity::{singularize, to_pascal_case};

    pub struct HonoRoutesGenerator;

    impl Generator for HonoRoutesGenerator {
        fn id(&self) -> &'static str {
            "hono-routes"
        }
        fn version(&self) -> &'static str {
            "1"
        }

        fn generate(&self, ctx: &GenerateContext<'_>) -> Result<Vec<GeneratedFile>> {
            let backend = ctx.loaded.manifest.targets.backend.clone();
            if let Some(b) = &backend {
                if let Some(fw) = &b.framework {
                    if fw != "hono" {
                        return Ok(vec![]);
                    }
                }
            }
            let out_dir = backend
                .and_then(|b| b.out)
                .unwrap_or_else(|| "generated/backend".into());

            let ops: Vec<&crate::graph::SemanticNode> = ctx
                .graph
                .nodes_by_kind(NodeKind::ApiOperation)
                .into_iter()
                .filter(|n| entity_in_scope(ctx, Some(&infer_entity_uri(ctx, n))))
                .collect();
            if ops.is_empty() {
                return Ok(vec![]);
            }

            // 分组：实体 → 操作
            let mut by_entity: std::collections::BTreeMap<
                String,
                Vec<&crate::graph::SemanticNode>,
            > = Default::default();
            for op in &ops {
                by_entity.entry(infer_entity(ctx, op)).or_default().push(op);
            }

            let mut imports: Vec<String> = vec!["import { Hono } from 'hono';".to_string()];
            let mut blocks: Vec<String> = Vec::new();

            for (entity, entity_ops) in &by_entity {
                let ts_name = to_pascal_case(entity);
                let route_var = format!("{}Routes", entity.to_lowercase());
                let validator = format!("isValid{ts_name}");
                imports.push(format!(
                    "import {{ {validator}, type {ts_name} }} from '../../generated/types/validators.js';"
                ));

                let mut lines = vec![
                    format!("/** {ts_name} API — 由 OpenAPI 契约生成，业务逻辑写在 handler 内 */"),
                    format!("export const {route_var} = new Hono();"),
                    String::new(),
                ];
                let mut ops_sorted: Vec<&&crate::graph::SemanticNode> = entity_ops.iter().collect();
                ops_sorted.sort_by(|a, b| a.name.cmp(&b.name));
                for op in ops_sorted {
                    lines.push(render_operation(op, &route_var, &ts_name, &validator));
                    lines.push(String::new());
                }
                blocks.push(lines.join("\n").trim_end().to_string());
            }

            imports.sort();
            imports.dedup();
            let content = format!(
                "{}\n\n{}\n\n{}\n",
                generated_header(&format!("{}@{}", self.id(), self.version())),
                imports.join("\n"),
                blocks.join("\n\n")
            );
            Ok(vec![GeneratedFile {
                path: format!("{out_dir}/routes.ts"),
                content,
                generator: self.id().into(),
            }])
        }
    }

    fn infer_entity(_ctx: &GenerateContext<'_>, op: &crate::graph::SemanticNode) -> String {
        let data = &op.data;
        let mut refs: Vec<String> = Vec::new();
        if let Some(r) = data.get("requestSchemaRef").and_then(|v| v.as_str()) {
            refs.push(r.to_string());
        }
        if let Some(arr) = data.get("responseSchemaRefs").and_then(|v| v.as_array()) {
            for x in arr {
                if let Some(s) = x.as_str() {
                    refs.push(s.to_string());
                }
            }
        }
        for r in &refs {
            if let Some(name) = r.strip_prefix("#/components/schemas/") {
                return name.to_string();
            }
        }
        let operation_id = data
            .get("operationId")
            .and_then(|v| v.as_str())
            .unwrap_or("");
        for prefix in [
            "create", "add", "list", "get", "update", "patch", "delete", "remove",
        ] {
            if let Some(rest) = operation_id.strip_prefix(prefix) {
                if let Some(first) = rest.chars().next() {
                    if first.is_uppercase() {
                        return singularize(rest.trim_end_matches(|c: char| {
                            c == 'I' || (c.is_uppercase() && rest.ends_with("ById") && c == 'd')
                        }));
                    }
                }
            }
        }
        "Common".to_string()
    }

    fn infer_entity_uri(ctx: &GenerateContext<'_>, op: &crate::graph::SemanticNode) -> String {
        crate::identity::entity_uri(&ctx.loaded.manifest.project_name, &infer_entity(ctx, op))
    }

    fn render_operation(
        op: &crate::graph::SemanticNode,
        route_var: &str,
        ts_name: &str,
        validator: &str,
    ) -> String {
        let data = &op.data;
        let method = data.get("method").and_then(|v| v.as_str()).unwrap_or("get");
        let path = data.get("path").and_then(|v| v.as_str()).unwrap_or("/");
        // {id} → :id
        let hono_path: String = path
            .chars()
            .filter_map(|c| match c {
                '{' => Some(':'),
                '}' => None,
                other => Some(other),
            })
            .collect();
        let operation_id = data
            .get("operationId")
            .and_then(|v| v.as_str())
            .unwrap_or("handler");
        let handler_var = format!("{}{}", operation_id[..1].to_lowercase(), &operation_id[1..]);
        let summary = data
            .get("summary")
            .and_then(|v| v.as_str())
            .unwrap_or(operation_id);
        let path_params: Vec<String> = data
            .get("parameters")
            .and_then(|v| v.as_array())
            .map(|a| {
                a.iter()
                    .filter(|p| p.get("in").and_then(|v| v.as_str()) == Some("path"))
                    .filter_map(|p| p.get("name").and_then(|v| v.as_str()).map(String::from))
                    .collect()
            })
            .unwrap_or_default();

        let mut lines = vec![format!(
            "/** {summary} — {} {path} */",
            method.to_uppercase()
        )];
        match method {
            "post" | "put" | "patch" => {
                lines.push(format!(
                    "{route_var}.{method}('{hono_path}', async (c) => {{"
                ));
                lines.push("  const body = (await c.req.json()) as unknown;".to_string());
                lines.push(format!("  if (!{validator}(body)) {{"));
                lines.push(format!(
                    "    return c.json({{ error: 'invalid {} payload' }}, 400);",
                    ts_name.to_lowercase()
                ));
                lines.push("  }".to_string());
                lines.push(format!("  const {handler_var} = body as {ts_name};"));
                lines.push(format!(
                    "  // TODO: implement {operation_id} business logic"
                ));
                let code = if method == "post" { 201 } else { 200 };
                lines.push(format!(
                    "  return c.json({{ ok: true, {handler_var} }}, {code});"
                ));
                lines.push("});".to_string());
            }
            "delete" => {
                lines.push(format!("{route_var}.delete('{hono_path}', async (c) => {{"));
                if !path_params.is_empty() {
                    lines.push(format!(
                        "  const {{ {} }} = c.req.param();",
                        path_params.join(", ")
                    ));
                }
                lines.push(format!("  // TODO: implement {operation_id}"));
                lines.push("  return c.json({ ok: true }, 200);".to_string());
                lines.push("});".to_string());
            }
            _ => {
                lines.push(format!("{route_var}.get('{hono_path}', async (c) => {{"));
                if !path_params.is_empty() {
                    lines.push(format!(
                        "  const {{ {} }} = c.req.param();",
                        path_params.join(", ")
                    ));
                }
                lines.push(format!("  // TODO: implement {operation_id}"));
                lines.push("  return c.json({ ok: true });".to_string());
                lines.push("});".to_string());
            }
        }
        lines.join("\n")
    }
}

pub mod sqlite_migration {
    use super::*;
    use crate::adapters::sql::{parse_sql_ddl, SqlColumn, SqlIndex, SqlTable};
    use std::path::Path;

    pub struct SqliteMigrationGenerator;

    impl Generator for SqliteMigrationGenerator {
        fn id(&self) -> &'static str {
            "sqlite-migration"
        }
        fn version(&self) -> &'static str {
            "1"
        }

        fn generate(&self, ctx: &GenerateContext<'_>) -> Result<Vec<GeneratedFile>> {
            let out_dir = ctx
                .loaded
                .manifest
                .targets
                .database
                .clone()
                .and_then(|d| d.out)
                .unwrap_or_else(|| "generated/database".into());
            let entries = ctx.loaded.manifest.group("database");
            if entries.is_empty() {
                return Ok(vec![]);
            }

            let mut tables: Vec<SqlTable> = Vec::new();
            let mut indexes: Vec<SqlIndex> = Vec::new();
            let mut first_source: Option<String> = None;
            for entry in entries {
                let abs = ctx.loaded.dir.join(&entry.path);
                let sql = crate::util::read_text(&abs)?;
                if first_source.is_none() {
                    first_source = Some(entry.path.clone());
                }
                let parsed = parse_sql_ddl(&sql)?;
                tables.extend(parsed.tables);
                indexes.extend(parsed.indexes);
            }
            if tables.is_empty() {
                return Ok(vec![]);
            }

            let migrations_dir = ctx.loaded.dir.join(&out_dir).join("migrations");
            let init_file = migrations_dir.join("0001_init.sql");
            if init_file.is_file() && !ctx.force {
                return Ok(vec![]);
            }

            let mut content = format!(
                "-- @generated by Forma ({}@{}) — do not edit manually.\n-- Project: {} v{}\n-- Baseline migration from SQL DDL specification.\n-- source {}\n\n",
                self.id(),
                self.version(),
                ctx.loaded.manifest.project_name,
                ctx.loaded.manifest.project_version,
                first_source.unwrap_or_default()
            );
            for t in &tables {
                content.push_str(&render_table(t));
                content.push('\n');
            }
            content.push('\n');
            for i in &indexes {
                content.push_str(&render_index(i));
                content.push_str("\n\n");
            }

            Ok(vec![GeneratedFile {
                path: format!("{out_dir}/migrations/0001_init.sql"),
                content,
                generator: self.id().into(),
            }])
        }
    }

    fn render_column(c: &SqlColumn) -> String {
        let mut def = format!(
            "  {} {}",
            c.name,
            if c.type_text.is_empty() {
                c.base_type.clone()
            } else {
                c.type_text.clone()
            }
        );
        if c.primary_key {
            def.push_str(" PRIMARY KEY");
        }
        if c.auto_increment {
            def.push_str(" AUTOINCREMENT");
        }
        if c.not_null {
            def.push_str(" NOT NULL");
        }
        if c.unique {
            def.push_str(" UNIQUE");
        }
        if let Some(d) = &c.default_value {
            def.push_str(&format!(" DEFAULT {d}"));
        }
        if let Some((t, col)) = &c.references {
            match col {
                Some(col) => def.push_str(&format!(" REFERENCES {t}({col})")),
                None => def.push_str(&format!(" REFERENCES {t}")),
            }
        }
        def
    }

    fn render_table(t: &SqlTable) -> String {
        let mut defs: Vec<String> = t.columns.iter().map(render_column).collect();
        for c in &t.constraints {
            match c.kind {
                "primary-key" => defs.push(format!("  PRIMARY KEY ({})", c.columns.join(", "))),
                "unique" => defs.push(format!("  UNIQUE ({})", c.columns.join(", "))),
                "foreign-key" => {
                    if let Some((rt, rc)) = &c.references {
                        defs.push(format!(
                            "  FOREIGN KEY ({}) REFERENCES {rt}({})",
                            c.columns.join(", "),
                            rc.join(", ")
                        ));
                    }
                }
                _ => {}
            }
        }
        format!("CREATE TABLE {} (\n{}\n);", t.name, defs.join(",\n"))
    }

    fn render_index(i: &SqlIndex) -> String {
        format!(
            "CREATE {}INDEX {}\n  ON {} ({});",
            if i.unique { "UNIQUE " } else { "" },
            i.name,
            i.table,
            i.columns.join(", ")
        )
    }

    #[allow(dead_code)]
    fn unused(_: &Path) {}
}

pub mod react_forms {
    use super::*;
    use crate::graph::{NodeKind, Standard};

    pub struct ReactFormsGenerator;

    impl Generator for ReactFormsGenerator {
        fn id(&self) -> &'static str {
            "react-forms"
        }
        fn version(&self) -> &'static str {
            "1"
        }

        fn generate(&self, ctx: &GenerateContext<'_>) -> Result<Vec<GeneratedFile>> {
            let frontend = ctx.loaded.manifest.targets.frontend.clone();
            if let Some(f) = &frontend {
                if let Some(fw) = &f.framework {
                    if fw != "react" {
                        return Ok(vec![]);
                    }
                }
            }
            let out_dir = frontend
                .and_then(|f| f.out)
                .unwrap_or_else(|| "generated/frontend".into());

            let mut files = Vec::new();
            for form in ctx.graph.nodes_by_kind(NodeKind::UiForm) {
                let bound = form
                    .data
                    .get("boundSchemaId")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .to_string();
                let Some(schema_node) =
                    ctx.graph
                        .nodes_by_kind(NodeKind::Type)
                        .into_iter()
                        .find(|n| {
                            n.standard == Standard::JsonSchema
                                && n.data.get("$id").and_then(|v| v.as_str())
                                    == Some(bound.as_str())
                        })
                else {
                    continue; // doctor 已报错
                };
                let entity_uri = schema_node
                    .data
                    .get("entityUri")
                    .and_then(|v| v.as_str())
                    .map(String::from);
                if !entity_in_scope(ctx, entity_uri.as_deref()) {
                    continue;
                }

                let id = bound.rsplit('/').next().unwrap_or("Entity");
                let entity_name = crate::identity::to_pascal_case(id);
                let component = format!("{entity_name}Form");
                let props: Vec<serde_json::Value> = schema_node
                    .data
                    .get("properties")
                    .and_then(|v| v.as_array())
                    .cloned()
                    .unwrap_or_default();
                let required: Vec<String> = schema_node
                    .data
                    .get("required")
                    .and_then(|v| v.as_array())
                    .map(|a| {
                        a.iter()
                            .filter_map(|x| x.as_str().map(String::from))
                            .collect()
                    })
                    .unwrap_or_default();
                let controls: Vec<serde_json::Value> = form
                    .data
                    .get("controls")
                    .and_then(|v| v.as_array())
                    .cloned()
                    .unwrap_or_default();

                let content = render_form(&component, &entity_name, &controls, &props, &required);
                files.push(GeneratedFile {
                    path: format!("{out_dir}/{component}.tsx"),
                    content,
                    generator: self.id().into(),
                });
            }
            Ok(files)
        }
    }

    fn humanize(name: &str) -> String {
        let mut out = String::new();
        let mut prev_sep = true;
        let chars: Vec<char> = name.chars().collect();
        for (i, c) in chars.iter().enumerate() {
            if *c == '_' || *c == '-' || *c == ' ' {
                prev_sep = true;
                continue;
            }
            if prev_sep {
                out.extend(c.to_uppercase());
                prev_sep = false;
                continue;
            }
            if c.is_ascii_uppercase() && i > 0 && chars[i - 1].is_ascii_lowercase() {
                out.push(' ');
            }
            out.push(*c);
        }
        out
    }

    fn escape_jsx(s: &str) -> String {
        s.chars()
            .map(|c| match c {
                '{' | '}' | '<' | '>' => format!("{{'{c}'}}"),
                _ => c.to_string(),
            })
            .collect()
    }

    fn render_field(prop: &serde_json::Value, label: &str, required: bool) -> String {
        let name = prop
            .get("name")
            .and_then(|v| v.as_str())
            .unwrap_or_default();
        let req_attr = if required { " required" } else { "" };
        let star = if required { " *" } else { "" };

        if let Some(enum_vals) = prop.get("enum").and_then(|v| v.as_array()) {
            if !enum_vals.is_empty() {
                let options: Vec<String> = enum_vals
                    .iter()
                    .map(|v| {
                        format!(
                            "          <option value={{{}}}>{v}</option>",
                            serde_json::to_string(v).unwrap_or_default()
                        )
                    })
                    .collect();
                return format!(
                    "      <label className=\"forma-form__field\">\n        <span>{label}{star}</span>\n        <select\n          value={{(value.{name} as string) ?? ''}}\n          onChange={{(e) => set('{name}', e.target.value as never)}}\n{req_attr}\n        >\n          <option value=\"\" disabled>—</option>\n{}\n        </select>\n      </label>",
                    options.join("\n")
                );
            }
        }

        let t = prop
            .get("type")
            .and_then(|v| v.as_str())
            .unwrap_or("string");
        match t {
            "boolean" => format!(
                "      <label className=\"forma-form__field forma-form__field--check\">\n        <input\n          type=\"checkbox\"\n          checked={{Boolean(value.{name})}}\n          onChange={{(e) => set('{name}', e.target.checked as never)}}\n        />\n        <span>{label}</span>\n      </label>"
            ),
            "number" | "integer" => {
                let step = if t == "integer" { "1" } else { "any" };
                format!(
                    "      <label className=\"forma-form__field\">\n        <span>{label}{star}</span>\n        <input\n          type=\"number\"\n          step=\"{step}\"\n          value={{(value.{name} as number) ?? ''}}\n          onChange={{(e) => set('{name}', e.target.value === '' ? (undefined as never) : Number(e.target.value) as never)}}\n{req_attr}\n        />\n      </label>"
                )
            }
            _ => {
                let format = prop.get("format").and_then(|v| v.as_str()).unwrap_or("");
                let input_type = match format {
                    "date-time" => "datetime-local",
                    "date" => "date",
                    _ => "text",
                };
                format!(
                    "      <label className=\"forma-form__field\">\n        <span>{label}{star}</span>\n        <input\n          type=\"{input_type}\"\n          value={{(value.{name} as string) ?? ''}}\n          onChange={{(e) => set('{name}', e.target.value as never)}}\n{req_attr}\n        />\n      </label>"
                )
            }
        }
    }

    fn render_form(
        component: &str,
        entity_name: &str,
        controls: &[serde_json::Value],
        props: &[serde_json::Value],
        required: &[String],
    ) -> String {
        let mut fields: Vec<String> = Vec::new();
        let mut covered: Vec<String> = Vec::new();

        for control in controls {
            let name = control
                .get("id")
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .to_string();
            let Some(prop) = props
                .iter()
                .find(|p| p.get("name").and_then(|v| v.as_str()) == Some(name.as_str()))
            else {
                continue;
            };
            covered.push(name.clone());
            let label = control
                .get("label")
                .and_then(|v| v.as_str())
                .map(String::from)
                .unwrap_or_else(|| humanize(&name));
            let is_required = required.iter().any(|r| r == &name);
            fields.push(render_field(prop, &escape_jsx(&label), is_required));
        }
        for prop in props {
            let name = prop
                .get("name")
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .to_string();
            if covered.contains(&name) {
                continue;
            }
            let is_required = required.iter().any(|r| r == &name);
            fields.push(render_field(
                prop,
                &escape_jsx(&humanize(&name)),
                is_required,
            ));
        }

        format!(
            "{}\nimport {{ useState }} from 'react';\nimport type {{ {entity_name} }} from '../../generated/types/types.js';\n\n/** {entity_name} 表单 — 布局来自 JSON Forms UI Schema */\nexport type {entity_name}Draft = Partial<{entity_name}>;\n\nexport interface {component}Props {{\n  initialValue?: {entity_name}Draft;\n  onSubmit?: (value: {entity_name}Draft) => void;\n  submitting?: boolean;\n  submitError?: string | null;\n}}\n\nexport function {component}({{ initialValue, onSubmit, submitting, submitError }}: {component}Props) {{\n  const [value, setValue] = useState<{entity_name}Draft>(initialValue ?? {{}});\n\n  const set = <K extends keyof {entity_name}Draft>(key: K, v: {entity_name}Draft[K]) =>\n    setValue((prev) => ({{ ...prev, [key]: v }}));\n\n  return (\n    <form\n      className=\"forma-form\"\n      onSubmit={{(e) => {{\n        e.preventDefault();\n        onSubmit?.(value);\n      }}}}\n    >\n{}\n      {{submitError ? <p className=\"forma-form__error\" role=\"alert\">{{submitError}}</p> : null}}\n      <button type=\"submit\" disabled={{submitting}}>\n        {{submitting ? 'Saving…' : 'Save'}}\n      </button>\n    </form>\n  );\n}}\n",
            generated_header(&format!("{}@{}", "react-forms", "1")),
            fields.join("\n")
        )
    }
}
